;
; timer.asm — «секундомер растра» на КР580ВИ53, канал 2 (порт 09h).
;
; Идея (как в exolon, см. roms/redesign/exolon/reports/Summary.md §14):
; прерывание VBlank (RST 7) совпадает с концом сканирования лучом видимой
; части. Если на каждом VBlank перезапускать счётчик канала 2 значением,
; равным ровно одному кадру, счётчик становится «секундомером кадра»: он
; линейно убывает вместе с лучом, и по его значению всегда понятно, дошёл ли
; луч до опасной зоны или ещё нет.
;
; Числа сняты с модели vector-debugger (beam_state):
;   frame_v_cycles=239616, line_v_cycles=768, frame_lines=312;
;   ВИ53 тактирован 1.5 МГц = 12 МГц / 8  =>  96 тиков таймера на строку;
;   один кадр = 312*96 = 29952 = 0x7500.
; Период 0x7500 при такте 1.5 МГц в точности равен частоте кадра, поэтому
; счётчик, перезапущенный в VBlank, остаётся в фазе с лучом весь кадр.
;
; Порт 09h = канал 2 = «3-й канал» (нумерация Вектора: 0=0Bh,1=0Ah,2=09h).
; Звуковой движок демки (sfx_mario.c) занимает только каналы 0 и 1, так что
; канал 2 полностью свободен под этот таймер и не конфликтует со звуком.
;
; Функции (8080, SECTION code_clib):
;   mario_timer_reload — перезапустить счётчик канала 2 на полный кадр
;                        (CW mode0 lsb+msb, OUT 09h lo, OUT 09h hi). Зовётся
;                        из кадрового ISR на каждом VBlank.
;   mario_timer_read   — защёлкнуть канал 2 (CW latch RL=00) и вычитать 16-
;                        битный остаток: сначала младший байт, потом старший.
;                        Возврат в HL (C: unsigned int). Опрос луча в main.
;
; ПОЧЕМУ РЕЖИМ 0, А НЕ 3. Режим 3 — это генератор меандра (им музыка на
; ВИ53 и делает тон: см. vi53.c, vi53_m3[]). Канал 2 выведен на динамик,
; поэтому меандр на 0x7500 (~25 Гц) = непрерывный гул/шум. Кроме того в
; режиме 3 счётчик убывает на 2 за такт и САМ перезагружается на нуле —
; т.е. примерно на середине кадра обнуляется и стартует заново, «elapsed»
; переполняется — и гейт рисования пропускает запись, когда луч УЖЕ внутри
; полосы Марио (мерцание). Режим 0 — одноразовый счёт: OUT=0 (тишина),
; убывание на 1 за такт, без авто-перезагрузки; досчитывает до 0 ровно к
; следующему VBlank, где мы перезапускаем его сами. Монотонно и беззвучно.
;
;

        SECTION code_clib
        PUBLIC  _mario_timer_reload
        PUBLIC  _mario_timer_read

TIMER_FULL EQU 07500h           ; 29952 = один кадр при 96 тиках/строку
CW_CH2_M0  EQU 0B0h             ; канал2, lsb+msb, режим0 (OUT=0 тишина, счёт -1)
CW_CH2_LATCH EQU 080h           ; канал2, RL=00 — команда защёлки для чтения

; ---------------------------------------------------------------
; void mario_timer_reload(void)
;   Перезапуск счётчика канала 2 на полный кадр в РЕЖИМЕ 0 (молчит,
;   убывает на 1, без авто-перезагрузки). Из ISR: прерывания уже
;   замаскированы, повторный ei открыл бы реентерабельный вход, поэтому
;   просто пишем порты (каждый OUT атомарен).
; ---------------------------------------------------------------
_mario_timer_reload:
        mvi     a,CW_CH2_M0
        out     08h                     ; управляющее слово: канал2, режим0
        mvi     a,000h                  ; 0x7500: младший байт 00h
        out     09h
        mvi     a,075h                  ; старший байт 75h
        out     09h                     ; загрузка => старт отсчёта кадра
        ret

; ---------------------------------------------------------------
; unsigned int mario_timer_read(void)   -> HL
;   Защелкнуть и прочитать 16-битный остаток счётчика канала 2.
;   Значение = «тиков до конца кадра»; ближе к TIMER_FULL => луч выше
;   (только что после VBlank), меньше => луч ниже.
; ---------------------------------------------------------------
_mario_timer_read:
        mvi     a,CW_CH2_LATCH
        out     08h                     ; защёлка канала2 (снимок счётчика)
        in      09h                     ; младший байт
        mov     l,a
        in      09h                     ; старший байт
        mov     h,a
        ret
