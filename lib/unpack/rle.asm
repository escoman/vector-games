;
; graphrle.asm — быстрая RLE-распаковка картинки в заданную точку
; экрана (Вектор-06Ц).
;
; Заменяет C-функцию graph_rle_expand (graph.c).
;
;   void graph_rle_expand(const unsigned char *src,
;                         unsigned char x, unsigned char y);
;
; Поток (готовит utils/bmp2inc.py): заголовок из двух байт —
; ширина в 8-пиксельных блоках и высота (0 означает 256), затем пары
; (количество, байт), количество 1-255, терминатор — количество 0.
; Порядок байт прямоугольника картинки: плоскости с весами цвета
; 8, 4, 2, 1; в плоскости — блоки слева направо; в блоке — строки
; сверху вниз. Серия RLE может пересекать границы блоков и плоскостей.
;
; Координаты (x, y) — левый верхний угол картинки. Ограничения:
;   - x кратно 8 (иначе пиксели не совпадают с границами байтов
;     видеопамяти); некорректный x даёт сдвиг картинки;
;   - картинка должна целиком помещаться в экран 256x256
;     (x + ширина <= 256, y + высота <= 256) — не проверяется.
; Область вне картинки не трогается.
;
; Адресация VRAM: блок = 256 байт = столбец 8 пикселей (номер x/8),
; байт со смещением i в блоке хранит строку y = 255 - i (Y=0 — верх
; экрана), т.е. строки идут сверху вниз с УМЕНЬШЕНИЕМ адреса. Для
; верхней строки картинки в точке y смещение = 255 - y; дальше адрес
; уменьшается. Плоскости по 8 КБ: вес 8 — 0x8000, вес 4 — 0xA000,
; вес 2 — 0xC000, вес 1 — 0xE000. Каждые «высота» байт начинается
; следующий блок (h++), после последней колонки плоскости — следующая
; плоскость.
;
; Регистры: DE — поток, HL — видеоадрес, B — остаток серии RLE,
; C — остаток строк в текущем блоке (0 означает 256).
;
; Соглашение вызова z88dk classic — по выводу компилятора (zcc -S):
; y на sp+2, x на sp+4, src на sp+6 (16-битные слоты). Стек чистит
; вызывающий, поэтому функция НЕ трогает SP (никаких push/pop) и
; просто делает ret.
;
; Только 8080-инструкции.
;

        SECTION code_clib
        PUBLIC  _graph_rle_expand

_graph_rle_expand:
        ; --- y (sp+2) -> смещение верхней строки в блоке: 255 - y ---
        ld      hl, 2
        add     hl, sp
        ld      a, (hl)
        cpl                     ; 255 - y = ~y (по модулю 256)
        ld      (rle_i_top), a
        ; --- x (sp+4) -> номер первого блока = x/8 ---
        inc     hl
        inc     hl
        ld      a, (hl)
        rrca
        rrca
        rrca
        ld      (rle_xb0), a
        ; --- src (sp+6) -> DE ---
        inc     hl
        inc     hl
        ld      e, (hl)
        inc     hl
        ld      d, (hl)
        ; --- заголовок потока: ширина в блоках, высота ---
        ld      a, (de)
        inc     de
        ld      (rle_cols_max), a
        ld      (rle_brem), a   ; блоков осталось до конца плоскости
        ; добавка к h при переходе на следующую плоскость:
        ; 0x21 - ширина (замена inc h после последней колонки)
        ld      a, 0x21
        ld      hl, rle_cols_max
        sub     (hl)
        ld      (rle_pdelta), a
        ; --- высота -> C (0 означает 256) ---
        ld      a, (de)
        inc     de
        ld      (rle_rows), a
        ld      c, a
        ; --- HL = адрес верхней строки первого блока:
        ; 0x8000 + (xb0 * 256) + i_top ---
        ld      a, (rle_xb0)
        add     a, 0x80
        ld      h, a
        ld      a, (rle_i_top)
        ld      l, a

rle_loop:
        ld      a, (de)         ; количество
        inc     de
        or      a
        ret     z               ; терминатор — конец потока
        ld      b, a            ; длина серии
        ld      a, (de)         ; байт серии
        inc     de
        ld      (rle_val), a
rle_run:
        ld      a, (rle_val)
        ld      (hl), a
        dec     l               ; следующая строка блока (адрес уменьшается)
        dec     c
        jp      nz, rle_chk     ; блок ещё не заполнен
        ; записано «высота» байт — граница блока
        ld      a, (rle_brem)
        dec     a
        ld      (rle_brem), a
        jp      nz, rle_nb      ; плоскость ещё не кончилась
        ; плоскость заполнена: первая колонка следующей плоскости
        ld      a, (rle_cols_max)
        ld      (rle_brem), a
        ld      a, h
        ld      hl, rle_pdelta
        add     a, (hl)
        ld      h, a
        jp      rle_fl
rle_nb:
        inc     h               ; следующий блок (колонка)
rle_fl:
        ld      a, (rle_rows)   ; восстановить счётчики блока
        ld      c, a
        ld      a, (rle_i_top)
        ld      l, a            ; снова на верхнюю строку
rle_chk:
        dec     b
        jp      nz, rle_run     ; серия продолжается
        jp      rle_loop

        ; --- рабочие переменные ---
rle_i_top:      defb    0       ; смещение верхней строки в блоке (255-y)
rle_xb0:        defb    0       ; номер первого блока (x/8)
rle_cols_max:   defb    0       ; ширина картинки в блоках
rle_brem:       defb    0       ; блоков осталось до конца плоскости
rle_pdelta:     defb    0       ; добавка к h при смене плоскости
rle_rows:       defb    0       ; высота картинки (0 = 256)
rle_val:        defb    0       ; текущий байт серии
