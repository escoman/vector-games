; Функция: func_render_all
; Адрес: 0x1BF0
; Размер: ~52 байта
; Описание: Единый покадровый рендер (Step 0). Делает ОДИН чанк скана флипа —
;           128 ячеек из data_text_buffer начиная с var_scan_ptr. Полный оборот
;           скана = 768/128 = 6 кадров -> 2 оборота за 12-кадровый тик, т.е.
;           частота 2 flip/тик сохранена (как в исходном inline-скане
;           func_game_update: 2 вызова game_update * полный скан = 2 оборота).
;           После последней ячейки курсор возвращается к началу буфера (wrap).
;           Флипаемые коды задаются O(1) таблицей data_flip_tab (256 B,
;           ALIGN 256 перед меткой -> мл. байт адреса 00). Индекс = код
;           клетки, значение = код-замена, 0 = флипа нет. Чтение таблицы —
;           XCHG-идиомом 8080 (LDAX D НЕ индексируется, A=M[DE] без смещения):
;           HL=клетка -> XCHG -> MOV L,A (код клетки становится мл. байтом
;           адреса таблицы) -> MOV A,M -> XCHG (HL=клетка возвращён, DE=
;           таблица+код, старший байт H не меняется). Таблица покрывает огонь 75h<->FEh и
;           выход 16h..19h<->12h..15h (мигание выхода теперь идёт сканом,
;           отдельная фаза 4 в func_game_update удалена).
; Прозрачность: трогает A/B/C/D/H/L/F. Вызывается из lbl_main_game_loop над
;              PUSH B, поэтому сохранение не нужно. В func_draw_char_at_hl
;              PUSH/POP H уже встроен — HL остаётся корректным между ячейками;
;              DE (адрес таблицы) прозрачен для func_render_glyph (PUSH/POP D),
;              поэтому после CALL старший байт DE по-прежнему = H таблицы.

func_render_all:
    LHLD var_scan_ptr           ; HL = курсор на начало кадра (указатель клетки)
    LXI D, data_flip_tab        ; DE = таблица флипов (выровнена, H = старший байт)
    MVI B, 080h                 ; 128 ячеек за проход
loc_ra_cell:
    MOV A, M                    ; A = код клетки
    XCHG                        ; DE = клетка, HL = таблица
    MOV L, A                    ; HL = таблица + код клетки (мл. байт = сам код)
    MOV A, M                    ; A = код-замена (0 — флипа нет)
    XCHG                        ; HL = клетка восстановлен, DE = таблица+код
    ORA A
    JZ loc_ra_next
    CALL func_draw_char_at_hl   ; CMP M/RZ + MOV M,A + глиф (флипаемых пар нет
                                ;   в HUD/текстах — RZ-путь не срабатывает)
loc_ra_next:
    INX H                       ; следующая клетка
    DCR B
    JNZ loc_ra_cell
    SHLD var_scan_ptr           ; сохранить курсор
    ; wrap по data_text_buffer+0x300 (D больше не нужен — переиспользуем DE)
    LXI D, data_text_buffer+300h
    MOV A, L
    SUB E
    MOV A, H
    SBB D
    JNZ loc_ra_done
    LXI H, data_text_buffer
    SHLD var_scan_ptr
loc_ra_done:
    RET
