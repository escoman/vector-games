; RAM-символы RANDOM PUTUP (overlay-дополнение, эмитится вслед за var_ram_symbols.asm).
; Базовый файл putup/asm/var_ram_symbols.asm не правится — новые адреса только здесь.
;
; Генератор (func_gen_level) пишет КАРТЫ И ОПИСАТЕЛИ ПРЯМО В СУЩЕСТВУЮЩИЕ массивы
; data_level_maps / data_level_params (они в ОЗУ — образ грузится на 0x0100),
; поэтому отдельные RAM-буферы карт НЕ нужны. Здесь — только scratch генератора
; для шагов рандомизации (fire/предметы/случайные выход и враги через func_prng);
; каркас Stage 2a (периметр + фикс. описатель) их пока не использует.
;
; Свободная зона: var-блок базы занят до 0x6A85 (var_hero_trample); далее зазор
; 0x6A86..0x6BFF (~1.4 КБ) свободен до data_hero_shift_cache@0x6C00.

; --- Scratch генератора (0x6A86..) -------------------------------------------
rgl_level: EQU 6A86h   ; байт: копия var_level (масштабирование сложности)
rgl_tmp:   EQU 6A87h   ; байт: временное значение (код тайла для предмета)
rgl_cnt:   EQU 6A88h   ; байт: счётчик проходов/попыток
rgl_row:   EQU 6A89h   ; байт: текущая строка карты (0..10)
rgl_col:   EQU 6A8Ah   ; байт: текущая колонка карты (0..15)
rgl_run:   EQU 6A8Bh   ; байт: длина сегмента / число ключей B (fire/wall-участки)
rgl_off:   EQU 6A8Ch   ; байт: внутренний счётчик цикла (scatter fire/fruit/egg)

; --- Состояние поуровневого randomizer-цикла (Stage 2b) ---------------------
rgl_mapbase:  EQU 6A8Dh  ; 2 байта: база текущей КАРТЫ (LHLD/SHLD), +176/итер
rgl_descbase: EQU 6A8Fh  ; 2 байта: база текущего ОПИСАТЕЛЯ, +8/итер
rgl_s1:  EQU 6A92h   ; байт: state врага-1 (1/2 — горизонтальный)
rgl_x1:  EQU 6A93h   ; байт: char-X врага-1 (=2*col)
rgl_y1:  EQU 6A94h   ; байт: char-Y врага-1 (=2*row)
rgl_s2:  EQU 6A95h   ; байт: state врага-2
rgl_x2:  EQU 6A96h   ; байт: char-X врага-2
rgl_y2:  EQU 6A97h   ; байт: char-Y врага-2
