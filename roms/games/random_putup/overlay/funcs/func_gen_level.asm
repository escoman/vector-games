; ============================================================================
; Функция: func_gen_level   (RANDOM PUTUP, Stage 2 — рантайм-генератор уровней)
; Вызов:   из lbl_title_key_poll на старте игры (после func_music_start_track,
;          перед JMP func_level_loader) — т.е. «по нажатию пробела», ОДИН раз.
;
; Идея (минимальные правки исходной игры): НЕ вводить новые RAM-буферы, а
;   ЗАПОЛНИТЬ ПЕРИМЕТРОМ/ПУСТОТОЙ уже существующие массивы прямо в ОЗУ:
;     * data_level_maps — 15 карт по 176 Б (row-major 16 колонок x 11 рядов),
;       карта N лежит по data_level_maps + N*0xB0 (так же их читает loader);
;     * data_level_params — 16 записей по 8 Б (описатель уровня: exit X/Y +
;       2 сущности state/X/Y); заполняем записи 1..15.
;   Образ грузится на 0x0100 в ОЗУ, поэтому обе таблицы перезаписываемы;
;   func_level_loader остаётся НЕТРОНУТЫМ и читает то, что написал генератор.
;
; Шаг 1–3 (каркас, без рандома): каждая карта — периметр стеной (тайл 0x02),
;   интерьер пустой/проходимый (тайл 0x01; байт карты = ИНДЕКС в data_tile_graphics,
;   0x01 — запись «4 пробела 0x20»); все описатели = шаблон уровня 1.
;
; Счётчики внешних циклов — в RAM (rgl_cnt): стек 8080 умеет только 16-битные
;   пары (PUSH/POP B|D|H|PSW), одиночные регистры (C/E) push-ить нельзя.
; Регистры не сохраняются (вызывающий их пересоздаёт). ШАГ 2: сюда же (по месту
;   карт) позже добавятся fire-сегменты/предметы/рандомный выход-враги через
;   func_prng — scratch-байты объявлены в rand_ram_symbols.asm.
; ============================================================================

func_gen_level:
    ; ---------------------------------------------------------------------
    ; 1) 15 карт: залить всё тайлом 0x01, затем периметр тайлом 0x02.
    ;    HL — курсор по tableau карт (176 Б подряд); rgl_cnt — счётчик карт.
    ; ---------------------------------------------------------------------
    LXI H, data_level_maps
    MVI A, 15
    STA rgl_cnt                         ; карт (data_level_01..15)
rgl_map_loop:
    PUSH H                              ; база текущей карты
    ; --- memset 176 -> 0x01 (пустая/проходимая клетка) ---
    MVI B, 176
rgl_mem_lp:
    MVI M, 01h
    INX H
    DCR B
    JNZ rgl_mem_lp                      ; HL = база + 176
    POP H                               ; HL = база карты (row0,col0)
    ; --- row0: 16 стен ---
    MVI B, 16
rgl_r0:
    MVI M, 02h
    INX H
    DCR B
    JNZ rgl_r0                          ; HL = row1,col0
    ; --- rows 1..9: col0 и col15 стены (interior остаётся 0x01) ---
    MVI E, 9                            ; E — счётчик рядов 1..9 (to15 его не трогает)
rgl_rn:
    MVI M, 02h                          ; col0
    MVI B, 15
rgl_to15:
    INX H
    DCR B
    JNZ rgl_to15                        ; HL = col15
    MVI M, 02h                          ; col15
    INX H                               ; HL = col0 следующего ряда
    DCR E
    JNZ rgl_rn                          ; HL = row10,col0
    ; --- row10: 16 стен ---
    MVI B, 16
rgl_r10:
    MVI M, 02h
    INX H
    DCR B
    JNZ rgl_r10                         ; HL = база + 176 = следующая карта
    LDA rgl_cnt
    DCR A
    STA rgl_cnt
    JNZ rgl_map_loop

    ; ---------------------------------------------------------------------
    ; 2) 15 описателей (записи 1..15): шаблон уровня 1.
    ; ---------------------------------------------------------------------
    LXI H, data_level_params+8          ; record 1 (record 0 = уровень 0, не исп.)
    MVI A, 15
    STA rgl_cnt                         ; записей
rgl_desc_loop:
    PUSH H                              ; база записи (HL будет двигать курсор)
    LXI D, rgl_desc                     ; источник — 8-байтный шаблон
    MVI B, 8
rgl_desc_cp:
    LDAX D                              ; A = (DE)
    MOV M, A                            ; (HL) = A
    INX D
    INX H                               ; HL = следующая копия
    DCR B
    JNZ rgl_desc_cp                     ; HL = база записи + 8 (следующая запись)
    POP D                               ; снять сохранённую базу (в DE, безвредно)
    LDA rgl_cnt
    DCR A
    STA rgl_cnt
    JNZ rgl_desc_loop
    RET

; --- шаблон описателя = level 1: exit(X=14h,Y=10h); ent1(1,X=0Ah,Y=06h); ent2(1,X=0Ah,Y=0Ch)
rgl_desc:
    DEFB 014h, 010h, 001h, 00Ah, 006h, 001h, 00Ah, 00Ch
