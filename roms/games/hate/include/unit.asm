;
; unit.asm — юнит игрока: самолётик и танк.
;
; Самолётик летит (высота ← ↑/↓), танк по земле — оба маневрируют влево/вправо.
; Здесь только юнит: движение, отрисовка, стирание. Стрельба, взлёт/посадка и
; смена техники — следующими шагами.
;
; КУДА МАНЕВРИРОВАТЬ. Рельеф набегает по диагонали: столбец x держит ленту
; со смещения 4x, поэтому одна и та же полоса земли (дорога, хребет) идёт по
; экрану «вправо и вверх» — плюс 4 строки на столбец. Движение ВДОЛЬ рельефа
; — это +4 строки на столбец; поперёк — минус 4. Оригинальная проекция (см.
; ENGINE.MD 4.2) даёт объекту столбец [11] = (дистанция - боковое) >> 3 и
; смещение [10] = боковое + константа, то есть боковое при движении вправо
; уводит объект вниз. Наш юнит повторяет это: u_y = U_BASE - 4*u_col + u_alt.
; Отсюда и физика картинки: у левого края юнит над горизонтом (дальняя полоса),
; к правому краю снижается к самой дороге — там и садится.
;
; КУДА РИСУЕТ. В СВОБОДНУЮ плоскость буфера (TZ §3.3): у A это 0xC000,
; у B — 0x8000, логический цвет 2 (lv_pal4[2] — белый). Рельеф занимает
; другой вес (0xE000 / 0xA000), поэтому блиттер поля юнита не касается и
; стирать под ним рельеф не нужно: картинка юнита — каркас, рельеф сквозь
; него виден. Там, где пиксели совпадут, индекс станет 3 (lv_pal4[3]).
;
; ПОЧЕМУ КАЖДЫЙ КАДР, А НЕ НА ТИКЕ. Полоса поля перерисовывается 4 кадра,
; но юнит живёт в отдельной плоскости: стёрли прошлый прямоугольник,
; нарисовали новый — и всё это в окне гашения сразу после VBlank, пока луч
; ещё вверху, а юнит — в нижней половине кадра. Поэтому юнит двигается
; 50 Гц, при этом поле скроллится как раньше (2 пикселя за кадр).
;
; ПРЯМОУГОЛЬНИК НА КАЖДЫЙ БУФЕР. После свопа новый front держит кадр
; четырёхкадровой давности — там юнит стоит на старом месте, и его надо
; стереть до того, как луч дойдёт до этих строк. Поэтому координаты
; последней отрисовки помнятся отдельно для буфера A и буфера B.
;
; Спрайт — 4 фазы по 2 пикселя сдвига (include/unit.inc): столбцов 5
; (32 пикселя картинки + три сдвига), строк 20. За кадр рисуется только 5
; столбцов, то есть ~100 байт, и только когда положение изменилось.
;
; Только 8080: без LDIR/LDDR/JR/DJNZ/IX/IY и префиксов CB/DD/ED/FD.

        SECTION code_clib
        PUBLIC  _unit_start
        PUBLIC  _unit_frame

        EXTERN  _gfx_dblbuf_front
        EXTERN  _kbd_rows

U_XMAX  EQU     16 * 8          ; правый край юнита: дальше — уже под дорогой
U_STEP  EQU     2               ; пикселей за кадр (фаза сдвига = 2 пикселя)
U_ALTMAX EQU    90              ; потолок набора высоты, строк
U_BASE  EQU     130             ; низ юнита у левого края при высоте 0

; ---------------------------------------------------------------------------
; void unit_start(void)
;
; Поставить юнит на полосу: у левого края (дальняя полоса), техника —
; самолётик. Дальше по плану взлёт с полосы, так что стартует он сверху
; и вниз к полосе пойдёт сам.
; Перед этим обнулить плоскости юнита в обоих буферах: RAM при включении
; (и при загрузке ROM в эмуляторе) не обнуляется, а заставка до миссии
; рисовала во все четыре плоскости — её осадки иначе горели бы в поле красным
; (индекс 3 = рельеф + пиксель юнита).
; ---------------------------------------------------------------------------
_unit_start:
        call    u_clear
        xra     a                 ; u_xpix = 0: крайнее левое положение
        sta     u_xpix
        sta     u_alt
        sta     u_kind
        sta     u_rv
        sta     u_rv + 1
        lxi     h, un_plane
        shld    u_spr
        ret

; Обнулить свободные плоскости: у A это C000, у B — 8000 (по 8 КБ).
u_clear:
        lxi     d, 0C000h
        call    u_zero
        lxi     d, 08000h
u_zero:
        mvi     c, 32               ; 32 страницы по 256 байт
        xra     a
uz_page:
        mvi     b, 0                ; 256 за проход, счётчик в B
uz_byte:
        stax    d
        inx     d
        dcr     b
        jnz     uz_byte
        dcr     c
        jnz     uz_page
        ret

; ---------------------------------------------------------------------------
; unsigned char unit_frame(void)
;
; Кадр юнита: ввод, физика, стереть старый прямоугольник, нарисовать новый.
; Вызывается сразу после v06_wait_frame(), когда луч в гашении: и опрос
; матрицы, и запись в VRAM попадают в окно (BEAM_TIMING.MD §8).
;
; Возврат: L = 1 — юнит стрелял (пока не используется).
; ---------------------------------------------------------------------------
_unit_frame:
        call    _gfx_dblbuf_front
        sta     u_buf
        ora     a                   ; A = 0 -> front это A (плоскость C000)
        mvi     a, 0C0h
        jz      uf_plane
        mvi     a, 80h              ; front это B (плоскость 8000)
uf_plane:
        sta     u_plane

        call    u_keys              ; u_xpix / u_alt по клавишам
        call    u_rect              ; рабочий прямоугольник = rect[u_buf]
        call    u_pos               ; u_col / u_ph / u_y

        ; --- ничего не делать, если в этом буфере уже стоит та же картинка
        lda     u_wv
        ora     a
        jz      uf_erase
        lda     u_wcol
        mov     b, a
        lda     u_col
        cmp     b
        jnz     uf_erase
        lda     u_wy
        mov     b, a
        lda     u_y
        cmp     b
        jnz     uf_erase
        lda     u_wph
        mov     b, a
        lda     u_ph
        cmp     b
        jnz     uf_erase
        jmp     uf_save

uf_erase: ; --- стереть прошлое положение в этом буфере
        lda     u_wv
        ora     a
        jz      uf_new
        mvi     a, 1
        sta     u_mode              ; 1 — писать нули
        lda     u_wcol
        sta     u_col
        lda     u_wy
        sta     u_y
        lda     u_wph
        sta     u_ph
        call    u_put

uf_new: ; --- нарисовать на новом месте
        call    u_pos
        xra     a
        sta     u_mode              ; 0 — писать спрайт
        call    u_put
        mvi     a, 1
        sta     u_wv

uf_save:
        call    u_rect_back         ; rect[u_buf] = то, что сейчас нарисовано
        xra     a
        mov     l, a
        ret

; ---------------------------------------------------------------------------
; u_keys: чтение матрицы (строки уже сняты kbd_scan в главном цикле).
;
; Стрелки — строка 0: бит4 ←, бит5 ↑, бит6 →, бит7 ↓.
; Танк высоту не меняет: ↑/↓ у него ничего не делают.
; ---------------------------------------------------------------------------
u_keys:
        lda     _kbd_rows
        mov     b, a
        sta     u_keys_r

        ; --- влево: бит 4
        mvi     a, 10h
        ana     b
        jz      uk_right
        lda     u_xpix
        sui     U_STEP
        jnc     uk_lset
        xra     a
uk_lset:
        sta     u_xpix

uk_right:
        lda     u_keys_r
        mov     b, a
        mvi     a, 40h
        ana     b
        jz      uk_up
        lda     u_xpix
        adi     U_STEP
        cpi     U_XMAX + 1
        jc      uk_rset
        mvi     a, U_XMAX
uk_rset:
        sta     u_xpix

uk_up:
        lda     u_kind              ; танк — только маневрирует
        ora     a
        jnz     uk_done
        lda     u_keys_r
        mov     b, a
        mvi     a, 20h              ; ↑ — выше
        ana     b
        jz      uk_down
        lda     u_alt
        cpi     U_ALTMAX
        jnc     uk_down
        inr     a
        sta     u_alt

uk_down:
        lda     u_keys_r
        mov     b, a
        mvi     a, 80h              ; ↓ — ниже
        ana     b
        jz      uk_done
        lda     u_alt
        ora     a
        jz      uk_done
        dcr     a
        sta     u_alt
uk_done:
        ret

; ---------------------------------------------------------------------------
; u_pos: пиксель и высота -> столбец окна, фаза сдвига и строка низа.
;
;   u_col  = u_xpix >> 3          (столбец, 0..16)
;   u_ph   = (u_xpix >> 1) & 3    (сдвиг вправо на 2*фаза пикселей)
;   u_y    = U_BASE - 4*u_col + u_alt
;          — поперёк набегающего рельефа: смещение внутри столбца растёт
;          ВВЕРХ по экрану, а лента столбца x начинается с 4x, поэтому
;          движение вправо (плюс столбец) обязан уводить вниз (минус 4
;          строки), иначе юнит едет вдоль полосы, а не поперёк полос.
;          Полосы не ограничиваем снизу: минимум u_y = 130 - 64 = 66, при
;          max высоте 220, верх окна 239 — всегда внутри страницы.
; ---------------------------------------------------------------------------
u_pos:
        lda     u_xpix
        rar
        rar
        rar
        ani     1Fh                 ; u_xpix <= 16*8, хватает маски 1Fh
        sta     u_col
        lda     u_xpix
        rar                         ; бит0 уходит в CY, не мешает
        ani     03h
        sta     u_ph
        lda     u_col
        add     a
        add     a                   ; 4*u_col
        mov     b, a
        mvi     a, U_BASE
        sub     b                   ; стартуем от дальней полосы у левого края
        mov     b, a
        lda     u_alt
        add     b
        sta     u_y
        ret

; ---------------------------------------------------------------------------
; u_put: нарисовать (u_mode=0) или стереть (u_mode=1) окно спрайта.
;
; Вход: u_col, u_y, u_ph, u_plane, u_spr, u_mode.
; Окно — un_cols столбцов по un_rows байт, каждый следующий столбец правее
; на единицу по старшему байту адреса (то есть на 8 пикселей по экрану).
; Внутри столбца адрес растёт по смещению, а смещение — это ВВЕРХ по экрану,
; поэтому INX B в конце столбца надо вернуть к u_y: иначе столбцы ложатся
; лесенкой вместо картинки.
; Счётчик строк — D, не память: A в этом цикле носит байт данных (или ноль
; при стирании), и LDA/DCR/STA счётчика в A оставляют в A число, которое на
; следующей итерации уедет в STAX вместо картинки.
; ---------------------------------------------------------------------------
u_put:
        lda     u_ph
        mov     l, a
        mvi     h, 0
        dad     h                   ; слова таблицы фаз по 2 байта
        lxi     d, u_poff
        dad     d
        mov     e, m
        inx     h
        mov     d, m                ; DE = смещение фазы в таблице спрайта
        lhld    u_spr
        dad     d                   ; HL = первый столбец фазы

        lda     u_plane
        mov     b, a
        lda     u_col
        add     b
        mov     b, a                ; B = старший байт первого столбца
        lda     u_y
        mov     c, a                ; C = строка низа спрайта

        mvi     a, un_cols
        sta     u_ccnt
up_col:
        lda     u_mode
        ora     a
        jnz     up_zero
        mvi     d, un_rows          ; счётчик строк — в D: A занят данных
up_copy:
        mov     a, m
        stax    b
        inx     b
        inx     h
        dcr     d
        jnz     up_copy
        jmp     up_next
up_zero:
        xra     a
        mvi     d, un_rows
up_zloop:
        stax    b
        inx     b
        dcr     d
        jnz     up_zloop
up_next:
        inr     b                   ; следующий столбец окна
        lda     u_y
        mov     c, a                ; INX B сдвинул смещение на un_rows —
        lda     u_ccnt              ; низ окна у всех столбцов один и тот же
        dcr     a
        sta     u_ccnt
        jnz     up_col
        ret

; ---------------------------------------------------------------------------
; Прямоугольник последней отрисовки: rect[u_buf] <-> рабочие переменные.
; Записей две (A и B), поля: столбец, строка низа, фаза, признак «нарисован».
; u_rect читает записанный прямоугольник в u_w*, u_rect_back пишет обратно то,
; что в буфере стоит сейчас, — то есть u_col/u_y/u_ph после отрисовки.
; ---------------------------------------------------------------------------
u_rect:
        lda     u_buf
        mov     e, a
        mvi     d, 0
        lxi     h, u_rc
        dad     d
        mov     a, m
        sta     u_wcol
        lxi     h, u_ry
        dad     d
        mov     a, m
        sta     u_wy
        lxi     h, u_rp
        dad     d
        mov     a, m
        sta     u_wph
        lxi     h, u_rv
        dad     d
        mov     a, m
        sta     u_wv
        ret

u_rect_back:
        lda     u_buf
        mov     e, a
        mvi     d, 0
        lxi     h, u_rc
        dad     d
        lda     u_col
        mov     m, a
        lxi     h, u_ry
        dad     d
        lda     u_y
        mov     m, a
        lxi     h, u_rp
        dad     d
        lda     u_ph
        mov     m, a
        lxi     h, u_rv
        dad     d
        lda     u_wv
        mov     m, a
        ret

; ---------------------------------------------------------------------------
; Рабочие переменные.
; ---------------------------------------------------------------------------
        SECTION bss_clib

u_kind:     defb    0       ; 0 — самолётик, 1 — танк
u_xpix:     defb    0       ; левый край окна, пиксели (шаг U_STEP)
u_alt:      defb    0       ; высота над дорогой, строк
u_col:      defb    0       ; столбец окна для u_put
u_y:        defb    0       ; строка низа окна для u_put
u_ph:       defb    0       ; фаза сдвига 0..3
u_plane:    defb    0       ; старший байт плоскости юнита (C0 или 80)
u_spr:      defs    2       ; таблица спрайта текущей техники
u_mode:     defb    0       ; 0 — рисовать, 1 — стирать
u_keys_r:   defb    0       ; снимок строки 0 матрицы на этот кадр
u_ccnt:     defb    0       ; столбцов окна осталось

u_buf:      defb    0       ; какой буфер сейчас front (0 = A, 1 = B)
u_wcol:     defb    0       ; рабочий прямоугольник
u_wy:       defb    0
u_wph:      defb    0
u_wv:       defb    0

u_rc:       defb    0, 0    ; прямоугольник в буфере A / B
u_ry:       defb    0, 0
u_rp:       defb    0, 0
u_rv:       defb    0, 0

; Данные спрайтов: unit.inc открывает SECTION rodata_user сам, после него по
; коду ничего быть не должно.
        INCLUDE "unit.inc"

; Смещения фаз в таблице спрайта: фаза * un_bytes (4 байта на спрайт).
        SECTION rodata_user
u_poff:
        defw    0, 0 + un_bytes, 0 + 2 * un_bytes, 0 + 3 * un_bytes
