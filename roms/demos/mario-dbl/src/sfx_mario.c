/*
 * sfx_mario.c — звуковые эффекты демки Mario double-buffering.
 *
 * Два варианта сборки (флаг бэкенда задаётся в Makefile, как в nu_pogodi):
 *   - по умолчанию          — тон на КР580ВИ53 (sfx.c -> vi53_set_channel);
 *   - -DMUSIC_AY_DRUMS_AY   — тон на AY-3-8910 (sfx.c -> ay.c) + шум на
 *                             канале C AY через движок ударных (drums.asm).
 *
 * Прыжок и приземление — тональные свипы через 3-голосный смеситель sfx.c
 * (таблица шагов sfx_step_t: нота + detune + тики). Работают на обоих чипах.
 *
 * Свипы сделаны ЛЕСТНИЦЕЙ из коротких шагов по 1 кадру, а не большим detune:
 * на AY detune — 12-битный период, даже ±127 за кадр даёт полтона, а на ВИ53
 * — 16-битный делитель, там detune силён. Лестница нот одинаково звучит на
 * обоих, поэтому выбор одного подхода, а не #ifdef по таблицам.
 *
 * Шум ветра — только на AY: у КР580ВИ53 шумогенератора нет (vi53.c — три
 * тональных канала), поэтому в ВИ53-сборке mario_sfx_frame молча пропускает
 * ветер. На AY ветер = непрерывный шум канала C: каждый кадр, пока бежим,
 * заново запускаем steady-семпл через drum_sample_play (формат .smp:
 * {N, (R6,R10)...}, N=1 — один кадр), а при остановке глушим drum_mute().
 * drum_tick() не зовём: семпл N=1 не должен «дозвучивать» с затуханием — мы
 * сами держим его каждый кадр. Лёгкий «флаттер» ветра — сменой R6 раз в 4 кадра.
 */

#include "v06.h"

/* ------------------------- ТОНАЛЬНЫЕ ЭФФЕКТЫ ---------------------------- */

/* Прыжок: звенящий «цзинг» — восходящий мажорный арпеджио + shimmer на
 * вершине (чередование через терцию туда-обратно). Всё по 1 кадру. Приоритет 60. */
static const sfx_step_t step_jump[] = {
    { N_C(6), 0, 1 },   /* 1046 Гц — подъём */
    { N_E(6), 0, 1 },   /* 1318    */
    { N_G(6), 0, 1 },   /* 1568    */
    { N_C(7), 0, 1 },   /* 2093    */
    { N_G(7), 0, 1 },   /* 3136 Гц — вершина */
    { N_E(7), 0, 1 },   /* 2637    */
    { N_G(7), 0, 1 },   /* 3136    shimmer: терция туда-обратно */
    { N_C(7), 0, 1 },   /* 2093    */
    { N_G(7), 0, 1 },   /* 3136    */
    { N_E(7), 0, 1 },   /* 2637    */
};
static const sfx_t fx_jump = { step_jump, 10, 60 };

/* Приземление: короткий низкий «чпок» — 2 ноты вниз по 1 кадру (~40 мс),
 * без затухающего хвоста. Приоритет 30 — ниже прыжка. */
static const sfx_step_t step_land[] = {
    { N_C(4), 0, 1 },   /* 262 Гц */
    { N_G(3), 0, 1 },   /* 196    */
};
static const sfx_t fx_land = { step_land, 2, 30 };

/* -------------------------------- ВЕТЕР --------------------------------- */
#ifdef MUSIC_AY_DRUMS_AY
/* steady-семпл шума: {N=1, R6, R10}. R6 — период шума (больше — темнее),
 * R10 — громкость канала C (0..15). Два тембра для флаттера. */
static const unsigned char wind_lo[] = { 1, 28, 4 };   /* темнее  */
static const unsigned char wind_hi[] = { 1, 21, 4 };   /* светлее */
static unsigned char wind_phase;      /* счётчик кадров (флаттер)      */
static unsigned char wind_active;     /* 1 = ветер сейчас звучит       */
#endif

/* ------------------------------- API ------------------------------------ */
/*
 * Звук живёт в КАДРОВОМ ПРЕРЫВАНИИ (frame_handler = mario_frame в main.c),
 * но ПОСЛЕ смены палитры: обработчик сначала грузит палитру (v06_set_palette_isr
 * — raster-критично, в самом начале гасения), и только потом зовёт
 * mario_sfx_frame(). Так долгий звук не сдвигает палитрный цикл за blanking
 * (нет бегущих полос), а сам звук пишет только свои порты (ВИ53 0x08-0x0B /
 * AY 0x14-0x15), не трогая 02/0C. Движок играет ровно один такт за VBlank
 * (50 Гц) — темп честный даже на проспавшихся кадрах, догон цикла не трогает.
 *
 * Из main-контекста тут дёргаются ТОЛЬКО байтовые флаги (mario_sfx_running,
 * req_*) — записи атомарны на 8080; сам движок (sfx_play/sfx_tick/ветер)
 * трогается исключительно из ISR, поэтому гонки за полуживое состояние нет.
 */

unsigned char mario_sfx_running;         /* флаг бега (зеркало из main, для ветра) */
static volatile unsigned char req_jump;  /* 1 = запросить эффект прыжка в ISR       */
static volatile unsigned char req_land;  /* 1 = запросить эффект приземления        */

/* Инициализация звука. Порядок важен: сначала ударные (drum_init/route),
 * затем sfx_init — он на AY зовёт ay_mixer_init и выставляет чистый R7
 * (тон A/B/C включён, шум выключен) как базовое состояние микшера. */
void mario_sfx_init(void)
{
#ifdef MUSIC_AY_DRUMS_AY
    drum_init();
    drum_route_ay();              /* шум — на канал C AY                    */
    wind_phase = 0;
    wind_active = 0;
#endif
    mario_sfx_running = 0;
    req_jump = 0;
    req_land = 0;
    sfx_init();
}

/* Запросить эффект прыжка: только флаг, исполнит ISR (mario_sfx_frame).
 * Прямой sfx_play из main конфликтовал бы с движком, играющим в прерывании. */
void mario_sfx_jump(void)
{
    req_jump = 1;
}

/* Запросить эффект приземления. */
void mario_sfx_land(void)
{
    req_land = 1;
}

/* Кадровый движок звука — зовётся ИЗ frame_handler (в прерывании), строго
 * ПОСЛЕ загрузки палитры. Сначала разгребает пост-запросы эффектов (запуск
 * свипа идёт здесь, в ISR-контексте — единственный владелец движка), затем
 * досчитывает тональные голоса и поддерживает/гасит ветер. Никаких ei/halt/di:
 * мы уже в ISR (повторный ei открыл бы окно реентерабельного входа). */
void mario_sfx_frame(void)
{
    if (req_jump) { req_jump = 0; sfx_play(&fx_jump); }
    if (req_land) { req_land = 0; sfx_play(&fx_land); }

    sfx_tick();

#ifdef MUSIC_AY_DRUMS_AY
    if (mario_sfx_running) {
        /* Флаттер: менять тембр шума раз в 4 кадра (~12 Гц). */
        const unsigned char *w = ((wind_phase >> 2) & 1u) ? wind_hi : wind_lo;
        drum_sample_play(w);
        ++wind_phase;
        wind_active = 1;
    } else if (wind_active) {
        drum_mute();              /* однократно погасить канал C            */
        wind_active = 0;
    }
#endif
}
