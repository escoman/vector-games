; Функция: func_snd_op_keep_a
; Адрес: 0x3940
; Размер: 6 байт
; Описание: Обёртка: вызывает func_sound_op, сохраняя регистр A (PUSH/POP PSW),
;           так как func_sound_op использует A для кода операции, а здесь A
;           несёт параметр звука, который нужно передать без искажения флагов
;           вызывающего кода.

func_snd_op_keep_a:
    PUSH PSW                ; 0x3940
    CALL func_sound_op      ; 0x3941
    POP PSW                 ; 0x3944
    RET                     ; 0x3945
