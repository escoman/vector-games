/*
 * mode.c — управление видеорежимами Вектора-06Ц.
 *
 * Центральный модуль графики: хранит текущий режим, переключает
 * режимы (ПИА + скролл), предоставляет унифицированные функции
 * очистки и загрузки палитры.
 *
 * По умолчанию — режим 0 (256x256, 16 цветов): аппаратный режим
 * Вектора-06Ц при старте программы.
 */

#include "v06.h"

/* --------------------------- Таблица режимов ------------------------- */

const gfx_mode_t gfx_modes[] = {
    /* mode 0: 256x256, 16 цветов, все 4 плоскости */
    { 32, 0x0F, 16 },
    /* mode 1: 256x256, 2 цвета, плоскость 0xE000 */
    { 32, 0x01,  2 },
    /* mode 2: 512x256, 4 цвета, все 4 плоскости.
     * Чётные: index & 0x03 → слоты 0-3 (E000 бит 0, 8000 бит 3)
     * Нечётные: index & 0x0c → слоты 0,4,8,12 (A000 бит 2, C000 бит 1) */
    { 64, 0x0F,  4 },
    /* mode 3: 512x256, 2 цвета, E000 + A000.
     * Данные E000 дублируются в A000, плоскости C000/8000 скрыты. */
    { 64, 0x05,  2 },
};

unsigned char gfx_current_mode = 0;  /* аппаратный режим при старте */

/* ------------------------ Переключение режима ----------------------- */

/* asm-функции из v06pal.asm и clr.asm */
extern void v06_set_mode_bit(unsigned char val);
extern void v06_set_palette_asm(const unsigned char *pal);

void gfx_set_mode(unsigned char mode)
{
    gfx_current_mode = mode;

    if (gfx_modes[mode].width_div8 > 32) {
        /* 512x256: ПИА + скролл 0xFF */
        v06_out(V06_PIA_CW, 0x88);      /* ПИА: PA вход, PB выход */
        v06_set_mode_bit(0x10);          /* бит 4 = режим, бордюр сохранён */
        v06_out(V06_PIA_PA, 0xFF);       /* скролл = 0xFF */
    } else {
        /* 256x256: сброс бита 4 (мог остаться от 512-режима) */
        v06_set_mode_bit(0x00);
    }
}

/* ------------------------- Очистка экрана --------------------------- */

/* asm-функция заполнения плоскостей по маске (clr.asm) */

void gfx_clear(unsigned char color)
{
    graph_fill_planes(gfx_modes[gfx_current_mode].plane_mask, color);
}

/* ------------------------- Загрузка палитры ------------------------- */

/* asm-загрузчик 16 цветов палитры (v06pal.asm) */

void gfx_set_palette(const unsigned char *colors)
{
    unsigned char full[16];
    const gfx_mode_t *m = &gfx_modes[gfx_current_mode];
    unsigned char i;

    if (m->num_colors == 16) {
        /* 256x256, 16 цветов: прямое копирование */
        for (i = 0; i < 16; i++)
            full[i] = colors[i];
    } else if (m->width_div8 > 32) {
        /*
         * 512x256: каждый 4-битный индекс из VRAM распаковывается
         * в два пикселя (из эмулятора, filler.cpp):
         *
         *   чётный  = PaletteRaw(index & 0x03)   → слоты 0,1,2,3
         *   нечётный = PaletteRaw(index & 0x0c)   → слоты 0,4,8,12
         *
         * Бит 0 (E000) и бит 3 (8000) → чётные пиксели (слоты 0-3).
         * Бит 2 (A000) и бит 1 (C000) → нечётные пиксели (слоты 0,4,8,12).
         *
         * 4 цвета: все плоскости активны.
         *   full[i] = colors[i & 0x03] — цикл {c0,c1,c2,c3} × 4.
         *   Слоты 0-3 для чётных, 0/4/8/12 для нечётных.
         *
         * 2 цвета: видим E000+A000, скрываем C000+8000.
         *   Слоты 0,1 = c0,c1. Слоты 2-15 = c0 (фон, скрытие мусора).
         */
        if (m->num_colors >= 4) {
            /*
             * Чётные пиксели: index & 0x03 → слоты 0,1,2,3
             * Нечётные пиксели: index & 0x0c → слоты 0,4,8,12
             *
             * Полная палитра:
             *   слот  0: c0   (фон)          ← чётный 00, нечётный 00
             *   слот  1: c1   (E000)         ← чётный 01
             *   слот  2: c2   (8000)         ← чётный 10
             *   слот  3: c3   (E000+8000)    ← чётный 11
             *   слот  4: c1   (A000)         ← нечётный 01
             *   слот  8: c2   (C000)         ← нечётный 10
             *   слот 12: c3   (A000+C000)    ← нечётный 11
             *   остальное: c0 (фон, скрытие мусора)
             */
            for (i = 0; i < 16; i++)
                full[i] = colors[0];
            full[0x00] = colors[0];
            full[0x01] = colors[1];
            full[0x02] = colors[2];
            full[0x03] = colors[3];
            full[0x04] = colors[1];
            full[0x08] = colors[2];
            full[0x0C] = colors[3];
        } else {
            for (i = 0; i < 16; i++)
                full[i] = colors[0];
            full[0x00] = colors[0];
            full[0x01] = colors[1];
        }
    } else {
        /*
         * 256x256, 2 цвета: плоскость E000 (бит 0).
         * Биты 1-3 — неактивные плоскости, их содержимое
         * скрываем: все слоты кроме 0 → передний план.
         */
        for (i = 0; i < 16; i++)
            full[i] = colors[(i & m->plane_mask) % m->num_colors];
    }

    v06_set_palette_asm(full);
}
