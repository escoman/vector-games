/*
 * snd.c — общие глобальные переменные звуковой библиотеки Вектора-06Ц.
 *
 * Здесь лежит единственный экземпляр флага режима вывода, который
 * разделяют music.c (тоновые каналы) и drums.asm (канал шума). В заголовок
 * v06.h определение класть нельзя (было бы по копии в каждом .c), а держать
 * его в одном из двух потребителей — значит заставить второй (drums.asm)
 * линковаться вместе с music.c. Поэтому общий флаг вынесен в отдельный
 * модуль, который подключается в каждый ROM, использующий звук.
 *
 * В ROM'ах без music.c (например, демо ударных drums) этот файл — единственный
 * владелец g_music_mode; drums.asm берёт его через EXTERN _g_music_mode.
 */

#include "v06.h"

/* Глобальный переключатель вывода всего звука (3 тона + шум):
 *   MUSIC_MODE_VI53 (0) — тоны на КР580ВИ53, шум ударных на Tape Out (PC0);
 *   MUSIC_MODE_AY   (1) — тоны и шум на AY-3-8910.
 * Пишется через music_mode() (мелодия) и drum_mode() (только шум), читается
 * в обоих модулях. Значение по умолчанию — VI53. */
unsigned char g_music_mode = MUSIC_MODE_VI53;
