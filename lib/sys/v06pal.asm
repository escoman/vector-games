;
; v06pal.asm — загрузка палитры Вектора-06Ц.
;
; Аппаратная особенность Вектора: запись в порт 0C попадает не в
; «выбранный» регистр, а в регистр того цвета, который отображается
; на экране в момент записи (цвет под лучом). В гасящем интервале
; отображается бордюр, индекс которого берётся из битов 0-3 порта 02 —
; поэтому для записи слота N палитры нужно:
;   1) установить бордюр = N (порт 02);
;   2) записать байт цвета в порт 0C, пока луч в гасящем интервале.
;
; Синхронизация: ei+halt будит процессор кадровым прерыванием
; (начало кадра), дальше ~40 строк обратного хода — сплошной бордюр,
; 16 записей успеваются с большим запасом.
;
; Формат байта цвета: 0bRRRGGGBB (D0-D2 красный, D3-D5 зелёный, D6-D7 синий).
;
;   void v06_set_palette_asm(const unsigned char *pal);  /* 16 байт */
;

        SECTION code_clib
        PUBLIC  v06_set_palette_asm
        PUBLIC  _v06_set_palette_asm

v06_set_palette_asm:
_v06_set_palette_asm:
        pop     de              ; адрес возврата
        pop     hl              ; pal
        push    hl
        push    de

        ei
        halt                    ; ждём кадровое прерывание (начало кадра)

        in      a, (0x02)       ; сохранить бит режима ДО цикла
        and     0x10            ; бит 4 (512x256)
        ld      c, a            ; C = бит режима

        ld      de, 15
        add     hl, de          ; hl = pal + 15 (обход с конца: бордюр
                                ; идёт 15..0, и данные должны идти 15..0)
        ld      b, 16           ; 16 слотов палитры
pal_loop:
        ld      a, b
        dec     a               ; индекс слота = 15..0 (b = 16..1)
        out     (0x02), a       ; бордюр = индекс записываемого слота
        nop
        nop
        nop
        nop                     ; запас на задержку применения бордюра
        ld      a, (hl)
        out     (0x0C), a       ; байт цвета -> палитра[бордюр]
        nop
        nop                     ; запас до следующей смены бордюра
        dec     hl
        dec     b
        jp      nz, pal_loop

        ld      a, c            ; бит режима (сохранён до цикла)
        out     (0x02), a       ; бордюр = 0, бит режима восстановлен
        ret

; ---------------------------------------------------------------
; Установка бита режима 512x256 с сохранением цвета бордюра.
;
;   void v06_set_mode_bit(unsigned char val);
;
; val: бит 4 = режим 512x256 (0x10 вкл / 0x00 выкл).
; Биты 0-3 порта 0x02 (бордюр) не меняются.
;
        PUBLIC  v06_set_mode_bit
        PUBLIC  _v06_set_mode_bit

v06_set_mode_bit:
_v06_set_mode_bit:
        pop     hl              ; адрес возврата
        pop     de              ; val -> e
        push    de
        push    hl
        in      a, (0x02)       ; текущее значение PB
        and     0x0F            ; сохранить бордюр (биты 0-3)
        or      e               ; установить бит режима
        out     (0x02), a
        ret

