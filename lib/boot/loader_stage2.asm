;
; loader_stage2.asm — второй загрузчик (stage-2) для Вектора-06Ц.
;
; Отдельный модуль с ORG 0E000h: метки разрешаются в абсолютные адреса
; там, где blob будет исполняться, поэтому копир в boot/loader.asm
; остаётся побайтовым без релопации. В bin'е только код (приёмный буфер и
; переменные лежат в экранной плоскости 0DED0h..0DEFFh, как у NEWROM,
; рабочее поле drawp — 0FB00h.., конфиг — абсолютные ячейки 0FB10h..0FB1Fh;
; их в blob нет); z80asm -b с ORG файл не дополняет нулями — бюджет кода
; 768 Б (область 0E000h..0E2FFh) проверяет utils/bin2inc.py (цель loader2);
; сразу за кодом — слоты данных панелей 0E300h и 0EF00h (по 3 КБ).
;
; Конвейер (ТЗ docs/LOADER_TZ.MD §3, порядок нормативен):
;   DI → SP=0DCF0h → очистка 0000h..DFFFh → заглушка JMP 0E000h в 0000h →
;   рестарт ПИА → панели из конфига (§5.2) → карта загрузки OR-записью
;   поверх панелей (§5) → палитра «видна только плоскость C000» цветами из
;   конфига (§4.1, §4.2) — уже по готовности к приёму: нарисованное на
;   время цветов прячется в stash 01000h и возвращается обратно (слепая
;   палитра требует пустой плоскости), поэтому экран вспыхивает картой
;   целиком → приём v06c-rom с порта магнитофона (§6) →
;   JP (HL)=addrhi:0000 — переход на старт загруженного образа (§3.8).
;
; Прерываний нет нигде: ни EI, ни HLT, ни RST, вектора не пишутся —
; в стёртую область грузится новый ROM (.r0m — с 0000h).
;
; Система команд — только КР580ВМ80А (i8080, docs/VECTOR_VERIFIED.md §2).
; Модуль собирается z80asm с -m=8080_strict: в этом режиме синтаксис
; мнемоник — интеловский 8080 (jmp — безусловный, jp — «jump positive»,
; jm/jz/jnz/jc/jnc, cp/cz/rz/rm…), а Z80-расширения (IX/IY, DD/FD/ED,
; индексируемые операнды) ассемблируются с ошибкой, а не молча. Без -m
; z80asm по умолчанию собирает Z80, и «jp метка» в том режиме — это
; безусловный JMP, а не переход по знаку «плюс»; контроль по байтам бинаря
; (utils/disasm8080.py, ТЗ §9.4) остаётся второй ступенью.
; «RST 7» эталонного NEWROM (задержка + выборка ленты) заменён двумя прямыми
; CALL — SAMPLE (с задержкой) и RDATAP (без неё, как CALL REATP в оригинале);
; самомасштабирование TSBIT покрывает изменившуюся длину цикла.
;
; Эталон переноса: NEWROM v2.0 (TMK Soft'91) — копия исходников в
; docs/etalon/: kish1.asm (адресная разметка) и newrom2.asm (с метками
; TBIT/TSBIT/MITAP/READB/REATP/RCON3, кодировка CP866). Приём ленты обязан
; совпадать с оригиналом логика в логику; расхождения, разрешённые ТЗ, —
; двухвходовый узел выборки вместо RST 7 (§6) и инициализация PRINV (§2):
; без обеих приём не работает, и выглядит это как проблема таймингов.
;

; --- переменные (ТЗ §2.1): как у NEWROM — приёмный буфер и «глобальные»
;     переменные живут ВНУТРИ экранной плоскости (0DED0h..0DEFFh ⊂ C000h..
;     DFFFh), поэтому их запись видна на экране: «живые» байты принятого
;     записями-паттернами и точками стека — ровно как в оригинале.
;     Оффсеты — по newrom2.asm 11..17 (ABUFF+36/38/39) и kish1 (STA 0DEF6H):
;     буфер занимает ровно 35 байт DED0h..DEF2h, а PRINV/CONR/VAR идут ПОСЛЕ
;     него — иначе первый же принятый блок затёр бы их своими данными.
;     Рабочее поле drawp — в high RAM (0FB00h..), конфиг — 0FB10h..0FB1Fh,
;     слоты панелей — сразу за кодом, 0E300h и 0EF00h, стек — от 0DCF0h ---
ABUFF   equ 0ded0h              ; буфер: 35 байт, принятых после E6
PRINV   equ 0def4h              ; инверсия ленты (00h / FFh)   = ABUFF+36
CONR    equ 0def6h              ; итераций задержки на выборку = ABUFF+38
STARTHI equ 0def7h              ; addrhi ПЕРВОГО заголовка = адрес старта
                                ; образа (куда он лёг линейно). Ловится один
                                ; раз в loa111, т.к. B по ходу приёма шагает
                                ; по страницам — §3.8. Slot VAR у NEWROM.
SBCNT   equ 0def8h              ; счётчик подблоков текущего блока

; рабочее поле drawp (панель): старший/младший байт начала строки в
; плоскости, байт в строке, счётчик строк. HL при шаге по блокам
; прибавляет 100h за байт, поэтому начало строки держим в двух байтах.
DRAWHB  equ 0fb00h
DRAWLB  equ 0fb01h
DRAWWB  equ 0fb02h
DRAWROW equ 0fb03h

; --- конфиг загрузчика (ТЗ §4.2, §5.2, §7): пишет его копир из ROM
;     заставки, 10 байтами из начала struct loader_cfg. Указатели на
;     данные панелей в конфиге НЕ живут: стаб кладёт их по фиксированным
;     слотам ниже, а stage-2 получает адрес вызывающим ---
CFG_BG  equ 0fb10h              ; цвет слотов с битом 1 = 0 (он же бордюр)
CFG_LINE equ 0fb11h             ; цвет слотов с битом 1 = 1: линии и арт
CFG_P1  equ 0fb12h              ; дескриптор панели 1: x, y, wb, h
CFG_P2  equ 0fb16h              ; дескриптор панели 2: то же
P_X     equ 0                   ; смещения внутри дескриптора
P_Y     equ 1
P_WB    equ 2
P_H     equ 3

; слоты данных панелей в high RAM: их РАЗУПАКОВЫВАЕТ сюда копир заставки
; (ZX0-декодер lib/unpack/zx0.asm). Формула base+stride совпадает с
; loader.asm/v06.h — рост панели в пределах stride не сдвигает соседнюю.
; панель 1 — 0E300h..0EEFFh, панель 2 — 0EF00h..0FAFFh (по 3 КБ).
LOADER_PANEL_BASE   equ 0e300h
LOADER_PANEL_STRIDE equ 0c00h
LOADER_P1_DATA      equ LOADER_PANEL_BASE                       ; панель 1: +0
LOADER_P2_DATA      equ LOADER_PANEL_BASE + LOADER_PANEL_STRIDE  ; панель 2: +1

TIN     equ 10h                 ; маска Tape In (бит 4 порта 01h)

        org 0e000h

; ---------------------------------------------------------------
; точка входа (0E000h): сюда прыгает stub loader.asm, не возвращается
; ---------------------------------------------------------------
stage2: di                      ; §3.1 — больше прерываний не будет
        lxi sp, 0dcf0h          ; §3.4 вершина стека — как у NEWROM (STEK=DCF0h),
                                ; ВНУТРИ стираемой области: PUSH пишет
                                ; return-адреса в плоскость C000 — точки стека
                                ; видны на экране. Стирающая петля (§3.2)
                                ; идёт до всего остального и сама без CALL/PUSH.
        mvi a, 08h
        sta CONR                ; задержка до первой калибровки (как NEWROM)
        xra a
        sta PRINV               ; ОБЯЗАТЕЛЬНО: NEWROM обнуляет все 64 КБ
                                ; целиком, и PRINV=0 у него «сам»; мы стираем
                                ; 0000h..DFFFh, а PRINV теперь внутри этой
                                ; области — обнуление честное, но ЯВНОЕ: без
                                ; этой строки на машине, где плоскость уже
                                ; заполнена, каждый байт XORился бы с garbage
                                ; (AA^A5=0F).

; --- §3.2 Очистка 0000h..DFFFh: цикл держим без CALL/PUSH — он и в
; новом порядке идёт до всего остального, и лишние т-состояния на
; 56 КБ стирания нам даром не нужны. По 4 байта за итерацию. ---
        lxi b, 0000h            ; BC — линейный адрес
clea1:  mvi a, 00h
clea2:  stax b
        inx b
        stax b
        inx b
        cmp c                   ; C завершил 00h..FFh старшего байта B?
        jnz clea2
        mov a, b
        cpi 0e0h                ; дошли до E000h (собственный код)?
        jnz clea1

; --- §3.8-reset: заглушка «JMP 0E000h» в векторе сброса (0000h..0002h):
;     после аппаратного reset управление снова уходит в загрузчик. Ставим
;     СРАЗУ после очистки и ДО приёма: для .rom (старт 0100h) приём в 0000h
;     не пишет и заглушка живёт; для .r0m (старт 0000h) её затирает
;     собственный код образа — туда reset и должен вести (занять 0000h под
;     загрузчик одновременно с точкой входа r0m физически невозможно). ---
        mvi a, 0c3h             ; JMP
        sta 0000h
        mvi a, 000h             ; адрес 0E000h: мл. 00h, ст. E0h
        sta 0001h
        mvi a, 0e0h
        sta 0002h

; --- §3.3 Рестарт ПИА (как NEWROM) ---
        mvi a, 088h
        out 00h                 ; PA — вход, PB — выход
        mvi a, 081h
        out 04h                 ; PC — вход
        mvi a, 0ffh             ; запись CW сбрасывает PA (скролл) —
        out 03h                 ; восстанавливаем 0FFh сразу
        out 05h
        out 06h
        out 07h
        xra a
        out 02h                 ; режим 256x256, бордюр — слот 0

; --- §3.4 вершина стека выставлена на входе (сразу после DI) ---

; --- §5.2 Панели: арт в углы экрана, ДО сетки ---
; wb = 0 в дескрипторе значит «панели нет» (дефолтный конфиг loader_boot
; именно такой: картинка остаётся ровно §5). Данные уже лежат в слотах
; high RAM, их положил туда копир заставки вместе с blob.
        lda CFG_P1+P_WB
        ora a
        jz nop1
        lxi h, CFG_P1
        lxi d, LOADER_P1_DATA
        call drawp
nop1:   lda CFG_P2+P_WB
        ora a
        jz nop2
        lxi h, CFG_P2
        lxi d, LOADER_P2_DATA
        call drawp
nop2:

; --- §5 Карта загрузки: 8 групп, r0 = 54 + 24·g ---
; Байт (col,row) лежит в C000 + col·100h + (255−row); строка — 32 байта
; со stride 100h, поэтому младший байт адреса = 255−row, старший — кол.
; Запись теперь OR-ом: линии «лежат поверх» панелей §5.2, но арт от этого
; не исчезает (в точках пересечения — 107 пикселей из 4352 — остаётся
; светиться то, что уже нарисовано).
        mvi e, 08h              ; g = 0..7
        mvi d, 0c9h             ; 255 − 54 — младший байт строки r0
cardg:  mov a, d
        mov l, a
        mvi h, 0c0h
        call cri                ; r0: пунктир (1 пиксель линии на 8)
        mov a, d
        dcr a
        mov l, a                ; r0+1: сплошная
        mvi h, 0c0h
        call crd
        mov a, d
        sui 10
        mov l, a                ; r0+10: сплошная
        mvi h, 0c0h
        call crd
        mov a, d
        sui 24                  ; период группы — 24 строки
        mov d, a
        dcr e
        jnz cardg

; --- §4.1a hide: C000..DFFF -> stash 01000h..02FFFh, плоскость в 00 ---
; На время слепых цветов экран пуст: при nonzero-пикселе под лучом номер
; ячейки палитры задаёт пиксель, а не бордюр (BEAM_TIMING §6), и обход
; 15..0 раскидал бы цвета по чужим слотам (+2 от бита C000, +8 от E000)
; — отсюда и «чёрные» 2/3, и весь мусор. Поэтому уводим картинку в stash
; ниже 0x8000 (он НЕ отображается и не индексирует палитру), плоскость
; гасим в 0 -> индекс ∈ {0,8} (только код в E000), палитра ставится
; вслепую корректно, потом stash возвращаем. Плоскости A000/8000 трогать
; нечем: boot-erase (§3.2) их уже обнулил, и мы в них не рисуем.
; Пара байт за итерацию: 4096 итераций, ~0,1 с.
        lxi h, 0c000h           ; читаем плоскость
        lxi d, 01000h           ; кладём в stash (stax d)
sv1:    mov a, m                ; байт картинки
        stax d                  ; -> stash
        inx d
        mvi m, 00h              ; обнуление плоскости (не трогает A/флагов)
        inx h
        mov a, m                ; второй байт той же пары
        stax d
        inx d
        mvi m, 00h
        inx h
        mov a, h                ; дошли до страницы E0 (h==0e0h)?
        cpi 0e0h
        jnz sv1


; --- §4.1 Палитра «видна только плоскость C000», вслепую ---
; Ставится ПОСЛЕ того, как панели и карта уже нарисованы (порядок §3), но
; при спрятанной в stash плоскости (§4.1a) — иначе пиксель под лучом сам
; задаёт номер ячейки (BEAM_TIMING §6) и слепой обход раскидал бы цвета.
; Когда C000..DFFF пуста, из четырёх весов индекса остаётся только E000
; (бит 3, weight 8) — наш код; промах луча бьёт лишь в ячейки 0 и 8, а они
; обе фонового цвета и добиваются завершающим проходом. Дальше идём по
; гашению: OUT 02h бордюр=N, OUT 0Ch — цвет в ячейку N. Полный обход
; 15..0 повторяется много раз; цвет зависит только от бита 1 индекса (§4),
; два цвета берутся из конфига (§4.2): 0 = фон, 1 = линии.
        mvi e, 96               ; прогонов цикла (~1.5 кадра, ≈25 мс)
pal0:   mvi c, 15               ; N = 15..0
pal1:   mov a, c
        out 02h                 ; бордюр = slot N
        ani 02h                 ; бит 1 индекса (MVI флагов не трогает)
        jz palbg
        lda CFG_LINE
        jmp palw
palbg:  lda CFG_BG
palw:   out 0ch                 ; цвет слота N
        dcr c
        jp pal1                 ; jump positive: 15..0; при 0->FF знак
                                ; сменится — выход (в -m=8080_strict jp и
                                ; есть «переход по плюсу»)
        dcr e
        jnz pal0
; завершающий проход: бордюр 0 + фон — перекрывает возможные попадания
; луча в ячейки 0 и 8 (~2 мс)
        mvi d, 04h
pal2o:  mvi e, 50h
pal2:   xra a
        out 02h
        lda CFG_BG
        out 0ch
        dcr e
        jnz pal2
        dcr d
        jnz pal2o

; --- §4.1c show: stash 01000h -> C000..DFFF — картинка своими цветами ---
; По ходу чтения обнуляем stash: для мелких ROM приём не дописывает до
; 02FFF, и без обнуления там осталась бы копия картинки (мусор в RAM,
; ниже 0xE000 — а тест round-trip ждёт там нулей).
        lxi h, 01000h           ; читаем stash
        lxi d, 0c000h           ; кладём в плоскость (stax d)
rt1:    mov a, m                ; байт -> плоскость
        stax d
        inx d
        mvi m, 00h              ; и обнуляем stash
        inx h
        mov a, m
        stax d
        inx d
        mvi m, 00h
        inx h
        mov a, h                ; прочитано 8 КБ (h==030h: 1000h+2000h)?
        cpi 030h
        jnz rt1

; --- §3.7 Мотор включён, приём ленты (§6) ---
; Палитра (§4.1) выставлена — загрузчик к приёму готов, дальше на экране
; только то, что рисует сам приём (метки AKART).
        mvi a, 02h
        out 01h
        jmp loadf               ; уходим в приём; декодер ниже

; ---------------------------------------------------------------
; §5 подпрограммы строки карты: 32 блока со stride 100h, OR в плоскость.
; Значение линии заряжается A на каждой итерации: держать его нечем —
; B счётчик, C/D/E/H/L нужны вызывающему, а cell-переменная дороже двух
; байтов MVI (lda + mov стоят 7+4 т-состояний против 7 у MVI).
; ---------------------------------------------------------------
crd:    mvi b, 32               ; сплошная строка
cr1:    mvi a, 0ffh
        ora m
        mov m, a
        inr h
        dcr b
        jnz cr1
        ret

cri:    mvi b, 32               ; пунктир: 1 пиксель на 8
cr2:    mvi a, 081h
        ora m
        mov m, a
        inr h
        dcr b
        jnz cr2
        ret

; ---------------------------------------------------------------
; §5.1 AKART: адрес принятого подблока в памяти -> адрес ячейки
; «столбика» в C000. Порт newrom2.asm 277..297 один-в-один (логика
; карты прогресса приёма). Вызов — из хвоста sbc, HL = BC = адрес
; первой байты подблока. RLC/RAR на i8080 — ЧИСТЫЕ 8-битные ротации:
; bit7<->bit0 замыкаются внутри A, CY = выходящий бит; вход CY не
; участвует (и ANI сбрасывает его по ходу — см. comments ниже).
;   col      = addrhi & 1Fh
;   row_byte = 24 + 24*(addrhi>>5) + (addrlo>>5)
; Восемь подблоков страницы (offset 0x00..0xE0 шаг 0x20) дают восемь
; РАЗНЫХ VRAM-строк внутри группы — это и есть «заполняющийся столбик».
; HL — вход/выход; DE сохраняется PUSH/POP'ом, B и C AKART не трогает.
; ---------------------------------------------------------------
akart:  push d
        mov a, l
        rlc                     ; 3 RLC: addrlo целиком влево на 3, биты
        rlc                     ;   7..5 возвращаются в 2..0 — это и есть
        rlc                     ;   lo>>5 (для lo, кратного 20h)
        mov l, a                ;   L = addrlo>>5 (0..7 — номер подблока)
        mov a, h
        rar                     ;   H>>1 (bit0 возвращается в bit7)
        ani 70h                 ;   mask bits 6-4 = addrhi bits 7-5 на месте
        mov d, a
        rar                     ;   /2 (bit0 у V=...&70h всегда 0 — чисто)
        add d                   ;   1.5 * ((H>>1)&70h) = 24 * (H>>5)
        add l                   ;   + номер подблока 0..7
        adi 18h                 ;   +24: база групп
        mov l, a                ;   L = байт внутри блока = 255-row
        mov a, h
        ani 1fh                 ;   col = addrhi & 1Fh
        adi 0c0h                ;   +C0h: блок C000h..DFFFh (наша плоскость)
        mov h, a
        pop d
        ret

; ---------------------------------------------------------------
; §5.2 drawp: панель из конфига в плоскость C000, OR-ом.
; вход: HL = дескриптор (x, y, wb, h), DE = данные панели (слот high RAM);
; выход: нет, регистры порченые — вызов идёт до приёма ленты.
; Байты панели уже уложены как плоскость: 1 байт = 8 пикселей по
; горизонтали, строки сверху вниз — шаг по блокам это +100h (inr h), шаг
; по строкам экрана это −1 в младшем байте адреса (255−y). X кратно 8 —
; это проверяет конвертер, поэтому сдвигов и масок тут нет.
; ---------------------------------------------------------------
drawp:  mov a, m                ; desc+0 = x
        ora a                   ; ОБЯЗАТЕЛЬНО чистый C перед RAR: поворот идёт
        rar                     ;   ЧЕРЕЗ carry, и CMC (дополнить, а не сбросить)
        rar                     ;   на входе с C=0 даёт C=1 — тогда в bit7 первым
        rar                     ;   RAR затекает 1: x=0 превращается в 80h->40h->20h,
                                ;   ADI 0C0h шлёт DRAWHB в 0E0h, и панель пишется
                                ;   поверх кода загрузчика (PC уходит в мусор).
                                ;   ORA A не меняет A и гарантированно обнуляет C.
                                ;   /8 через 3 RAR корректен, т.к. x кратно 8
                                ;   (проверяет конвертер) — младшие 3 бита нули,
                                ;   назад в старшие ничего не затекает.
        adi 0c0h                ; блок плоскости C000 + (x/8)·100h
        sta DRAWHB
        inx h
        mov a, m                ; desc+1 = y
        cma                     ; 255 − y: байт строки внутри блока
        sta DRAWLB
        inx h
        mov a, m                ; desc+2 = wb
        sta DRAWWB
        inx h
        mov a, m                ; desc+3 = h
        sta DRAWROW
drw1:   lda DRAWHB
        mov h, a
        lda DRAWLB
        mov l, a                ; HL = начало строки панели в плоскости
        lda DRAWWB
        mov c, a                ; счётчик байтов строки
drw2:   ldax d                  ; байт данных
        ora m                   ; поверх того, что уже нарисовано
        mov m, a
        inx d                   ; шаг по данным: +1
        inr h                   ; шаг по плоскости: +100h (следующий блок)
        dcr c
        jnz drw2
        lda DRAWLB              ; строка экрана ниже = адрес на 1 меньше
        dcr a
        sta DRAWLB
        lda DRAWROW
        dcr a
        sta DRAWROW
        jnz drw1
        ret

; ---------------------------------------------------------------
; §6 Приём: калибровка CONR → синхробайт → заголовок → блоки
; ---------------------------------------------------------------
loadf:  call tsbit              ; RCON3: измерить T
rcon1:  mov d, a
        ora a
        rar                     ; T/2
        mov e, a
        add d                   ; T + T/2
        mov h, a
        call tsbit
        cmp h
        jc rcon1                ; ещё не в нужном диапазоне
rcon2:  add d                   ; 0.75T
        sta CONR
        mvi e, 12               ; синхробайт: 12 подряд 55h или AAh
loa21:  mvi a, 08h
        call mitap
        cpi 055h
        jz loa11
        cpi 0aah
        jnz loadf               ; мусор — перекалибровка и заново
loa11:  dcr e
        jnz loa21
; первый заголовок
loa111: call readb
        mov e, a                ; E = cs0 (он же поле cs0 подблоков)
        mov a, m
        cpi 00h                 ; заголовок начинается с 00 (у подблока — id)
        jnz loa111
        lxi h, ABUFF+33
        mov a, m
        dcx h
        cmp m                   ; rev == N → это первый блок
        jnz loadf               ; нет — полная ресинхронизация
        mov d, a                ; D = N — счётчик блоков
        dcx h
        mov a, m                ; addrhi
        sta STARTHI             ; latch старта: выход пойдёт сюда (§3.8)
        mov b, a                ; B = addrhi — страница приёма
        mvi a, 08h
        sta SBCNT
; приём записей блока
loa13:  call readb
        push psw
        mov a, m
        cpi 00h
        jz loa12                ; заголовок следующего блока
        add a                   ; id*32 (0E6h-синхронизированный id = 80h..87h)
        add a
        add a
        add a
        add a
        mov c, a                ; смещение в странице
        pop psw
        inx h
        mov a, m
        cmp e                   ; поле cs0 подблока == cs0 заголовка?
        jnz loa13               ; нет — запись не та, читаем заново
        push d
        push b                  ; B = addrhi
        inx h                   ; HL = payload (ABUFF+2)
        lxi d, 207eh            ; D = 32 — счётчик байт, E = 7Eh — маркер
sbc:    mov a, m
        stax b                  ; [addrhi:offset] = байт
        ldax b
        xra m
        mov m, a                ; гигиена оригинала: буфер после копирования 0
        inx h
        inr c
        dcr d
        jnz sbc
        pop b                   ; §5.1 AKART: BC = адрес первой байты
        mov l, c                ;   подблока в памяти — ровно как NEWROM
        mov h, b                ;   перед CALL AKART делает MOV L,C / MOV H,B
        call akart              ; HL = ячейка «столбика» в C000
        mov m, e                ; E = 7Eh (не менялся в sbc): 6 жёлтых
                                ;   пикселей из 8 — видимый «подблок принят»
        pop d
        lda SBCNT               ; 8 подблоков на блок
        dcr a
        sta SBCNT
        ora a
        jnz loa13
        mov a, d                ; блок принят: это был последний?
        cpi 01h
        jnz loa13               ; нет — ждём заголовок следующего
        jmp load_done
; заголовок: cs0 должен убывать на 1 по блокам
loa12:  pop psw
        sub e
        jz loa13                ; тот же cs0 — повторный заголовок, пропускаем
        inr a
        jnz loadf               ; расхождение — полный рестарт приёма
        dcr e                   ; cs0 нового блока
        inr b                   ; следующая страница приёма
        dcr d                   ; блоков осталось на один меньше
        mvi a, 08h
        sta SBCNT
        jmp loa13
load_done:
        xra a                   ; §3.7 мотор выкл
        out 01h
        lda STARTHI             ; §3.8: переход на фактический старт образа:
        mov h, a                ; HL = addrhi:0000 (для .r0m — 0000h, для
        mvi l, 00h              ;   .rom — 0100h). Прыжок СВЕРХУ заглушки JMP
        pchl                    ;   0E000h, поэтому .rom сразу стартует, а не
                                ;   возвращается в загрузчик

; ---------------------------------------------------------------
; §6 READB: принять 35 байт после паттерна E6 в ABUFF с проверкой CS
; вход: —; выход: A = cs, HL = ABUFF; не совпало — пересинхронизация
; ---------------------------------------------------------------
readb:  push b
        lxi h, ABUFF
rea2:   push h
        lxi b, 0023h            ; B = 0 — затравка суммы, C = 35 — счётчик
        mvi a, 0ffh             ; MITAP в режиме поиска паттерна
rea1:   call mitap
        mov m, a
        inx h
        add b                   ; кумулятивная контрольная сумма
        mov b, a
        mvi a, 08h              ; далее — режим приёма байта
        dcr c
        jnz rea1
        dcx h                   ; HL = байт cs
        mov a, b                ; A = сумма всех 35
        sub m
        sub m                   ; сумма(34) − cs == 0?
        mov a, m                ; A = cs (MOV флагов не меняет)
        pop h
        jnz rea2
        pop b
        ret

; ---------------------------------------------------------------
; §6 MITAP: принять байт; A=0FFh — ждать паттерн 0E6h (или 19h при
; инверсной ленте), A=08h — принять 8 бит. Выход: A = байт (с учётом
; инверсии), паттерн в буфер не кладётся.
;
; Регистровый контракт: BC и DE вызывающий держит живыми между вызовами
; (READB крутит счётчик записи в C, цикл синхробайта — серию в E, заголовок
; хранит cs0 в E). PUSH B/D сохраняют пары целиком, то есть и C, и E тоже.
; ---------------------------------------------------------------
mitap:  push b
        push d
        mvi c, 00h
        mov d, a
        call rdatap             ; БЕЗ задержки (эталон: CALL REATP, не RST 7)!
izmsig: in 01h
        ani TIN
        cmp e
        jz izmsig               ; ждём перехода
        rlc                     ; бит 4 -> carry
        rlc
        rlc
        rlc
        mov a, c
        ral                     ; сдвигаем фазу перехода в C
        mov c, a
        call sample             ; задержка 0.75T + обновить E
        mov a, d
        ora a
        jp m118                 ; jump positive: D>0 — режим приёма байта
        mov a, c
        cpi 0e6h
        jz m113
        cpi 019h                ; инверсная лента
        jnz izmsig
        mvi a, 0ffh
        sta PRINV
        jmp m113x
m113:   xra a
        sta PRINV               ; прямая лента
m113x:  mvi d, 09h
m118:   dcr d
        jnz izmsig
        lda PRINV
        xra c
        pop d
        pop b
        ret

; ---------------------------------------------------------------
; §6 TSBIT: среднее из 32 интервалов T с отбраковкой выбросов > T/2
; выход: A = T (в итерациях цикла выборки)
; ---------------------------------------------------------------
tsbit:  push h
        push d
tsf10:  call tbit
        mov b, a                ; первый замер — эталон разброса
        ora a
        rar                     ; T/2
        mov c, a
        lxi h, 0000h
        mvi d, 32               ; число измерений
tsf11:  call tbit
        push d
        mvi d, 00h
        mov e, a
        dad d                   ; накопить в HL
        pop d
        mov e, a
        sub b                   ; |Δ| относительно первого замера
        jnc tsf13
        mov a, b
        sub e
tsf13:  cmp c
        jnc tsf10               ; выброс — начать усреднение заново
        dcr d
        jnz tsf11
        dad h                   ; ×2 (HL уже содержит сумму)
        mov a, h                ; A = среднее
        pop d
        pop h
        ret

; ---------------------------------------------------------------
; §6 TBIT: замер длительности одного полупериода в итерациях (×4)
; ---------------------------------------------------------------
tbit:   push d
        call sample
rtf10:  in 01h
        ani TIN
        cmp e
        jz rtf10                ; ждём перехода
        mov e, a
        mvi d, 01h
rtf11:  in 01h                  ; считаем итерации до следующего перехода
        ani TIN
        inr d
        cmp e
        jz rtf11
        mov a, d
        add a                   ; цикл ~36 t-состояний, масштаб ×4
        add a
        pop d
        ret

; ---------------------------------------------------------------
; §6 SAMPLE: замена «RST 7» NEWROM — задержка CONR + выборка Tape In
; выход: E = текущий уровень (00h / 10h)
;
; Два входа, как в эталоне (newrom2.asm: LDA CONR → DELAY → REATP):
;   SAMPLE — с задержкой 0.75T, вызывается из цикла битов (MITAP, TBIT);
;   RDATAP — немедленная выборка уровня, единственный вход MITAP при вызове.
; Это не косметика: задержка при входе в MITAP стоит ещё 0.75T после того,
; как 0.75T уже отработаны на последнем бите предыдущего вызова, поэтому
; фронт на границе байта теряется и разбивка по байтам уплывает на бит
; каждый байт. Синхробайт тогда не набирается, и READB ресинхронизируется
; бесконечно.
; ---------------------------------------------------------------
sample: lda CONR
smp1:   dcr a
        jnz smp1
rdatap: in 01h
        ani TIN
        mov e, a
        ret
