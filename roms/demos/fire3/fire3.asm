; fire3.asm — огонь на Вектора-06Ц методом «racing the beam» (как clrs.rom).
;
; Отличие от fire2
; ---------------
; fire2 каждый кадр раскладывает цвет каждой точки по 4 бит-плоскостям VRAM
; (1280 точек = 5120 байт записи за кадр). Здесь VRAM очищается один раз:
; все пиксели имеют индекс 0, а цвет выводится сменой ЯЧЕЙКИ ПАЛИТРЫ №0 в
; тот момент, когда луч рисует очередную строку (OUT 0Ch).
;
; Механизм проверен по исходникам ядра эмулятора (vector-psp):
;   filler.cpp  commit_palette(index), где index — данные пикселя ПОД ЛУЧОМ;
;               при очищенной VRAM index = 0 и для картинки, и для бордюра,
;               поэтому ОДИН OUT 0Ch в начале строки перекрашивает ВСЮ строку
;               (картинку и горизонтальные бордюры) в новый цвет;
;   board.cpp   длительность инструкции учитывается в «видео-тактах»
;               v_cycles; строка = 768 v_cycles, кадр = 312 строк = 239616;
;               картинка — строки 40..295 (render_full_frame_256), 1 пиксель =
;               2 v_cycles, видимое окно строки — rpixel [128..640) с лагом 24.
;
; Что это даёт для решётки 64x20
; ------------------------------
; Вертикаль дёшевая: строк 256, на каждую хватает и задержки, и ОДНОГО
; вывода цвета. Поэтому на этапе калибровки одна строка экрана = один цвет,
; а точка буфера по высоте = FIRE_LINES = 4 строки. Горизонтальная решётка
; 4px требует не одного, а ~16 вывод/цветов на строку — это следующий шаг
; (одна строка стоит 768 v_cycles, вывод ~12..28 → физически не больше
; нескольких смен цвета на строку). Пока честим вертикальное позиционирование.
;
; Архитектура гонки
; -----------------
; Тело строки — обычный фиксированный код, ОДИН указатель HL идёт по
; таблице цветов _row_table[256] (байт на строку развёртки 40..295):
;     mov a,m / inx h / out (0Ch)  — взять цвет строки, сдвинуться, вывести
; Задержка до ровных 768 v_cycles набрана NOP-ами (их флаги не трогают),
; а счётчик строк — это C: он стартует с 0 (после грубой задержки BC=0) и
; «inr c / jnz» делает ровно 256 итераций, после чего C оборачивается в 0 и
; цикл сам завершается. Самоизменяемого кода нет вообще; единственный
; патчаемый операнд — LXI B грубой задержки (fire3_set_coarse), длина от
; этого не меняется, фаза луча не съезжает.
;
; Раскладка тела строки (ровно 768 v_cycles):
;     mov a,m   8
;     inx h     8
;     out 0Ch   12
;     inr c     8
;     NOP x180  720
;     jnz body  12
;     ----------------
;     итого     768
;
;   void fire3_init(void)                       — вектор RST 7 + очистка VRAM
;   void fire3_set_coarse(unsigned int cycles)  — грубая привязка ISR (callee)
; Таблицу _row_table заполняет основной цикл (см. fire3_sync в main.c).
;
; Только инструкции Intel 8080 (без jr/djnz, без префиксов CB/DD/ED/FD).

        PUBLIC  _fire3_init
        PUBLIC  _fire3_set_coarse
        PUBLIC  _beam_isr
        PUBLIC  _beam_body
        PUBLIC  _beam_coarse_imm
        PUBLIC  _row_table

        EXTERN  _frame_count

; ---------------- геометрия развёртки (v_cycles) ----------------
LINE_VC     EQU 768             ; одна строка развёртки
PIC_TOP     EQU 40              ; первая строка картинки (abs. line 40 = row 0)
BEAM_LINES  EQU 256             ; строк ведёт ISR (abs. 40..295) = _row_table
NOP_PAD     EQU 180             ; NOP в теле: 180*4 = 720 v_cycles

; Грубая задержка от входа в ISR до начала строки PIC_TOP. Откалибрована
; прогоном beam_timing.py (v_cycles по таблице ядра vector-psp): при этом
; значении первый OUT попадает на offset ~26 v_cycles внутри строки 40
; (левый бордюр, до начала картинки) — цвет берётся ВСЕЙ строкой, дальше
; тело фазо-закрыто по 768 и table[i] ложится ровно на строку 40+i.
; Дельта всех 256 строк = ровно 768 (проверено). Меняется только стартовая
; строка картинки, если сдвинуть PIC_TOP.
COARSE_DEF  EQU 952

        SECTION bss_clib
        ALIGN   256

; Байт цвета (0bBBGGGRRR) на каждую строку развёртки 40..295. Заполняет
; основной цикл из внутреннего буфера 64x20 (см. fire3_sync в main.c).
_row_table: defs BEAM_LINES         ; 256 байт

        SECTION code_clib

; ================================================================
; void fire3_init(void)
;
; Свой вектор RST 7 вместо кадрового обработчика из startup.asm: гонка за
; лучом считает такты, лишний пролог и косвенный вызов функции из C в ISR
; недопустимы. К этому моменту startup.asm уже инициализировал ПИА, скролл
; (0xFF) и порт 02 (режим 256x256, бордюр 0); палитра уже загружена.
; ================================================================
_fire3_init:
        di
        ; --- VRAM 8000h..FFFFh в ноль: все пиксели = индекс 0 ---
        lxi     h,0x8000
fi_vram:
        mvi     m,0
        inr     l
        jnz     fi_vram
        inr     h
        jnz     fi_vram
        ; --- таблица луча: всё чёрным (0) ---
        lxi     h,_row_table
        mvi     c,BEAM_LINES            ; 256 → цикл обнулится ровно за 256
fi_tab:
        mvi     m,0
        inx     h
        dcr     c
        jnz     fi_tab
        ; --- вектор RST 7 (0x0038) -> _beam_isr ---
        mvi     a,0C3h
        sta     0x0038
        lxi     h,_beam_isr
        shld    0x0039
        ei
        ret

; ================================================================
; void fire3_set_coarse(unsigned int cycles)   [__z88dk_callee]
; Патчит операнд LXI B грубой задержки — задаёт, на какую строку ложится
; первый OUT. Калибруется прогоном; вызывать между кадрами.
; ================================================================
_fire3_set_coarse:
        pop     d                       ; адрес возврата
        pop     h                       ; cycles (младшее слово в стеке)
        push    d
        shld    _beam_coarse_imm + 1    ; операнд LXI B
        ret

; ================================================================
; _beam_isr — кадровое прерывание, «гонка за лучом».
;
; Вход: RST 7 (вектор 0x0038) примерно на v_cycle 174 строки 0. Прерывания
; на время гонки запрещены (DI), EI перед RET. Регистры сохраняются.
; После 256 строк (картинка 40..295) цикл сам выходит по обороту C.
; ================================================================
_beam_isr:
        di
        push    b
        push    d
        push    h
        push    psw
        ; --- грубая привязка: смотать такты до строки PIC_TOP ---
_beam_ptr_imm:
        lxi     h,_row_table            ; HL = &row_table[0]
_beam_coarse_imm:
        lxi     b,COARSE_DEF            ; грубая задержка (патч)
bm_coarse:
        dcx     b                       ; 8
        mov     a,b                     ; 8
        ora     c                       ; 4
        jnz     bm_coarse               ; 12 → итерация 32 v_cycles; BC=0 на выходе
        ; BC=0000 => C=0 — счётчик строк готов
        ; =================== тело строки: ровно 768 v =====================
_beam_body:
        mov     a,m                     ; 8   A = color[i]
        inx     h                       ; 8   HL = &table[i+1]
        out     (0Ch)                   ; 12  луч в начале строки -> цвет всей строки
        inr     c                       ; 8   счётчик строк (256 → оборот в 0)
        REPT    NOP_PAD
        nop                             ; 4   заполнитель, флаги не трогает
        ENDR
        jnz     _beam_body              ; 12  пока C<>0 — следующая строка
        ; --- картинка (256 строк) проведена, выходим в гасящем интервале ---
bm_exit:
        ; frame_count++ (16-бит), чтобы gfx_next_frame продолжил работу:
        ; мы подменили isr_frame из startup.asm и должны сами вести счётчик.
        lxi     h,_frame_count
        mov     a,m
        inr     a
        mov     m,a
        jnz     f3_nowrap
        inx     h
        inr     m
f3_nowrap:
        pop     psw
        pop     h
        pop     d
        pop     b
        ei
        ret

; Примечание. Тело строки жёстко равно 768 v_cycles, поэтому гонка держится
; за лучом всю картинку 40..295; грубая задержка задаёт только фазу внутри
; первой строки (куда в строке попадёт OUT). OUT lands в левом бордюре/начале
; картинки — индекс под лучом всё равно 0, строка окрашивается целиком.
