; ============================================================================
; Функция: func_gen_level   (RANDOM PUTUP, Stage 2 — рантайм-генератор уровней)
; Вызов:   из lbl_title_key_poll на старте игры (после func_music_start_track,
;          перед JMP func_level_loader) — т.е. «по нажатию пробела», ОДИН раз.
;
; Идея (минимальные правки исходной игры): НЕ вводить новые RAM-буферы, а
;   ЗАПОЛНИТЬ ПЕРИМЕТРОМ/ПУСТОТОЙ уже существующие массивы прямо в ОЗУ:
;     * data_level_maps — 15 карт по 176 Б (row-major 16 колонок x 11 рядов),
;       карта N лежит по data_level_maps + N*0xB0 (так же их читает loader);
;     * data_level_params — 16 записей по 8 Б (описатель уровня: exit X/Y +
;       2 сущности state/X/Y); заполняем записи 1..15.
;   Образ грузится на 0x0100 в ОЗУ, поэтому обе таблицы перезаписываемы;
;   func_level_loader остаётся НЕТРОНУТЫМ и читает то, что написал генератор.
;
; Шаг 1–3 (каркас, без рандома): каждая карта — периметр стеной (тайл 0x02),
;   интерьер пустой/проходимый (тайл 0x01; байт карты = ИНДЕКС в data_tile_graphics,
;   0x01 — запись «4 пробела 0x20»); все описатели = шаблон уровня 1.
;
; Счётчики внешних циклов — в RAM (rgl_cnt): стек 8080 умеет только 16-битные
;   пары (PUSH/POP B|D|H|PSW), одиночные регистры (C/E) push-ить нельзя.
; Регистры не сохраняются (вызывающий их пересоздаёт). ШАГ 2: сюда же (по месту
;   карт) позже добавятся fire-сегменты/предметы/рандомный выход-враги через
;   func_prng — scratch-байты объявлены в rand_ram_symbols.asm.
; ============================================================================

func_gen_level:
    ; ---------------------------------------------------------------------
    ; 1) 15 карт: залить всё тайлом 0x01, затем периметр тайлом 0x02.
    ;    HL — курсор по tableau карт (176 Б подряд); rgl_cnt — счётчик карт.
    ; ---------------------------------------------------------------------
    LXI H, data_level_maps
    MVI A, 15
    STA rgl_cnt                         ; карт (data_level_01..15)
rgl_map_loop:
    PUSH H                              ; база текущей карты
    ; --- memset 176 -> 0x01 (пустая/проходимая клетка) ---
    MVI B, 176
rgl_mem_lp:
    MVI M, 01h
    INX H
    DCR B
    JNZ rgl_mem_lp                      ; HL = база + 176
    POP H                               ; HL = база карты (row0,col0)
    ; --- row0: 16 стен ---
    MVI B, 16
rgl_r0:
    MVI M, 02h
    INX H
    DCR B
    JNZ rgl_r0                          ; HL = row1,col0
    ; --- rows 1..9: col0 и col15 стены (interior остаётся 0x01) ---
    MVI E, 9                            ; E — счётчик рядов 1..9 (to15 его не трогает)
rgl_rn:
    MVI M, 02h                          ; col0
    MVI B, 15
rgl_to15:
    INX H
    DCR B
    JNZ rgl_to15                        ; HL = col15
    MVI M, 02h                          ; col15
    INX H                               ; HL = col0 следующего ряда
    DCR E
    JNZ rgl_rn                          ; HL = row10,col0
    ; --- row10: 16 стен ---
    MVI B, 16
rgl_r10:
    MVI M, 02h
    INX H
    DCR B
    JNZ rgl_r10                         ; HL = база + 176 = следующая карта
    LDA rgl_cnt
    DCR A
    STA rgl_cnt
    JNZ rgl_map_loop

    ; ---------------------------------------------------------------------
    ; 2) 15 описателей (записи 1..15): шаблон уровня 1.
    ; ---------------------------------------------------------------------
    LXI H, data_level_params+8          ; record 1 (record 0 = уровень 0, не исп.)
    MVI A, 15
    STA rgl_cnt                         ; записей
rgl_desc_loop:
    PUSH H                              ; база записи (HL будет двигать курсор)
    LXI D, rgl_desc                     ; источник — 8-байтный шаблон
    MVI B, 8
rgl_desc_cp:
    LDAX D                              ; A = (DE)
    MOV M, A                            ; (HL) = A
    INX D
    INX H                               ; HL = следующая копия
    DCR B
    JNZ rgl_desc_cp                     ; HL = база записи + 8 (следующая запись)
    POP D                               ; снять сохранённую базу (в DE, безвредно)
    LDA rgl_cnt
    DCR A
    STA rgl_cnt
    JNZ rgl_desc_loop

    ; ---------------------------------------------------------------------
    ; 3) ТЕСТОВЫЙ уровень 1 (Stage 2, шаг «каркас + набор элементов»).
    ;    Поверх каркаса кладём СПРОЕКТИРОВАННУЮ карту и описатель уровня 1.
    ;    Герой стартует (1,2), гравитацией падает на пол row9 и идёт ВПРАВО
    ;    (весь маршрут — по одному ряду пола, прыжки НЕ нужны):
    ;      * КЛЮЧ (яйцо 0x07) на клетке (9,3) — подбирается при проходе;
    ;      * ЗАМОК (тайл 0x08) в полу row10 на col6: герой стоит НАД ним
    ;        (клетка под ногами bufaddr+0x40 = TL 0x79) и по действию (key 5,
    ;        func_player_move_d/loc_106B) вставляет яйцо -> var_egg_seq++;
    ;      * при var_egg_seq==B (B=1 для lv<10) из описателя открывается ВЫХОД
    ;        (дверь) на клетке (9,10) — тот же ряд пола, достижим шагом вправо;
    ;      * ОГОНЬ (0x06) — полоса в воздухе (row5, cols5..10) как элемент
    ;        сложности: по ALGORITHM.MD §6 смертелен лишь при попадании ВНУТРЬ
    ;        клетки в фазе 0x75 (фаза 0xFE, наоборот, отталкивает/блокирует);
    ;      * ФРУКТЫ (0x0A/0x0B) на (9,13)/(9,14);
    ;      * 2 ВРАГА (state 1) патрулируют воздух (col5, rows 3 и 6).
    ;    176 Б rgl_map1 -> data_level_maps (карта уровня 1).
    ; ---------------------------------------------------------------------
    LXI H, rgl_map1
    LXI D, data_level_maps
    MVI B, 176
rgl_cp_map1:
    MOV A, M
    STAX D
    INX H
    INX D
    DCR B
    JNZ rgl_cp_map1
    ;    8 Б rgl_desc1 -> data_level_params+8 (запись уровня 1).
    LXI H, rgl_desc1
    LXI D, data_level_params+8
    MVI B, 8
rgl_cp_desc1:
    MOV A, M
    STAX D
    INX H
    INX D
    DCR B
    JNZ rgl_cp_desc1
    RET

; --- шаблон описателя = level 1: exit(X=14h,Y=10h); ent1(1,X=0Ah,Y=06h); ent2(1,X=0Ah,Y=0Ch)
rgl_desc:
    DEFB 014h, 010h, 001h, 00Ah, 006h, 001h, 00Ah, 00Ch

; --- ТЕСТОВАЯ карта уровня 1: 16x11 тайл-индексов. #=стена 02, .=пол 01,
;     ~=огонь 06, K=ключ-яйцо 07, L=замок 08, o/p=фрукт 0A/0B. Строка = ряд. ---
rgl_map1:
    DEFB 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h   ; ряд 0  (потолок)
    DEFB 02h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 02h   ; ряд 1
    DEFB 02h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 02h   ; ряд 2
    DEFB 02h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 02h   ; ряд 3
    DEFB 02h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 02h   ; ряд 4
    DEFB 02h, 01h, 01h, 01h, 01h, 06h, 06h, 06h, 06h, 06h, 06h, 01h, 01h, 01h, 01h, 02h   ; ряд 5  (огонь в воздухе)
    DEFB 02h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 02h   ; ряд 6
    DEFB 02h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 02h   ; ряд 7
    DEFB 02h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 02h   ; ряд 8
    DEFB 02h, 01h, 01h, 07h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 01h, 0Ah, 0Bh, 02h   ; ряд 9  (K@col3; дверь@col10; плоды@col13,14)
    DEFB 02h, 02h, 02h, 02h, 02h, 02h, 08h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h, 02h   ; ряд 10 (пол-стена; L=замок@col6)

; --- ТЕСТОВЫЙ описатель уровня 1: выход(X=14h=col10,Y=12h=row9);
;     ent1(state1,X=0Ah=col5,Y=06h=row3); ent2(state1,X=0Ah=col5,Y=0Ch=row6) ---
rgl_desc1:
    DEFB 014h, 012h, 001h, 00Ah, 006h, 001h, 00Ah, 00Ch
