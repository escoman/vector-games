def extract_glyphs(raw_data):
    """Extract glyph data from raw table. Each entry is 16 bytes."""
    glyphs = []
    for i in range(128):
        offset = i * 16
        normal = list(raw_data[offset:offset + 8])
        reversed_g = list(raw_data[offset + 8:offset + 16])
        glyphs.append({'normal': normal, 'reversed': reversed_g})
    return glyphs


def render_glyph_bmp(glyphs, num_glyphs, cols, filename, glyph_w=8, glyph_h=8, padding=1):
    """Render glyphs to 1-bit BMP file."""
    rows = (num_glyphs + cols - 1) // cols
    img_w = cols * (glyph_w + padding) + padding
    img_h = rows * (glyph_h + padding) + padding

    # BMP row size must be multiple of 4
    row_size = (img_w + 31) // 32 * 4
    pixel_data_size = row_size * img_h
    file_size = 54 + 8 + pixel_data_size  # headers + palette + pixels

    bmp = bytearray()

    # BMP file header (14 bytes)
    bmp += b'BM'
    bmp += struct.pack('<I', file_size)
    bmp += struct.pack('<HH', 0, 0)
    bmp += struct.pack('<I', 62)  # pixel data offset (14 + 40 + 8)

    # DIB header (40 bytes)
    bmp += struct.pack('<I', 40)
    bmp += struct.pack('<i', img_w)
    bmp += struct.pack('<i', img_h)
    bmp += struct.pack('<HH', 1, 1)  # 1 plane, 1 bpp
    bmp += struct.pack('<I', 0)  # no compression
    bmp += struct.pack('<I', pixel_data_size)
    bmp += struct.pack('<i', 3780)
    bmp += struct.pack('<i', 3780)
    bmp += struct.pack('<I', 2)
    bmp += struct.pack('<I', 0)

    # Color palette: 0=black, 1=white
    bmp += struct.pack('<BBBB', 0, 0, 0, 0)
    bmp += struct.pack('<BBBB', 255, 255, 255, 0)

    # Pixel data (bottom-up) — iterate by actual BMP scanlines
    for bmp_y in range(img_h - 1, -1, -1):
        row_bytes = bytearray(row_size)
        # Determine which logical row and scanline within glyph this BMP row is
        row_idx = bmp_y // (glyph_h + padding)
        local_y = bmp_y % (glyph_h + padding)
        if local_y < glyph_h:
            for col_idx in range(cols):
                glyph_idx = row_idx * cols + col_idx
                if glyph_idx >= num_glyphs:
                    continue
                glyph = glyphs[glyph_idx]['normal']
                x_off = padding + col_idx * (glyph_w + padding)
                byte_val = glyph[local_y] if local_y < len(glyph) else 0
                for x in range(glyph_w):
                    px = x_off + x
                    if px >= img_w:
                        continue
                    if byte_val & (0x80 >> x):
                        row_bytes[px >> 3] |= (0x80 >> (px & 7))
        bmp.extend(row_bytes)

    with open(filename, 'wb') as f:
        f.write(bmp)
    print(f"BMP: {filename} ({img_w}x{img_h}, {num_glyphs} glyphs, {cols} cols)")


def export_inc(glyphs, filename):
    """Export glyphs as z88dk .inc file."""
    with open(filename, 'w') as f:
        f.write("; Glyph table from putup.rom\n")
        f.write("; RAM address: 0x6400\n")
        f.write("; Each glyph: 8 bytes (8x8 pixels, bit 7 = leftmost)\n")
        f.write("; 128 entries, 16 bytes each (8 normal + 8 reversed)\n")
        f.write("; Only normal half exported here\n\n")
        f.write("FONT_TABLE_SIZE = 128\n\n")
        for i, g in enumerate(glyphs):
            if any(b != 0 for b in g['normal']):
                f.write(f"; Index {i}\n")
                f.write("    db ")
                f.write(", ".join(f"0x{b:02X}" for b in g['normal']))
                f.write("\n")
            else:
                f.write(f"; Index {i} (empty)\n")
                f.write("    db 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00\n")
    print(f"INC: {filename}")


def main():
    dest_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'dest')
    os.makedirs(dest_dir, exist_ok=True)

    glyphs = extract_glyphs(RAW_DATA)

    non_empty = sum(1 for g in glyphs if any(b != 0 for b in g['normal']))
    print(f"Total entries: {len(glyphs)}")
    print(f"Non-empty glyphs: {non_empty}")

    # Print glyph map
    for i, g in enumerate(glyphs):
        if any(b != 0 for b in g['normal']):
            preview = ''.join(f'{b:02X}' for b in g['normal'])
            print(f"  [{i:3d}] {preview}")

    # Render BMP (16 cols x 8 rows = 128 glyphs)
    bmp_path = os.path.join(dest_dir, 'glyphs.bmp')
    render_glyph_bmp(glyphs, 128, 16, bmp_path)

    # Export .inc
    inc_path = os.path.join(dest_dir, 'glyphs.inc')
    export_inc(glyphs, inc_path)


if __name__ == '__main__':
    main()
