;
; plane.asm — вывод и стирание сегментов в одной битовой плоскости
; Вектора-06Ц.
;
;   void gfx_plane_or(const unsigned char *src);
;   void gfx_plane_andn(const unsigned char *src);
;
; Обе работают только с плоскостью веса 1 (0xE000) — «плоскостью сегментов».
; Схема такая: фон занимает только чётные индексы палитры, то есть бит 0
; в нём сброшен везде. Тогда взвод бита 0 рисует сегмент поверх любого фона
; одним и тем же цветом (все нечётные индексы палитры заданы одинаково),
; а сброс бита 0 тем же массивом возвращает ровно тот индекс фона, что был
; до вывода. Поэтому один и тот же массив данных служит и для рисования,
; и для стирания — нейтральных патчей и теневого буфера не нужно.
;
; Формат src (готовит roms/games/nu_pogodi/tools/gen_assets.py):
;
;   [0] x0  — левый край прямоугольника, КРАТЕН 8
;   [1] y0  — верхняя строка
;   [2] wb  — ширина прямоугольника в байтах
;   [3] h   — высота в строках
;   [4..]   wb*h байт масок
;
; Порядок байт — колонками: сначала h байт колонки 0 сверху вниз, затем
; колонка 1 и так далее. Старший бит байта — левый пиксель.
;
; Адресация VRAM: блок = 256 байт = столбец из 8 пикселей (номер x/8),
; байт со смещением i в блоке хранит строку y = 255 - i, то есть строки
; идут сверху вниз с УМЕНЬШЕНИЕМ адреса. Отсюда обход колонки — это просто
; DEC HL: и ROM, и видеопамять читаются/пишутся линейно, без пересчёта
; адресов на байт. Переход к следующей колонке — INC номера блока.
;
; Требования к прямоугольнику (не проверяются):
;   - x0 кратно 8, иначе пиксели не совпадут с границами байтов;
;   - y0 + h <= 256, иначе DEC HL уйдёт за границу блока;
;   - x0 + wb*8 <= 256.
;
; Плоскость веса 1 должна быть активна в текущем виде экрана (в режиме
; GFX_MODE_256_16 — активна).
;
; Стоимость: 47 тактов на байт у OR и 51 у AND-NOT. Волк (6 байт x 67
; строк = 402 байта) выводится за ~19 КБ тактов при кадре 59904, то есть
; смена позы вместе со стиранием предыдущей съедает примерно кадр. Смены
; происходят не чаще игрового тика, а самый быстрый тик — каждые 5 кадров.
;
; Соглашение вызова z88dk classic: src лежит в 16-битном слоте по sp+2,
; стек чистит вызывающий, поэтому функция НЕ трогает SP и делает ret.
;
; Только 8080-инструкции.
;

        SECTION code_clib
        PUBLIC  _gfx_plane_or
        PUBLIC  _gfx_plane_andn

; ---------------------------------------------------------------
; void gfx_plane_or(const unsigned char *src)
;
; Выставить биты маски: показать сегмент.
; ---------------------------------------------------------------
_gfx_plane_or:
        call    pl_enter                ; DE = данные, B — колонки, C — строки
pl_loop_or:
        ld      a, (de)
        inc     de
        or      (hl)
        ld      (hl), a
        dec     hl
        dec     c
        jp      nz, pl_loop_or
        dec     b                       ; колонок осталось
        jp      nz, pl_reload_or
        ret
pl_reload_or:
        ld      a, (pl_blk)
        inc     a
        ld      (pl_blk), a
        add     a, 0xE0
        ld      h, a
        ld      a, (pl_itop)
        ld      l, a
        ld      a, (pl_rows)
        ld      c, a
        jp      pl_loop_or

; ---------------------------------------------------------------
; void gfx_plane_andn(const unsigned char *src)
;
; Снять биты маски: стереть сегмент, вернув индекс фона.
; ---------------------------------------------------------------
_gfx_plane_andn:
        call    pl_enter
pl_loop_andn:
        ld      a, (de)
        inc     de
        cma
        and     (hl)
        ld      (hl), a
        dec     hl
        dec     c
        jp      nz, pl_loop_andn
        dec     b
        jp      nz, pl_reload_andn
        ret
pl_reload_andn:
        ld      a, (pl_blk)
        inc     a
        ld      (pl_blk), a
        add     a, 0xE0
        ld      h, a
        ld      a, (pl_itop)
        ld      l, a
        ld      a, (pl_rows)
        ld      c, a
        jp      pl_loop_andn

; ---------------------------------------------------------------
; Чтение заголовка и подготовка первого прохода.
;
; Вход: SP — стек вызова, параметр src в слоте sp+2.
; Выход: DE — данные, HL — видеоадрес верхней строки нулевого блока,
;        B — число колонок, C — число строк, pl_blk — номер блока.
; AF, HL разрушаются. Внутри использует CALL, то есть сам видит src
; на sp+4 (плюс адрес возврата).
; ---------------------------------------------------------------
pl_enter:
        ld      hl, 4                   ; sp+2 — src, ещё +2 — адрес возврата
        add     hl, sp
        ld      e, (hl)
        inc     hl
        ld      d, (hl)         ; DE = src
        ld      a, (de)         ; x0
        inc     de
        rrca
        rrca
        rrca                    ; /8 — номер начального блока
        ld      (pl_blk), a
        ld      a, (de)         ; y0
        inc     de
        cpl                     ; 255 - y0 — смещение верхней строки в блоке
        ld      (pl_itop), a
        ld      a, (de)         ; wb
        inc     de
        ld      b, a
        ld      a, (de)         ; h
        inc     de
        ld      (pl_rows), a
        ld      c, a
        ld      a, (pl_blk)
        add     a, 0xE0
        ld      h, a
        ld      a, (pl_itop)
        ld      l, a
        ret

; ---------------------------------------------------------------
; Рабочие переменные.
; ---------------------------------------------------------------
pl_blk:         defb    0       ; текущий номер блока (x/8)
pl_itop:        defb    0       ; смещение верхней строки в блоке (255-y0)
pl_rows:        defb    0       ; строк в колонке
