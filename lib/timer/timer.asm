;
; timer.asm — «секундомер растра» на КР580ВИ53, канал 2 (порт 09h).
; lib/timer — стандартный модуль библиотеки (образец: exolon,
; roms/redesign/exolon/reports/Summary.md §1, §14; первая реализация —
; демо roms/demos/mario-timer, откуда этот модуль и вынесен в библиотеку).
;
; Идея. Прерывание VBlank (RST 7, ~50 Гц) совпадает с концом сканирования
; лучом видимой части экрана. Если на каждом VBlank перезапускать счётчик
; канала 2 значением, равным ровно одному кадру, счётчик становится
; «секундомером кадра»: он линейно убывает вместе с лучом, и по его
; значению всегда видно, дошёл ли луч до опасной зоны или ещё нет. Никаких
; прерываний для самого луча не нужно — фаза держится один раз на кадр.
;
; Числа сняты с модели beam_state vector-debugger:
;   frame_v_cycles = 239616, line_v_cycles = 768, frame_lines = 312;
;   ВИ53 тактирован 1.5 МГц = 12 МГц / 8  =>  96 тиков таймера на строку;
;   один кадр = 312 * 96 = 29952 = 0x7500.
; Период 0x7500 при такте 1.5 МГц в точности равен частоте кадра, поэтому
; счётчик, запущенный в VBlank, остаётся в фазе с лучом весь кадр.
;
; ПОЧЕМУ КАНАЛ 2. Порт 09h = канал 2 = «3-й канал» (нумерация Вектора:
; 0 = 0Bh, 1 = 0Ah, 2 = 09h). Звуковые движки библиотеки (music.c, sound.c,
; sfx.c) используют каналы 0 и 1, когда их ограничить маской
; music_set_channel_mask(0x03) / sfx_set_channel_mask(0x03); канал 2 при
; этой маске свободен таймеру полностью.
;
; ПОЧЕМУ РЕЖИМ 0, А НЕ 3. Режим 3 — генератор меандра (им музыка на ВИ53 и
; делает тон: vi53.c, vi53_m3[]). Канал 2 выведен на динамик, поэтому меандр
; на 0x7500 (~25 Гц) = непрерывный гул. Кроме того в режиме 3 счётчик убывает
; на 2 за такт и САМ перезагружается на нуле, то есть примерно на середине
; кадра обнуляется и стартует заново — «elapsed» переполняется, и монотонность
; теряется. Режим 0 — одноразовый счёт: OUT = 0 (тишина), убывание на 1 за
; такт, без авто-перезагрузки; досчитывает до 0 ровно к следующему VBlank,
; где его перезапускают сами. Монотонно и беззвучно.
;
; Функции (8080, SECTION code_clib):
;   timer_start       — пуск счётчика канала 2 на полный кадр (0x7500):
;                       CW mode0, OUT 09h lo, OUT 09h hi. Зовётся из кадрового
;                       ISR на каждом VBlank — так счётчик весь кадр идёт в
;                       фазе с лучом.
;   timer_start_sync  — то же, но сначала однократная привязка к прерыванию:
;                       EI; HLT; пуск. Луч ловится на ближайшем VBlank, и
;                       таймер стартует ровно в начале кадра. Для программ,
;                       которые после этого работают поллингом (как exolon).
;                       Требует работающих прерываний (их включает
;                       lib/sys/startup.asm до вызова main).
;   timer_read        — защёлкнуть канал 2 (CW latch RL=00) и вычитать 16-
;                       битный остаток: сначала младший байт, потом старший.
;                       Возврат в HL (C: unsigned int).
;   timer_elapsed     — сколько тиков таймера луч уже прошёл с начала кадра,
;                       то есть TIMER_FULL - остаток. Возврат в HL.
;   timer_wait        — спин до нужного значения счётчика (unsigned int value,
;                       __z88dk_callee): выходит, как только остаток станет не
;                       больше value, ИЛИ если счётчик успел перезагрузиться
;                       (пересекли VBlank, окно кадра упущено — возврат
;                       немедленно, рисовать надо сейчас).
;
; Из ISR безопасен только timer_start (три OUT, каждый атомарен, без di/ei:
; лишний ei разрешил бы повторный вход в прерывание посреди ISR). timer_read,
; timer_elapsed и timer_wait — из основного цикла; спин в ISR означал бы
; пропущенные кадры.
;
; Только 8080-инструкции: без jr/djnz и без префиксов CB/DD/ED/FD.
;

        SECTION code_clib
        PUBLIC  _timer_start
        PUBLIC  _timer_start_sync
        PUBLIC  _timer_read
        PUBLIC  _timer_elapsed
        PUBLIC  _timer_wait

TIMER_FULL    EQU 0x7500        ; 29952 = один кадр при 96 тиках на строку
CW_CH2_M0     EQU 0xB0          ; канал 2, режим 0 (OUT=0 тишина, счёт -1)
CW_CH2_LATCH  EQU 0x80          ; канал 2, RL=00 — команда защёлки для чтения

; ---------------------------------------------------------------
; void timer_start(void)
;   Пуск счётчика канала 2 на полный кадр в режиме 0.
; ---------------------------------------------------------------
_timer_start:
        mvi     a, CW_CH2_M0
        out     08h                     ; управляющее слово: канал 2, режим 0
        mvi     a, TIMER_FULL & 0xFF    ; 0x7500: младший байт 00h
        out     09h
        mvi     a, TIMER_FULL >> 8      ; старший байт 75h
        out     09h                     ; загрузка => старт отсчёта кадра
        ret

; ---------------------------------------------------------------
; void timer_start_sync(void)
;   Пуск, привязанный к фазе луча: EI; HLT; timer_start.
;   HLT будит кадровое прерывание (RST 7), то есть продолжение идёт после
;   него — в самые первые такты нового кадра; таймер стартует синфазно с
;   лучом.
;   Прерывания оставляем включёнными: движок библиотеки (frame_count,
;   frame_handler, sound) на них и держится. ROM, который хочет дальше
;   работать только поллингом (схема exolon), делает DI сам сразу после.
; ---------------------------------------------------------------
_timer_start_sync:
        ei
        halt                            ; спать до ближайшего VBlank
        jp      _timer_start            ; и в этой же фазе запустить счётчик

; ---------------------------------------------------------------
; unsigned int timer_read(void)   -> HL
;   Защёлкнуть и прочитать 16-битный ОСТАТОК счётчика канала 2.
;   Больше значение => луч выше (только что после VBlank), меньше => ниже.
; ---------------------------------------------------------------
_timer_read:
        mvi     a, CW_CH2_LATCH
        out     08h                     ; защёлка канала 2 (снимок счётчика)
        in      09h                     ; младший байт
        ld      l, a
        in      09h                     ; старший байт
        ld      h, a
        ret

; ---------------------------------------------------------------
; unsigned int timer_elapsed(void)   -> HL
;   Сколько тиков луч уже ПРОШЁЛ с начала кадра = TIMER_FULL - остаток.
;   Перезагрузку счётчика (VBlank внутри кадра) не различает: значение
;   всегда в пределах 0..TIMER_FULL, сравнение с ним корректно и сразу
;   после старта кадра, и перед самым его концом.
; ---------------------------------------------------------------
_timer_elapsed:
        call    _timer_read             ; HL = остаток
        ; Разность считаем снизу вверх: младший байт, затем старший с заёмом.
        mvi     a, TIMER_FULL & 0xFF    ; 00h
        sub     l                       ; 00h - младший байт остатка
        ld      l, a
        mvi     a, TIMER_FULL >> 8      ; 75h
        sbc     h                       ; старший байт с заёмом
        ld      h, a
        ret

; ---------------------------------------------------------------
; void timer_wait(unsigned int value)   __z88dk_callee
;   Спин до значения счётчика: выход, когда ОСТАТОК <= value.
;
;   value — это именно значение таймера (обратный отсчёт), а не строка
;   растра; от строки y его переводят макросы v06.h:
;       timer_wait(TIMER_REMAIN(TIMER_LINES(y)));
;
;   Второй выход — перезагрузка счётчика: если value оказался уже пройден
;   в ЭТОМ кадре (луч ушёл ниже нужной строки раньше, чем мы досчитали),
;   ждать следующий кадр бессмысленно — окно упущено, возвращаемся
;   немедленно. Благодаря этому функция всегда завершается внутри кадра
;   и никогда не зависает, в том числе при value = 0 (счётчик до нуля не
;   доживает — ISR перезапускает его).
;
;   Соглашение sccz80 __CALLEE__: слово аргумента лежит под адресом
;   возврата, аргументы со стека снимает сама функция (pop + push адреса
;   возврата), поэтому ret обычный, без adjustment.
; ---------------------------------------------------------------
_timer_wait:
        pop     bc                      ; адрес возврата
        pop     de                      ; DE = value
        push    bc                      ; адрес возврата на место

        call    _timer_read             ; HL = первый снимок
        ld      b, h                    ; BC = предыдущий снимок
        ld      c, l
tw_loop:
        call    _timer_read             ; HL = текущий остаток
        ; --- HL <= value ? (оба значения < 0x8000, знак не мешает) ---
        ld      a, h
        sub     d
        jp      c, tw_done              ; HL < value
        jp      nz, tw_wrap             ; HL > value
        ld      a, l
        sub     e
        jp      c, tw_done              ; HL < value
        jp      z, tw_done              ; HL = value
        ; --- HL > value: не перезагрузился ли счётчик по дороге? ---
        ; HL > value, значит осталось понять, вырос ли HL относительно
        ; предыдущего снимка BC (внутри кадра счётчик только убывает).
tw_wrap:
        ld      a, h
        sub     b
        jp      c, tw_advance           ; старше: HL < prev — считаем дальше
        jp      nz, tw_done             ; HL > prev — была перезагрузка, поздно
        ld      a, l                    ; старшие байты равны, решают младшие
        sub     c
        jp      nc, tw_done             ; HL > prev — перезагрузка, поздно
        ; HL <= prev — обычный ход счётчика (равенство бывает, если два
        ; чтения уложились в один тик таймера)
tw_advance:
        ld      b, h                    ; предыдущий снимок = текущий
        ld      c, l
        jp      tw_loop
tw_done:
        ret
