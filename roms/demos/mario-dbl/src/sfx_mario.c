/*
 * sfx_mario.c — звуковые эффекты демки Mario double-buffering.
 *
 * Вывод тона — КР580ВИ53 (sfx.c -> vi53_set_channel). Шумогенератора у ВИ53
 * нет, поэтому ветра при беге нет: mario_sfx_running держится только как
 * зеркало флага бега из main (на случай будущих эффектов).
 *
 * Прыжок и приземление — тональные свипы через 3-голосный смеситель sfx.c
 * (таблица шагов sfx_step_t: нота + detune + тики).
 *
 * Свипы сделаны ЛЕСТНИЦЕЙ из коротких шагов по 1 кадру, а не большим detune:
 * на ВИ53 detune — 16-битный делитель, там detune силён и дал бы резкий скачок
 * тона за кадр. Лестница нот звучит ровнее.
 */

#include "v06.h"

/* ------------------------- ТОНАЛЬНЫЕ ЭФФЕКТЫ ---------------------------- */

/* Прыжок: звенящий «цзинг» — восходящий мажорный арпеджио + shimmer на
 * вершине (чередование через терцию туда-обратно). Всё по 1 кадру. Приоритет 60. */
static const sfx_step_t step_jump[] = {
    { N_C(6), 0, 1 },   /* 1046 Гц — подъём */
    { N_E(6), 0, 1 },   /* 1318    */
    { N_G(6), 0, 1 },   /* 1568    */
    { N_C(7), 0, 1 },   /* 2093    */
    { N_G(7), 0, 1 },   /* 3136 Гц — вершина */
    { N_E(7), 0, 1 },   /* 2637    */
    { N_G(7), 0, 1 },   /* 3136    shimmer: терция туда-обратно */
    { N_C(7), 0, 1 },   /* 2093    */
    { N_G(7), 0, 1 },   /* 3136    */
    { N_E(7), 0, 1 },   /* 2637    */
};
static const sfx_t fx_jump = { step_jump, 10, 60 };

/* Приземление: короткий низкий «чпок» — 2 ноты вниз по 1 кадру (~40 мс),
 * без затухающего хвоста. Приоритет 30 — ниже прыжка. */
static const sfx_step_t step_land[] = {
    { N_C(4), 0, 1 },   /* 262 Гц */
    { N_G(3), 0, 1 },   /* 196    */
};
static const sfx_t fx_land = { step_land, 2, 30 };

/* ------------------------------- API ------------------------------------ */
/*
 * Звук живёт в КАДРОВОМ ПРЕРЫВАНИИ (frame_handler = mario_frame в main.c),
 * но ПОСЛЕ смены палитры: обработчик сначала грузит палитру (v06_set_palette_isr
 * — raster-критично, в самом начале гасения), и только потом зовёт
 * mario_sfx_frame(). Так долгий звук не сдвигает палитрный цикл за blanking
 * (нет бегущих полос), а сам звук пишет только свои порты (ВИ53 0x08-0x0B),
 * не трогая 02/0C. Движок играет ровно один такт за VBlank (50 Гц) — темп
 * честный даже на проспавшихся кадрах, догон цикла не трогает.
 *
 * Из main-контекста тут дёргаются ТОЛЬКО байтовые флаги (req_*) — записи
 * атомарны на 8080; сам движок (sfx_play/sfx_tick) трогается исключительно из
 * ISR, поэтому гонки за полуживое состояние нет.
 */

unsigned char mario_sfx_running;         /* флаг бега (зеркало из main)          */
static volatile unsigned char req_jump;  /* 1 = запросить эффект прыжка в ISR       */
static volatile unsigned char req_land;  /* 1 = запросить эффект приземления        */

/* Инициализация тонального движка sfx.c. */
void mario_sfx_init(void)
{
    mario_sfx_running = 0;
    req_jump = 0;
    req_land = 0;
    sfx_init();
}

/* Запросить эффект прыжка: только флаг, исполнит ISR (mario_sfx_frame).
 * Прямой sfx_play из main конфликтовал бы с движком, играющим в прерывании. */
void mario_sfx_jump(void)
{
    req_jump = 1;
}

/* Запросить эффект приземления. */
void mario_sfx_land(void)
{
    req_land = 1;
}

/* Кадровый движок звука — зовётся ИЗ frame_handler (в прерывании), строго
 * ПОСЛЕ загрузки палитры. Сначала разгребает пост-запросы эффектов (запуск
 * свипа идёт здесь, в ISR-контексте — единственный владелец движка), затем
 * досчитывает тональные голоса. Никаких ei/halt/di:
 * мы уже в ISR (повторный ei открыл бы окно реентерабельного входа). */
void mario_sfx_frame(void)
{
    if (req_jump) { req_jump = 0; sfx_play(&fx_jump); }
    if (req_land) { req_land = 0; sfx_play(&fx_land); }

    sfx_tick();
}
