; Функция: func_set_tile_buf
; Адрес:   0x4500 (номинальный: файла в оригинале нет, это emit проекта E1;
;           реальное размещение — tools/order.json / tools/layout.json)
; Размер:  ~25 байт
; Описание: Записать тайл 2x2 в ТЕКСТОВЫЙ БУФЕР, НЕ трогая VRAM. Вход: HL =
;           указатель графики тайла (4 байта-глифа), D = колонка, E = строка —
;           тот же контракт, что у func_draw_tile_to_buf.
;
;           ШАГ E1 (плавная анимация врагов): состояния сущностей 1..8 вызывают
;           ЭТУ функцию вместо func_draw_tile_to_buf. Отличия ровно два:
;             1) нет немедленного блита в VRAM — func_draw_char_at_hl
;                (func_put_char -> fall-through func_render_glyph) здесь заменён
;                прямой записью MOV M,A. Именно этот блит делал врага
;                клетко-гранулярным; теперь вид врага рисует func_enemy_render
;                каждый hw-кадр, догоняя цель по 4 px.
;             2) запись безусловно-повторная (без CMP M / RZ из func_put_char).
;                Содержимое буфера от этого не меняется, а «не перерисовать, если
;                код тот же» здесь и не нужно — перерисовку теперь выбирает
;                рендерер по своему кэшу кодов.
;
;           Обход клеток побайтово совпадает с func_draw_tile_to_buf:
;           (col,row), (col+1,row), (col,row+1), (col+1,row+1) — шаг строки
;           LXI B,001Fh; DAD B от (col+1,row). Буфер остаётся источником истины
;           для коллизий героя и скана огня: его содержимое, темп шага и логика
;           состояний НЕ изменены вообще.
;
;           Прозрачность как у func_draw_tile_to_buf: сохраняет BC и HL.

func_set_tile_buf:
    PUSH B                      ;
    PUSH H                      ; сохранить указатель графики тайла
    CALL func_coords_to_textbuf ; (D=col,E=row) -> HL = клетка в буфере
    POP D                       ; DE = указатель графики тайла
    LDAX D                      ; код [0]
    MOV M, A
    INX D
    INX H                       ; -> (col+1,row)
    LDAX D                      ; код [1]
    MOV M, A
    INX D
    LXI B, 001Fh
    DAD B                       ; -> (col,row+1)
    LDAX D                      ; код [2]
    MOV M, A
    INX D
    INX H                       ; -> (col+1,row+1)
    LDAX D                      ; код [3]
    MOV M, A
    POP B
    RET
