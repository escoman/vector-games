; Функция: func_put_char
; Адрес: 0x0800
; Размер: 3 байта
; Описание: Запись символа A в текстовый буфер по (HL) с проверкой изменения:
;           CMP M (сравнить с текущим); RZ — выход если символ не изменился;
;           MOV M, A — записать новый код. НЕ имеет собственного RET: управление
;           проваливается (fall-through) в func_render_glyph @0x0803, которая
;           рисует глиф и выполняет общий RET. Вызывается из func_print_char_at_ptr.

func_put_char:
    CMP M                       ; 0x0800
    RZ                          ; 0x0801
    MOV M, A                    ; 0x0802 — fall-through в func_render_glyph
