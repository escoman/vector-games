/*
 * mode.c — управление видеорежимами Вектора-06Ц.
 *
 * Центральный модуль графики: хранит текущий режим, переключает
 * режимы (ПИА + скролл), предоставляет унифицированные функции
 * очистки и загрузки палитры.
 *
 * По умолчанию — режим 0 (256x256, 16 цветов): аппаратный режим
 * Вектора-06Ц при старте программы.
 */

#include "v06.h"

/* --------------------------- Таблица режимов ------------------------- */

const gfx_mode_t gfx_modes[] = {
    /* mode 0: 256x256, 16 цветов, все 4 плоскости */
    { 32, 0x0F, 16 },
    /* mode 1: 256x256, 2 цвета, плоскость 0xE000 */
    { 32, 0x01,  2 },
    /* mode 2: 512x256, 4 цвета, все 4 плоскости (бит 0: E000+A000,
     * бит 1: C000+8000). mask 0x0F: заполняем все, чтобы бит 1 = 0
     * при очистке. Иначе после смены режима остаётся мусор. */
    { 64, 0x0F,  4 },
    /* mode 3: 512x256, 2 цвета, плоскости 0xE000+0xA000.
     * mask 0x0F: заполняем все 4 плоскости, чтобы бит 1 (C000/8000)
     * гарантированно = 0. Иначе после смены режима остаётся мусор. */
    { 64, 0x0F,  2 },
};

unsigned char gfx_current_mode = 0;  /* аппаратный режим при старте */

/* ------------------------ Переключение режима ----------------------- */

/* asm-функции из v06pal.asm и clr.asm */
extern void v06_set_mode_bit(unsigned char val);
extern void graph_fill_plane(unsigned char mask, unsigned char fill);
extern void v06_set_palette_asm(const unsigned char *pal);

void gfx_set_mode(unsigned char mode)
{
    gfx_current_mode = mode;

    if (gfx_modes[mode].width_div8 > 32) {
        /* 512x256: ПИА + скролл 0xFF */
        v06_out(V06_PIA_CW, 0x88);      /* ПИА: PA вход, PB выход */
        v06_set_mode_bit(0x10);          /* бит 4 = режим, бордюр сохранён */
        v06_out(V06_PIA_PA, 0xFF);       /* скролл = 0xFF */
    }
    /* 256x256: не трогаем — аппаратный режим по умолчанию */
}

/* ------------------------- Очистка экрана --------------------------- */

/* asm-функция заполнения плоскостей по маске (clr.asm) */

void gfx_clear(unsigned char color)
{
    graph_fill_plane(gfx_modes[gfx_current_mode].plane_mask, color);
}

/* ------------------------- Загрузка палитры ------------------------- */

/* asm-загрузчик 16 цветов палитры (v06pal.asm) */

void gfx_set_palette(const unsigned char *colors)
{
    unsigned char full[16];
    const gfx_mode_t *m = &gfx_modes[gfx_current_mode];
    unsigned char i;

    if (m->num_colors == 16) {
        /* 256x256, 16 цветов: прямое копирование */
        for (i = 0; i < 16; i++)
            full[i] = colors[i];
    } else {
        /*
         * 2 или 4 цвета: расширяем до 16 слотов, маскируя
         * неиспользуемые плоскости.
         *
         * Логика: палитра Вектора индексируется 4-битным значением
         * пикселя. Каждый бит значения — плоскость VRAM. Активные
         * плоскости определяются plane_mask. Неактивные плоскости
         * всегда 0 в VRAM, поэтому биты неактивных плоскостей в
         * индексе палитры всегда 0.
         *
         * Для каждого из 16 слотов: биты, соответствующие активным
         * плоскостям, формируют индекс в массиве colors[]. Биты
         * неактивных плоскостей в слоте должны давать тот же цвет,
         * что и при нулевых битах (т.к. VRAM в этих плоскостях = 0).
         * Проще: все слоты с одинаковыми активными битами → один
         * цвет из colors[].
         *
         * Пока не реализовано: требуется аппаратная проверка
         * соответствия plane_mask и битовых позиций палитры.
         */
        for (i = 0; i < 16; i++)
            full[i] = colors[0];  /* заглушка: все чёрные */
    }

    v06_set_palette_asm(full);
}
