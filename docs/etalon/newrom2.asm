;
        .ORG     0000H   ;начальный адрес программы
                        ;загрузчик с магнитной ленты
;
STEK:   .EQU     0DCF0H  ;адрес вершины стека
ABUFF:  .EQU     0DED0H  ;нач. адрес временного
                        ;буфера ввода 35 байт
PRINV:  .EQU     ABUFF+36;признак инверсии канала
                        ;ввода/вывода с магн.ленты
CONR:   .EQU     ABUFF+38;адрес константы считывания
VAR:    .EQU     ABUFF+39
MASK:   .EQU     00010000B       ;бит ввода с мг.
;
;инициализация портов ввода/вывода
;
        MVI     A,088H  ;A,B,C (3-0) - вывод, C (7-4) - ввод
        OUT     00      ;рег.режимов ик55
        MVI     A,081H  ;A,B,C (7-4) - вывод, C (3-0) - ввод
        OUT     04      ;запись в рег.режимов паралл.интерф.
        MVI     A,0FFH  ;
        OUT     03      ;входы ие7 = 0FFH
        OUT     05      ;порт (C) паралл. интерфейса = 0FFH
        OUT     06      ;порт (B) --//--
        OUT     07      ;порт (A) --//--
        MVI     A,08H   ;
        STA     CONR    ;нач.конст.чтения (см. RST7)
;
;выключение каналов звука
;
        MVI     A,0A8H  ;реж-4,ст.байт-(одновибратор)
        LXI     B,40H   ;запись в три таймера (C=40H-использ.
                        ;еще и как маска в выделении клав. "ус")
RTIM:   OUT     08H     ;реж-4,ст.байт
        SUB     C       ;счет каналов 2,1,0
        JNC     RTIM    ;переход если не все
                        ;каналы таймера выключены
;
        IN      01      ;пров.нажатия "ус"
        ANA     C       ;выделение "ус" (C=40H - маска)
        MOV     C,B     ;C=B - 0
        JZ      NOCLEA  ;озу не обнулять.
        XRA     A       ;A=0
        OUT     01      ;вкл.мотор,погасить рус.
CLEA1:  STAX    B       ;зап. "00"
        INX     B
        STAX    B
        INX     B
        CMP     C
        JNZ     CLEA1
        CMP     B
        JMP     PROD    ;обойти RST7
;
;подпр.обработки прерывания RST7
;
        LDA CONR        ;A=конст.чтения мл.
DELAY:  DCR     A
        JNZ     DELAY
REATP:  IN      01      ;чт.мл.
        ANI     MASK    ;выделение бит мл.
        MOV     E,A     ;E=рез.чт.
        RET
;
PROD:   JNZ     CLEA1   ;
                ;сначала проверим озу по адр.=SP
;
NOCLEA: LXI     SP,STEK ;уст.адр.стека загрузчика
        LXI     D,055AAH        ;контр.код.
TESTM:  PUSH    D       ;запись
        POP     H       ;считывание
        MOV     A,L     ;
        CMA             ;
        CMP     H       ;
        JNZ     TESTM   ;если не равны повторить
        LXI     D,09H
                        ;C=B=0 из предистории
CLEA3:  MOV     H,B     ;H=B
        MOV     L,D     ;L=0
        CALL    AKART   ;HL=адр.карты загрузки
        DCR     L       ;на ед.ниже
        MVI     M,0FFH  ;зап.нижней черточки
        DAD     D       ;HL=адр.верх.
        MVI     M,0FFH  ;зап.верх.черточки
        INR     L       ;на ед.выше
        MVI     M,81H   ;запись меток блоков
        INR     B       ;еще есть ?
        JNZ     CLEA3   ;?
;
;запишем в озу цветогенератора
;следующую таблицу:
;-----------------------------
;       адрес - цвет
;-----------------------------
; 0     0000 - синий
; 1     0001 - синий
; 2     0010 - желтый
; 3     0011 - желтый
; 4     0100 - синий
; 5     0101 - синий
; 6     0110 - желтый
; 7     0111 - желтый
; 8     1000 - синий
; 9     1001 - синий
; A     1010 - желтый
; B     1011 - желтый
; C     1100 - синий
; D     1101 - синий
; E     1110 - желтый
; F     1111 - желтый
;-----------------------------
; итак
        MVI     H,10000000B     ;код синего
        MVI     D,00101101B     ;желтый
        LXI     B,80FH  ;кол.двойных записей,нач.адр.озу цвета
WRCLR:  XRA     A       ;запись нулевого
        OUT     02      ;адреса озу
        EI              ;разрешение и
        HLT             ;ожидание прерывания
        MOV     A,C     ;запись
        OUT     02      ;адреса озу
        MOV     A,D     ;A=коду цвета
        OUT     0CH     ;запись
        DCR     C       ;след.адрес озу
        MOV     A,C     ;
        OUT     02      ;
        MOV     A,D     ;
        OUT     0CH     ;
        DCR     C       ;
        XCHG            ;B <-> D - другой цвет
        DCR     B       ;
        JNZ     WRCLR   ;повторять до конца
        CALL    LOADF   ;ввод с ленты в формате загрузчика
INTE:   EI              ;разрешение
        HLT             ;и ожидание прерывания
        INR     C       ;счет времени
        PUSH    B       ;
        POP     B       ;вывод счетчика в экран по адр. SP
        MOV     A,C     ;A=тек.времени
        ANI     00001000B       ;маскировка всех кроме рус/лат
        ORI     00000010B       ;установка D[1]=1 выкл.мотора
        OUT     01      ;вывод в порт "C"
        JMP     INTE    ;повторять без конца
                        ;(здесь ожидание
                        ;дальнейших действий оператора)
;
;ввод файла с мл. в озу
;
LOADF:
;
;опред.конст.чтения CONR.
;
RCON3:  CALL    TSBIT   ;опред.ср.вр.между бит.
RCON1:  MOV     D,A     ;D=длит.бита
        ORA     A       ;гашение переноса
        RAR             ;T/2
        MOV     E,A     ;
        ADD     D       ;T верхн.=T+T/2
        MOV     H,A     ;H=верхн.граница
        CALL    TSBIT   ;следующ.ср.время
        CMP     H       ;сравнение с верхн.
        JC      RCON1   ;в границах ?
RCON2:  ADD     D       ;A=0.25T+0.5T
        STA     CONR    ;занести конст.чтения
;проверим константу чтения
        MVI     E,12    ;считать 12 байт кодов 055H
LOA21:  MVI     A,8     ;ввести с мг.без бс=0E6H
        CALL    MITAP   ;п/п ввода байта с мг.
        CPI     055H    ;
        JZ      LOA11   ;тогда продолжить
        CPI     0AAH    ;
        JNZ     LOADF   ;оPределить CONR снова
LOA11:  DCR     E       ;счет введ.байт
        JNZ     LOA21   ;еще есть?
                        ;
LOA111: CALL    READB   ;ввод блока 35 байт
        MOV     E,A     ;е=кс блока (имени бл.данн.)
        MOV     A,M     ;перв.байт
        CPI     00H     ;не равен 0
        JNZ     LOA111  ;тогда это не заголовок
        LXI     H,ABUFF+33      ;(HL)=адр.тек.блока
        MOV     A,M     ;
        DCX     H       ;(HL)=числу блоков
        CMP     M       ;если не рабны то
        JNZ     LOADF   ;блок не начальный
        MOV     D,A     ;D=числу блоков в файле
        DCX     H       ;(HL)=нач.адресу загрузки
        MOV     B,M     ;B=ст.б.нач.адр.
LOA13:  CALL    READB   ;чит.блок с мл.
;
;вычисл.адр.загр.в озу из ном.бл.данных
;
        PUSH    PSW     ;
        MOV     A,M     ;A=перв.байту
        CPI     00H     ;если 0 то это
        JZ      LOA12   ;заголовок
        ADD     A       ;умнож.на 32
        ADD     A       ;
        ADD     A       ;
        ADD     A       ;
        ADD     A       ;
        MOV     C,A     ;мл.байт нач.адр.
        POP     PSW     ;
        INX     H       ;
        MOV     A,M     ;кс блока заголовка
        CMP     E       ;сравнение со старой кс заголовка
        JNZ     LOA13   ;да,новый блок (не загружать на старое место)
        PUSH    D       ;
        PUSH    B       ;пересылка 32 байт
        INX     H       ;HL=нач.данных
        LXI     D,207EH ;из буфф. в озу
LOA14:  MOV     A,M     ;взять из буфф.
        STAX    B       ;поместить в озу
        LDAX    B       ;взять из озу
        XRA     M       ;
        MOV     M,A     ;уст.ошибку в буфф.
LOA15:  INX     H       ;ABDUFF=ABDUFF+1
        INR     C       ;A озу= A озу+1
        DCR     D       ;счет байт
        JNZ     LOA14   ;D<>0
        POP     B       ;восст.(BC)
        MOV     L,C     ;(BC)=(HL)
        MOV     H,B     ; --//--
                        ;
        CALL    AKART   ;рассчет адр.карты заг.
                        ;HL=адр.для метки заг.
                        ;
        MOV     M,E     ;метка блока как загруж.
        POP     D       ;
        CALL    TESTL   ;п/п пров.загр.256 байт
        JZ      LOA13   ;дозагрузить!
        MOV     A,D     ;D-кол-во незаг. блоков
        CPI     01H     ;последний?
        JNZ     LOA13   ;нет.есть еще!
;
;A=D=1 - загружены все блоки
;
        RET             ;конец загрузки файла
;
;если это заголовок
;
LOA12:  POP     PSW     ;
        SUB     E       ;сравн.с прошлой кс
        JZ      LOA13   ;это тот же блок
        INR     A       ;
        JNZ     0000H   ;конец "пропуск блоков"
LOA19:  CALL    TESTL   ;пред.блок загруж.?
        JZ      0000H   ;конец "блок потерян"
                        ;перезапуск загрузчика
                        ;
        DCR     E       ;новое имя блока данных
        INR     B       ;адр.след.блока
        DCR     D       ;число незаг.блоков
        JMP     LOA13   ;продолжить загрузку
;
;п/п проверки загрузки 256 байтного блока
;
TESTL:  MVI     L,00H   ;
        MOV     H,B     ;HL=B,0
        CALL    AKART   ;п/п определения карты загрузки
LOA20:  MOV     A,M     ;0-блок не загружен
        ANA     A       ;уст. "Z"
        RZ              ;один из восьми блоков не загружен
        INX     H       ;след.адр.карты загр.
        CPI     081H    ;81 - верхний огран.карты
        JNZ     LOA20   ;еще есть?
        ANA     A       ;уст. "Z"
        RET             ;
;
;п/п определения
;адреса карты загр. HL=адр.
;
AKART:  PUSH    D       ;
        MOV     A,L     ;мл.байт
        RLC             ;разр.7-5 поместить
        RLC             ;на место 2-0 разр.
        RLC             ;
        MOV     L,A     ;врем.сохр.
        MOV     A,H     ;ст.байт
        RAR             ;на бит вправо
        ANI     70H     ;выделить разр.6-4
        MOV     D,A     ;умножить на 1.5
        RAR             ;/2
        ADD     D       ;I+I/2
        ADD     L       ;+мл.байт (2-0 р)
        ADI     18H     ;+смещение по "Y"
        MOV     L,A     ;запомнить мл.байт
        MOV     A,H     ;взять ст.байт
        ANI     1FH     ;маск.использ.разр.
        ADI     0C0H    ;поместить в экран-3
        MOV     H,A     ;ст.байт
        POP     D       ;
        RET             ;HL=адр.экр.(карт.)
;
;*** подпрограммы для чтения с мл ***
;
;п/п определения времени (T=(A))
;между битами в записи на мл.
;
TBIT:   PUSH    D       ;
        RST     7      ;чт.сост.мл.
RTF10:  IN      01      ;порт C
        ANI     MASK    ;
        CMP     E       ;сравн.с нач. сост.
        JZ      RTF10   ;если такой же
        MOV     E,A     ;запомн.новое сост.
        MVI     D,1     ;время=0
RTF11:  IN      01      ;10 тактов
        ANI     MASK    ; 7
        INR     D       ; 5
        CMP     E       ; 4
        JZ      RTF11   ;10
                        ;36 тактов итого
        MOV     A,D     ;A=врем.между битами
        ADD     A       ;удвоение результата
        ADD     A       ;--//--
        POP     D       ;
        RET
;
;п/п определения среднего времени
;между фронTами сигн.поступ.с мл.
; а=ср.время
;
TSBIT:  PUSH    H       ;
        PUSH    D       ;
TSF10:  CALL    TBIT    ;опред.вр.1-го
        MOV     B,A     ;опорное время=B
        ORA     A       ;
        RAR             ;T/2
        MOV     C,A     ;C=T/2
        LXI     H,0000  ;HL=рез.суммы
        MVI     D,32    ;количество измерений
TSF11:  CALL    TBIT    ;
        PUSH    D       ;
        MVI     D,0     ;
        MOV     E,A     ;
        DAD     D       ;+ к рег.результата
        POP     D       ;
        MOV     E,A     ;E=новое время
        SUB     B       ;вычисл.отклонение
        JNC     TSF13   ;переход если опор.больше
        MOV     A,B     ;A=т опрорн.
        SUB     E       ;из опорн.выч.тек.
TSF13:  CMP     C       ;сравнить с допуст. 0.5т
        JNC     TSF10   ;повтор.сначала
        DCR     D       ;еще измерять?
        JNZ     TSF11   ;?
        DAD     H       ;удвоить результат
        MOV     A,H     ;A=рез.усредн.
        POP     D       ;
        POP     H       ;
        RET             ;
;
;п/п счит.с мл.блока с верной контр.суммой
; ADR.BUFF=(HL)
;
READB:  PUSH    B       ;
        LXI     H,ABUFF ;HL=адр.буфф.данных
REA2:   PUSH    H       ;
        LXI     B,35    ;B=O-KS, C=числ.байт
        MVI     A,0FFH  ;искать е6
REA1:   CALL    MITAP   ;читать байт с мл.
        MOV     M,A     ;сохранить в буфф.
        INX     H       ;установить след.адрес
        ADD     B       ;выч.контр.сумму
        MOV     B,A     ;сохр.KS
        MVI     A,8     ;синх.байт считан.
        DCR     C       ;ещE есть байты
        JNZ     REA1    ;да!
        DCX     H       ;HL=адр.KS
        MOV     A,B     ;A=KS
        SUB     M       ;вычесть KS мл.
        SUB     M       ;и еще раз
        MOV     A,M     ;A=KS
        POP     H       ;
        JNZ     REA2    ;читать снова ?
        POP     B       ;
        RET             ;
;
;подпрограмма ввода байта
;с магнитофона A=FF - с поиском 0E6H
;A=08 - без поиска
;A=введенному байту
;
MITAP:  PUSH    B       ;
        PUSH    D       ;
        MVI     C,0     ;
        MOV     D,A     ;
        CALL    REATP   ;IN 1,ANI MASK,MOV E,A
IZMSIG: IN      01      ;
        ANI     MASK    ;
        CMP     E       ;
        JZ      IZMSIG  ;
        RLC             ;
        RLC             ;
        RLC             ;
        RLC             ;
        MOV     A,C     ;
        RAL             ;
        MOV     C,A     ;
        RST     7       ;зад. 0.75 тслед.
        MOV     A,D     ;
        ORA     A       ;
        JP      M118    ;
        MOV     A,C     ;
        CPI     0E6H    ;
        JNZ     M119    ;
        XRA     A       ;
        STA     PRINV   ;
        JMP     M121    ;
M119:   CPI     19H     ;
        JNZ     IZMSIG  ;
        MVI     A,0FFH  ;
        STA     PRINV   ;
M121:   MVI     D,9     ;
M118:   DCR     D       ;
        JNZ     IZMSIG  ;
        LDA     PRINV   ;
        XRA     C       ;
        POP     D       ;
        POP     B       ;
        RET             ;
;
        .END     ;конец программы "начальный загрузчик"
