; Функция: func_hero_repaint_over
; Адрес: 0x0EF5
; Описание: Beam-safe перекраска ОТОБРАЖЁННОГО героя поверх уже записанного в VRAM.
;           Вынесена из инлайн-блока loc_exit_hero (func_game_update) в переиспользуемый
;           примитив и вызывается:
;             * из loc_exit_hero — дорисовать героя поверх мигания выхода;
;             * из lbl_main_game_loop — сразу после CALL func_game_update, чтобы герой
;               был ПОСЛЕДНИМ экранным писателем в свою область в pass-кадре. Это закрывает
;               мерцание: func_score_and_redraw (эпilog сбора) стирает клетку героя в пустой
;               тайл (func_draw_tile_to_buf) УЖЕ ПОСЛЕ func_hero_render, и без перекраски
;               следующий скан полосы видит пустоту -> герой пропадает на кадр.
;
;           СОСТОЯНИЕ: рисует в ТЕКУЩЕЙ отображаемой позиции var_enemy_rc (lo=строка cr,
;           hi=колонка cc) — НЕ в целевой var_player_row/col (еasing-архитектура: цель
;           догоняется в func_hero_render). Кадр тайла берётся из var_hero_idx — это
;           «последний НАРИСОВАННЫЙ» индекс (источник истины func_hero_render, строки
;           262/276), поэтому перекраска байт-в-байт идемпотентна к тому, что уже на экране
;           (var_obj_type_idx мог бы указать следующий кадр и дать 1-кадровый сдвиг позы).
;           func_render_tile_vram_or сам применяет var_glyph_voff (суб-сдвиг по вертикали).
;
;           RASTER-GUARD: func_raster_guard_hero (полоса = var_scr_090A ∪ var_enemy_rc) —
;           OR-композит героя (~68 строк развёртки) пишется вне прохода луча. Идемпотентно:
;           повторный вызов на неизменном изображении безвреден.
;
;           Ограничение (этап A): использует выровненный 2x2 OR (hoff=0). На кадре
;           горизонтального midpoint (hoff!=0) func_hero_render рисует широкий 3-колоночный
;           or3 — здесь перекраска кладёт только выровненное ядро; артефакт 1 кадр,
;           самокорректируется следующим func_hero_render. Расширение на or3 — этап B.
;
;           Регистры/флаги для вызывающего не сохраняются намеренно: в главном цикле
;           сразу после идёт POP B (BC грузится со стека), в loc_exit_hero — loc_exit_done
;           перезагружает всё из RAM.

func_hero_repaint_over:
    CALL func_raster_guard_hero ; raster-sync: перекраска вне прохода луча
    LDA var_enemy_rc            ; lo = ОТОБРАЖАЕМая строка героя (твин-cr)
    MOV L, A
    LDA var_enemy_rc+1          ; hi = ОТОБРАЖАЕМая колонка героя
    MOV H, A
    XCHG                        ; DE = (D=col, E=row) — позиция для render
    LDA var_hero_idx            ; кадр = последний нарисованный func_hero_render
    ADD A
    ADD A                       ; idx*4
    LXI H, data_tile_table_26DE
    CALL func_hl_add_a          ; HL = указатель графики тайла героя
    CALL func_render_tile_vram_or  ; герой OR-композитом поверх (не затирает фон под ним)
    RET
