/*
 * sfx_mario.c — звуковые эффекты демки Mario double-buffering.
 *
 * Вывод тона — КР580ВИ53 напрямую (vi53_set_channel). Шумогенератора у ВИ53
 * нет, поэтому ветра при беге нет: mario_sfx_running держится только как
 * зеркало флага бега из main (на случай будущих эффектов).
 *
 * ПРЫЖОК — frame-exact глиссандо: константная таблица делителей ВИ53, один
 * делитель на один кадр 50 Гц (20 мс). Снята покадрово с эталонного сэмпла
 * src/sfx-14.mp3 (GStreamer->WAV, детектив основной частоты автокорреляцией на
 * сетке 20 мс с отсечкой октавных ошибок). Форма — чистый тон (без шума):
 *   кадры 0..8   : лёгкий прогиб ВНИЗ 292->281 Гц  (div 5136->5340)
 *   кадры 9..27  : плавный ПОДЪЁМ     298->580 Гц  (div 5034->2585)
 * Итого 28 кадров (~0,56 с).
 *
 * Почему НЕ detune-лестница sfx.c: detune — это прибавка к ДЕЛИТЕЛЮ, т.е. свип
 * линеен по периоду (частота ускоряется к верху и отстаёт в середине), а в
 * исходнике подъём линеен по ЧАСТОТЕ. Разница кривизны на слух = «не то».
 * Прямая таблица делителей повторяет замер кадр в кадр. Заодно detune — signed
 * char (±127) и не дал бы нужный ход на низких нотах.
 *
 * Приземление остаётся коротким двухнотным «чпоком» (тоже таблица делителей).
 *
 * Каналы ВИ53 (собственник — только этот файл): прыжок = канал 0, приземление =
 * канал 1. Разные каналы → эффекты могут перекрываться без конфликта. sfx.c /
 * notes.c из сборки выведены как неиспользуемые.
 */

#include "v06.h"

/* ------------------------- ТОНАЛЬНЫЕ ЭФФЕКТЫ ---------------------------- */

/* Прыжок: делитель на каждый кадр 50 Гц, f = 1500000 / div (КР580ВИ53, режим 3).
 * Снято кадр-в-кадр с src/sfx-14.mp3. */
static const unsigned int jump_div[] = {
    /* прогиб вниз: 292 -> 281 Гц */
    5136u, 5136u, 5170u, 5204u, 5238u, 5238u, 5238u, 5340u, 5340u,
    /* подъём: 298 -> 580 Гц */
    5034u, 4983u, 4660u, 4660u, 4371u, 4116u, 4082u, 3844u, 3810u,
    3571u, 3401u, 3350u, 3163u, 3129u, 2925u, 2789u, 2755u, 2585u, 2585u
};
#define JUMP_LEN  ((unsigned char)(sizeof(jump_div) / sizeof(jump_div[0])))

/* Приземление: короткий низкий «чпок» — 2 кадра (~40 мс), тон вниз. */
static const unsigned int land_div[] = {
    5733u,   /* C4 = 262 Гц */
    7653u    /* G3 = 196 Гц */
};
#define LAND_LEN  ((unsigned char)(sizeof(land_div) / sizeof(land_div[0])))

/* Позиция воспроизведения: 0xFF = эффект не играет. Пишется/читается только из
 * ISR (mario_sfx_frame) — гонки нет. */
#define SFX_IDLE  0xFFu
static unsigned char jump_pos = SFX_IDLE;
static unsigned char land_pos = SFX_IDLE;

/* ------------------------------- API ------------------------------------ */
/*
 * Звук живёт в КАДРОВОМ ПРЕРЫВАНИИ (frame_handler = mario_frame в main.c),
 * но ПОСЛЕ смены палитры: обработчик сначала грузит палитру (v06_set_palette_isr
 * — raster-критично, в самом начале гасения), и только потом зовёт
 * mario_sfx_frame(). Так долгий звук не сдвигает палитрный цикл за blanking
 * (нет бегущих полос), а сам звук пишет только свои порты (ВИ53 0x08-0x0B),
 * не трогая 02/0C. Движок играет ровно один такт за VBlank (50 Гц) — темп
 * честный даже на проспавшихся кадрах, догон цикла не трогает.
 *
 * Из main-контекста тут дёргаются ТОЛЬКО байтовые флаги (req_*) — записи
 * атомарны на 8080; сама таблица/позиции (jump_pos/land_pos) трогаются
 * исключительно из ISR, поэтому гонки за полуживое состояние нет.
 */

unsigned char mario_sfx_running;         /* флаг бега (зеркало из main)          */
static volatile unsigned char req_jump;  /* 1 = запросить эффект прыжка в ISR    */
static volatile unsigned char req_land;  /* 1 = запросить эффект приземления     */

/* Инициализация: тишина на обоих каналах, позиции — idle. */
void mario_sfx_init(void)
{
    mario_sfx_running = 0;
    req_jump = 0;
    req_land = 0;
    jump_pos = SFX_IDLE;
    land_pos = SFX_IDLE;
    vi53_set_channel(0u, 0u);
    vi53_set_channel(1u, 0u);
}

/* Запросить эффект прыжка: только флаг, исполнит ISR (mario_sfx_frame).
 * Прямой запуск из main конфликтовал бы с движком, играющим в прерывании. */
void mario_sfx_jump(void)
{
    req_jump = 1;
}

/* Запросить эффект приземления. */
void mario_sfx_land(void)
{
    req_land = 1;
}

/* Кадровый движок звука — зовётся ИЗ frame_handler (в прерывании), строго
 * ПОСЛЕ загрузки палитры. Сначала разгребает post-запросы эффектов (запуск
 * идёт здесь, в ISR-контексте — единственный владелец каналов), затем досчитывает
 * один кадр каждой активной таблицы. Никаких ei/halt/di: мы уже в ISR
 * (повторный ei открыл бы окно реентерабельного входа). */
void mario_sfx_frame(void)
{
    if (req_jump) { req_jump = 0; jump_pos = 0u; }
    if (req_land) { req_land = 0; land_pos = 0u; }

    /* Прыжок — глиссандо на канале 0: один делитель за кадр. */
    if (jump_pos != SFX_IDLE) {
        if (jump_pos < JUMP_LEN) {
            vi53_set_channel(0u, jump_div[jump_pos]);
            ++jump_pos;
        } else {
            vi53_set_channel(0u, 0u);
            jump_pos = SFX_IDLE;
        }
    }

    /* Приземление — 2 тона на канале 1. */
    if (land_pos != SFX_IDLE) {
        if (land_pos < LAND_LEN) {
            vi53_set_channel(1u, land_div[land_pos]);
            ++land_pos;
        } else {
            vi53_set_channel(1u, 0u);
            land_pos = SFX_IDLE;
        }
    }
}
