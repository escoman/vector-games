/*
 * main.c — H.A.T.E. (Vortex Software, 1989) на Векторе-06Ц.
 *
 * Этап 1: заставка и мелодия. Кадрового цикла здесь нет: картинка
 * статична (TZ §3.5 — заставка без dblbuf), а звук блокирующий
 * (TapeOut/PC0, TZ §3.8). Меню и переход в миссию — следующие этапы.
 *
 * Старт:
 *   1) чёрная палитра — экран гаснет, мусор ОЗУ не виден;
 *   2) режим 256x256, 16 цветов — ОБЫЧНЫЙ режим Вектора;
 *   3) распаковка 32 КБ плоскостей в 0x8000 (ZX0, 3.9 КБ в ROM);
 *   4) палитра заставки — восемь ярких цветов ZX (картинка проявляется);
 *   5) мелодия — sfx_title_play() не возвращается.
 *
 * Картинка ZX (256x192) прижата к ВЕРХНЕМУ краю экрана, как на Спектруме:
 * нижние 64 строки Вектора (в образе они нулевые) остаются чёрными, само
 * изображение не растягивается.
 */

#include "v06.h"
#include "title.inc"
#include "sfx_hate.h"

/* Восемь ярких цветов ZX по номерам чернил — ровно те, что раскладывает
 * по плоскостям tools/gen_title.py (номер чернила = номер цвета). Слоты
 * 8..15 режима 16 цветов не нужны и остаются чёрными: бит 3 цвета
 * (плоскость 0x8000) в образе нулевой. */
static const unsigned char title_palette[16] = {
    V06_RGB(0, 0, 0),       /* 0: чёрный    — фон, paper ZX            */
    V06_RGB(0, 0, 3),       /* 1: синий                                */
    V06_RGB(7, 0, 0),       /* 2: красный   — марка двигателя          */
    V06_RGB(7, 0, 3),       /* 3: пурпурный                            */
    V06_RGB(0, 7, 0),       /* 4: зелёный   — решётки, рельеф          */
    V06_RGB(0, 7, 3),       /* 5: голубой   — подводная лодка, плашка  */
    V06_RGB(7, 7, 0),       /* 6: жёлтый    — танк                     */
    V06_RGB(7, 7, 3),       /* 7: белый     — HATE, корабль, рамка     */
    V06_RGB(0, 0, 0), V06_RGB(0, 0, 0), V06_RGB(0, 0, 0), V06_RGB(0, 0, 0),
    V06_RGB(0, 0, 0), V06_RGB(0, 0, 0), V06_RGB(0, 0, 0), V06_RGB(0, 0, 0),
};

int main(void)
{
    gfx_set_black_palette();        /* экран чёрный: распаковка не видна */
    gfx_set_mode(GFX_MODE_256_16);  /* 256x256, все четыре плоскости    */

    /* 32 КБ плоскостей одним потоком: [вес 8][вес 4][вес 2][вес 1] по
     * адресам 0x8000/0xA000/0xC000/0xE000 (см. include/title.inc). */
    zx0_decompress(title_zx0, V06_VRAM);
    gfx_set_palette(title_palette);

    sfx_title_play();               /* блокирующий цикл, не возвращается */

    return 0;
}
