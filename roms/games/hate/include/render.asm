;
; render.asm — вывод рельефа меню H.A.T.E. в двойной буфер.
;
; ЧТО РИСУЕТСЯ. Данные — include/terrain.inc (tools/gen_terrain.py): рельеф
; сцены за меню, 32 столбца по 24 клетки. Кольцо оригинала уже разрезано на
; 8-байтные блоки-клетки, а цвет «запечён» в байты плоскостей (00 / FF /
; паттерн / ~паттерн), поэтому здесь нет ни разбора цвета, ни арифметики:
; только копирование 8 байт из словаря в VRAM.
;
; КУДА. В буфер A двойной буферизации (lib/gfx/dblbuf.asm): плоскость веса 1
; (0xE000, бит 0 палитры) и веса 2 (0xC000, бит 1). Каждая плоскость — свой
; поток указателей (terrain_c1 / terrain_c2) и свой проход t_pass. В буфер B
; та же картинка попадает копией A->B (gfx_dblbuf_copy_ab), как в mario-dbl:
; рельеф статичен, поэтому рисуется один раз на старте меню.
;
; КУДА ИМЕННО В VRAM. Байт плоскости адресуется как base + столбец*256 +
; (255 - строка), поэтому картинка, прижатая к верху экрана (как на ZX),
; ложится в байты 64..255 столбца: позиция s потока = base + x*256 + 64 + 8s,
; а это строки 191-8s..184-8s, то есть клетки идут СНИЗУ ВВЕРХ — ровно так,
; как их читает оригинал (ENGINE.MD §3.5: блиттер пишет вверх по экрану).
; Потоки в terrain.inc уже лежат в этом порядке. Младшие 64 байта столбца
; (строки 192..255) рельеф не трогает: там остаётся чёрное поле под панелью.
;
; ЦЕНА. 2 плоскости * 768 клеток * (8 байт копии + 36 тактов на указатель)
; ≈ 410 тыс. тактов ≈ 0.14 с на весь рельеф — один раз, до показа кадра.
;
; Только 8080: без LDIR/LDDR/JR/DJNZ/IX/IY и префиксов CB/DD/ED/FD.

        SECTION code_clib
        PUBLIC  _terrain_draw

; Геометрия — синхронно с terrain.inc (terrain_cols / terrain_cells_per_col).
OFSCREEN EQU    64              ; 255 - 191: байт строки 0 в столбце
; После 24 клеток (64 + 24*8 = 256) младший байт адреса обнуляется сам —
; это и есть условие конца столбца, отдельный счётчик клеток не нужен.

; ---------------------------------------------------------------------------
; void terrain_draw(void)
;
; Рельеф целиком в буфер A. Рисовать до показа кадра (gfx_dblbuf_show или
; fade-in): на экране в этот момент ещё чёрная палитра.
; ---------------------------------------------------------------------------
_terrain_draw:
        lxi     b, 0E000h + OFSCREEN   ; приёмник: плоскость веса 1, x=0
        lxi     d, terrain_c1          ; поток указателей этой плоскости
        call    t_pass
        lxi     b, 0C000h + OFSCREEN   ; приёмник: плоскость веса 2
        lxi     d, terrain_c2
        call    t_pass
        ret

; ---------------------------------------------------------------------------
; t_pass — весь рельеф в одну плоскость.
; Вход: BC = байт картинки в столбце 0 (base + OFSCREEN),
;       DE = поток указателей на блоки (terrain_c1 / terrain_c2).
; Портит A, BC, DE, HL.
; ---------------------------------------------------------------------------
t_pass:
        lda     terrain_cols     ; 32 — число столбцов, из terrain.inc
        sta     t_cols
t_col:
        mvi     c, OFSCREEN
t_cell:
        ldax    d               ; 7   адрес блока: сначала младший байт
        mov     l, a            ; 5
        inx     d               ; 6
        ldax    d               ; 7   затем старший
        mov     h, a            ; 5
        inx     d               ; 6
        mov     a, m            ; 7   --- 8 байт блока: (HL) -> (BC) ---
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, c            ; 7   конец столбца: C обнулился (256 байт)
        ora     a               ; 4
        jnz     t_cell          ; 10
        lda     t_cols          ; 13  следующий байтовый столбец VRAM
        dcr     a               ; 5
        sta     t_cols          ; 13
        jnz     t_col           ; 10
        ret

        SECTION bss_clib

t_cols: defs    1               ; осталось столбцов в текущем проходе

; Данные — в конце файла: terrain.inc открывает SECTION rodata_user сам,
; и до его включения по коду уже ничего не должно идти.
        INCLUDE "terrain.inc"
