;
; graphpr512.asm — вывод текста шрифтом 16x8 в режиме 512x256
; Вектор-06Ц / Intel 8080.
;
;   void graph_put_char_512(unsigned char x, unsigned char y, char ch,
;                           unsigned char color);
;   void graph_print_512(unsigned char x, unsigned char y, const char *s,
;                        unsigned char color);
;
; __z88dk_callee.
;
; VRAM:
;   E000-FFFF
;   C000-DFFF
;   A000-BFFF
;   8000-9FFF
;
; color:
;   bit 0 -> E000/A000
;   bit 1 -> C000/8000
;
; Только реальные инструкции Intel 8080.
;

        SECTION code_clib
        PUBLIC  _graph_put_char_512
        PUBLIC  _graph_print_512


; ---------------------------------------------------------------
; graph_put_char_512(x,y,ch,color)
;
; __z88dk_callee
;
; На входе:
;
;   SP -> return address
;         color
;         ch
;         y
;         x
;
; ---------------------------------------------------------------

_graph_put_char_512:

        pop     h
        pop     d
        mov     a,e
        sta     tmp_color

        pop     d
        mov     a,e
        sta     tmp_ch

        pop     d
        mov     a,e
        sta     tmp_y

        pop     d
        mov     a,e
        sta     tmp_x

        push    h

        jmp     draw_char_512


; ---------------------------------------------------------------
; draw_char_512
; ---------------------------------------------------------------

draw_char_512:

        ; x = 0..31

        lda     tmp_x
        cpi     32
        jnc     draw_done_512

        ; y = 0..248

        lda     tmp_y
        cpi     249
        jnc     draw_done_512


        ; -------------------------------------------------------
        ; Поиск символа
        ; -------------------------------------------------------

        lda     tmp_ch
        mov     c,a

        lxi     h,font_chars_512
        mvi     e,0


find_loop_512:

        mov     a,m
        ora     a
        jz      char_not_found_512

        cmp     c
        jz      glyph_found_512

        inx     h
        inr     e

        jmp     find_loop_512


char_not_found_512:

        mvi     e,0


glyph_found_512:

        ; -------------------------------------------------------
        ; HL = font16x8 + index * 16
        ; -------------------------------------------------------

        mvi     d,0
        mov     l,e
        mvi     h,0

        dad     h
        dad     h
        dad     h
        dad     h

        lxi     d,font16x8
        dad     d

        shld    tmp_glyph


        ; -------------------------------------------------------
        ; Базовый адрес E000:
        ;
        ; H = E0 + x
        ; L = 255 - y
        ; -------------------------------------------------------

        lda     tmp_x
        adi     0E0h
        mov     h,a

        lda     tmp_y
        mov     e,a

        mvi     a,255
        sub     e
        mov     l,a


        lda     tmp_color
        mov     c,a


        ; =======================================================
        ; bit 0 -> E000
        ; =======================================================

        mov     a,c
        ani     01h
        jz      skip_b0_even

        push    h

        lda     tmp_glyph
        mov     e,a

        lda     tmp_glyph + 1
        mov     d,a

        call    draw_8_even_bytes

        pop     h


skip_b0_even:


        ; =======================================================
        ; bit 0 -> A000
        ; =======================================================

        mov     a,c
        ani     01h
        jz      skip_b0_odd

        push    h

        mov     a,h
        sui     040h
        mov     h,a

        lda     tmp_glyph
        mov     e,a

        lda     tmp_glyph + 1
        mov     d,a

        inx     d

        call    draw_8_even_bytes

        pop     h


skip_b0_odd:


        ; =======================================================
        ; bit 1 -> C000
        ;
        ; ВАЖНО:
        ; E000 -> C000 = -2000h
        ; поэтому H уменьшается на 20h.
        ; =======================================================

        mov     a,c
        ani     02h
        jz      skip_b1_even

        push    h

        mov     a,h
        sui     020h
        mov     h,a

        lda     tmp_glyph
        mov     e,a

        lda     tmp_glyph + 1
        mov     d,a

        call    draw_8_even_bytes

        pop     h


skip_b1_even:


        ; =======================================================
        ; bit 1 -> 8000
        ; =======================================================

        mov     a,c
        ani     02h
        jz      skip_b1_odd

        push    h

        mov     a,h
        sui     060h
        mov     h,a

        lda     tmp_glyph
        mov     e,a

        lda     tmp_glyph + 1
        mov     d,a

        inx     d

        call    draw_8_even_bytes

        pop     h


skip_b1_odd:

        ret


draw_done_512:

        ret


; ---------------------------------------------------------------
; HL = VRAM address
; DE = glyph address
;
; Записываются байты:
;
;   0
;   2
;   4
;   6
;   8
;   10
;   12
;   14
;
; После каждой строки HL уменьшается на 1.
; ---------------------------------------------------------------

draw_8_even_bytes:

        ldax    d
        mov     m,a
        dcx     h
        inx     d
        inx     d

        ldax    d
        mov     m,a
        dcx     h
        inx     d
        inx     d

        ldax    d
        mov     m,a
        dcx     h
        inx     d
        inx     d

        ldax    d
        mov     m,a
        dcx     h
        inx     d
        inx     d

        ldax    d
        mov     m,a
        dcx     h
        inx     d
        inx     d

        ldax    d
        mov     m,a
        dcx     h
        inx     d
        inx     d

        ldax    d
        mov     m,a
        dcx     h
        inx     d
        inx     d

        ldax    d
        mov     m,a
        dcx     h

        ret


; ---------------------------------------------------------------
; graph_print_512(x,y,s,color)
;
; __z88dk_callee
; ---------------------------------------------------------------

_graph_print_512:

        pop     h               ; return address

        pop     d               ; color
        mov     a,e
        sta     tmp_color

        pop     d               ; string
        xchg
        shld    tmp_s
        xchg

        pop     d               ; y
        mov     a,e
        sta     tmp_y

        pop     d               ; x
        mov     a,e
        sta     tmp_x

        push    h               ; return address


print_loop_512:

        lda     tmp_x
        cpi     32
        jnc     print_done_512

        lhld    tmp_s
        xchg                    ; DE = pointer

        ldax    d
        ora     a
        jz      print_done_512

        sta     tmp_ch

        inx     d
        xchg
        shld    tmp_s
        xchg

        call    draw_char_512

        lda     tmp_x
        inr     a
        sta     tmp_x

        jmp     print_loop_512


print_done_512:

        ret


; ---------------------------------------------------------------
; Рабочие переменные
; ---------------------------------------------------------------

