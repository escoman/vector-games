/* Вывод одного символа: адрес каждой строки считается заново.
 * Блок символа = (x/8)*256 байт внутри каждой плоскости
 * (0x8000 + n*0x2000); строка y блока — по адресу (256-y)&0xFF,
 * строки вниз — уменьшение адреса. Неизвестный символ — пробел. */
void graph_put_char(unsigned char x, unsigned char y, char ch,
                    unsigned char color)
{
    unsigned char idx;
    unsigned char plane;
    unsigned char mask;
    unsigned char row;
    unsigned int block;
    unsigned char *dst;

    for (idx = 0; font_chars[idx] != '\0'; ++idx) {
        if (font_chars[idx] == ch)
            break;
    }
    if (font_chars[idx] == '\0')
        idx = 0;                          /* неизвестный символ -> пробел */

    block = (unsigned int)(x >> 3) << 8;  /* (x/8)*256 внутри плоскости */
    for (plane = 0, mask = 8u; plane < 4u; ++plane, mask >>= 1) {
        for (row = 0; row < 8u; ++row) {
            dst = (unsigned char *)(0x8000u + (unsigned int)plane * 0x2000u
                                    + block
                                    + ((256u - y - row) & 0xFFu));
            *dst = (color & mask) ? font8x8[idx][row] : 0x00u;
        }
    }
}

/* Вывод строки: символы идут влево-вправо с шагом 8 пикселей */
void graph_print(unsigned char x, unsigned char y, const char *s,
                 unsigned char color)
{
    while (*s != '\0') {
        graph_put_char(x, y, *s, color);
        x += 8u;
        ++s;
    }
}
