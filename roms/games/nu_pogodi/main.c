/*
 * Ну, погоди! — порт на Вектор-06Ц.
 *
 * Вывод фона (back.bmp, RLE) с редактируемой палитрой.
 */

#include "v06.h"
#include "src/back_bmp.inc"

/* Палитра из back.bmp (можно редактировать).
 * Формат: V06_RGB(r, g, b), где r=0..7, g=0..7, b=0..3.
 * Индексы совпадают с BMP (--no-opt). */
static const unsigned char back_palette[16] = {
    V06_RGB(4,4,2),  /*  0: 0x5B — фон (основной)  */
    V06_RGB(1,1,0),  /*  1: 0x09 — тёмно-оливковый */
    V06_RGB(4,1,0),  /*  2: 0x0C — тёмно-красный   */
    V06_RGB(3,2,0),  /*  3: 0x13 — коричневый      */
    V06_RGB(2,2,1),  /*  4: 0x52 — серый           */
    V06_RGB(0,0,0),  /*  5: (не используется)      */
    V06_RGB(5,4,2),  /*  6: 0xA5 — светло-серый    */
    V06_RGB(7,7,3),  /*  7: 0xFF — белый           */
    V06_RGB(0,0,0),  /*  8: (не используется)      */
    V06_RGB(0,0,0),  /*  9: (не используется)      */
    V06_RGB(0,0,0),  /* 10: (не используется)      */
    V06_RGB(0,0,0),  /* 11: (не используется)      */
    V06_RGB(0,0,0),  /* 12: (не используется)      */
    V06_RGB(0,0,0),  /* 13: (не используется)      */
    V06_RGB(0,0,0),  /* 14: (не используется)      */
    V06_RGB(0,0,0),  /* 15: (не используется)      */
};

int main(void)
{
    /* Рисуем на чёрном экране — картинка не видна до загрузки палитры. */
    gfx_set_black_palette();
    gfx_rle_expand(back_bmp_screen_rle, 0, 0);
    gfx_set_palette(back_palette);

    while (1);

    return 0;
}
