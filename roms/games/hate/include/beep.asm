;
; beep.asm — бипер заставки H.A.T.E. на TapeOut (PC0 ПИА1, порт 01h).
;
; Оригинал озвучен 1-битным бипером ZX (порт $FE). Здесь тот же бит и тот
; же приём: уровень PC0 пишется в BSR-регистр ПИА (порт 00h, D7=0): A=01h —
; SET PC0, A=00h — RESET (см. lib/snd/drums.asm, pc0_set). ВИ53 в озвучке
; не участвует (TZ §3.8).
;
; ЧТО ИГРАЕТ. Партитура (include/title_music.asm, генерируется
; tools/gen_title_music.py из лога оригинала) — четыре независимых голоса:
; A и B — узкоимпульсные генераторы мелодии, C — клик, N — шум. У каждого
; свой счётчик до следующего импульса и свой скрипт «сколько импульсов
; каким периодом».
;
; ПОЧЕМУ НЕ ЦЕПОЧКА ФРОНТОВ. Прежний экспорт был цепочкой (задержка,
; уровень) на каждый фронт PC0: 3 байта на фронт, 22138 фронтов — 65 КБ, и
; в ROM влезал только первый цикл (3.2 с). Здесь интервалы вычисляет сам
; плеер, поэтому вся запись (38.5 с) занимает ~3.2 КБ.
;
; ЕДИНИЦА ВРЕМЕНИ — 128 тактов (42.7 мкс), одна на все голоса: счётчики
; приходится сравнивать между собой, а пауза клика в 1.9 с в 16 бит по 32
; такта не влезает. Шаг счётчиков при этом 0.6 % от самого короткого
; периода (81 ед.) — это 10 центов, на слух неразличимо.
;
; ТАКТЫ ЗДЕСЬ — НЕ НОМИНАЛЬНЫЕ 8080. Контроллер видео придерживает
; процессор, поэтому команда занимает целое число 4-тактовых окон:
; 4->4, 5->8, 7->8, 10->12, 13->16, 16->20, 17->24 (v06c-emu, i8080.cpp,
; cpu_cycles -> v_cycles; проверено на эмуляторе по лучу: 1 такт =
; 4 v_cycle). Поэтому цикл задержки ниже (dcx d / mov a,e / ora d / jnz)
; = 8+8+4+12 = 32 такта, а не 24.
;
; ПЛАНИРОВЩИК. Шаг = «дождаться ближайшего импульса»: берётся минимум из
; четырёх счётчиков, выжидается ровно он, из всех счётчиков он
; вычитается; у кого получился ноль — выдаёт импульс и заряжает счётчик
; своим периодом. Джиттера кадровой синхронизации оригинала (и его
; «пропущенных проходов») здесь нет: время считает таймер, а не кадр.
;
; НАКЛАДНЫЕ РАСХОДЫ КОМПЕНСИРУЮТСЯ. Выдача импульса занимает время (ПИА +
; задержка + скважность), и без компенсации голос B (5703 импульса) отстал
; бы от A (3109) на треть секунды. Поэтому каждый импульс добавляет свою
; цену в `spent`, а следующая задержка укорачивается на неё. Цена шага
; (C_STEP) тоже вычтена и выровнена NOPами до целого числа 32-тактовых
; бит: иначе остаток стал бы постоянным сдвигом темпа.
;
; ШУМ ТОЖЕ КОМПЕНСИРУЕТСЯ — как импульс, только крупнее. Вспышка
; занимает 9.1 мс (MUS_BURST_B, считает генератор по рисунку шума) и
; замораживает все счётчики разом; без компенсации 44 вспышки утаскивали
; бы всю партитуру на 0.4 с (клик уезжал на 9 мс после каждой — слышно
; как «плавающий» бит). Поэтому fire_n добавляет её цену в `spent`,
; и следующие шаги её отрабатывают, как обычный долг.
;
; ПРЕРЫВАНИЯ НА ВРЕМЯ ИГРЫ ЗАПРЕЩЕНЫ. Кадровый ISR (startup.asm) тратит
; ~400 тактов; внутри цикла он растянул бы шаг на 0.4 %. Поэтому DI на всё
; время игры; клавиатура опрашивается в стыке партитуры (раз в ~38 с) —
; kbd_scan_rows сам ловит VBlank через EI;HLT, и порт 03h (скролл)
; трогается только в гасящем интервале.
;
; СОСТОЯНИЕ — сама собой, без прерываний: PC0 держит последний записанный
; уровень, между импульсами процессор только считает такты.
;
; КОНСТАНТЫ C_STEP/FIRE ПОВТОРЕНЫ в tools/gen_title_music.py (FIRE_BASE и
; MUS_DUTY_x). Правишь цикл здесь — сверься по лучу (reports/Stage1.md).
;

        SECTION code_clib

        PUBLIC  _beep_play_title

        EXTERN  mus_a, mus_b, mus_c
        EXTERN  mus_n, mus_np, mus_nz
        EXTERN  MUS_DUTY_A, MUS_DUTY_B, MUS_DUTY_C
        EXTERN  MUS_FIRE_A, MUS_FIRE_B, MUS_FIRE_C, MUS_BURST_B
        EXTERN  kbd_scan_rows
        EXTERN  _kbd_rows

PIA_CW  equ     0x00            ; ПИА1: CW (D7=1) / BSR (D7=0), общий порт PC0

C_STEP  equ     39              ; цена шага без задержки и импульсов, биты по 32
                                ; такта (сумма всех команд шага = 1200 такта;
                                ; подобрано по лучу на полном проходе)

; ---------------------------------------------------------------------------
; void beep_play_title(void)
;
; Блокирующий проигрыватель: играет партитуру заставки целиком (38.5 с),
; затем ждёт ЛЮБУЮ клавишу (экран в это время держит «PRESS ANY KEY WHEN
; READY») и возвращается в main — вход в меню.
;
; ПОЧЕМУ ОДИН ПРОХОД. Опрос матрицы возможен только в стыке партитуры:
; на время игры прерывания запрещены (шаг планировщика обязан быть точным),
; а опрос клавиатуры в kbd_scan_rows — это EI;HLT, т.е. лишний кадр в шаге.
; Поэтому «любая клавиша» ловится после финального такта.
; ---------------------------------------------------------------------------
_beep_play_title:
        di
        xor     a
        out     (PIA_CW), a         ; PC0 = 0 (BSR: сброс), динамик молчит
        call    mus_restart

; --- шаг планировщика ---------------------------------------------------
pl_loop:
        nop                         ; выравнивание шага до целых бит (C_STEP)
        call    mus_refill          ; 24  пополнить кончившиеся записи
        lda     last_flag           ; 16
        ora     a                   ; 4
        jnz     pl_over             ; 12
        call    sched_delay         ; 24  выждать ближайший импульс...
        ; --- ...и вычесть выжданное из всех счётчиков ---
        lhld    dmin                ; 20
        xchg                        ; 4   DE = dmin
        lxi     h, cd_a             ; 12
        mvi     b, 4                ; 8
cd_sub:
        mov     a,m                 ; 8   мл. байт
        sub     e                   ; 4
        mov     m,a                 ; 8
        inx     h                   ; 8
        mov     a,m                 ; 8   ст. байт
        sbb     d                   ; 4
        mov     m,a                 ; 8
        inx     h                   ; 8
        dcr     b                   ; 8
        jnz     cd_sub              ; 12
        ; --- у кого ноль — тому импульс ---
        lhld    cd_a                ; 20
        mov     a,h                 ; 8
        ora     l                   ; 4
        jz      fire_a              ; 12
chk_b:
        lhld    cd_b                ; 20
        mov     a,h                 ; 8
        ora     l                   ; 4
        jz      fire_b              ; 12
chk_c:
        lhld    cd_c                ; 20
        mov     a,h                 ; 8
        ora     l                   ; 4
        jz      fire_c              ; 12
chk_n:
        lhld    cd_n                ; 20
        mov     a,h                 ; 8
        ora     l                   ; 4
        jz      fire_n              ; 12
        jmp     pl_loop             ; 12

; --- конец партитуры: клавиатура и выход в меню -------------------------
pl_over:
        call    pl_seam             ; ждём любую клавишу (и её отпускание)
        ret                         ; → main: рельеф меню

; ---------------------------------------------------------------------------
; sched_delay — DE = 4*минимум(cd) - spent - C_STEP (биты по 32 такта),
; spent = 0, затем задержка. Выходит по ret из beat_delay — сразу в pl_loop.
; ---------------------------------------------------------------------------
sched_delay:
        lhld    cd_a                ; 20  текущий минимум — в DE
        mov     d,h                 ; 8
        mov     e,l                 ; 8
        lhld    cd_b                ; 20  кандидат — в HL
        mov     a,l                 ; 8
        sub     e                   ; 4
        mov     a,h                 ; 8
        sbb     d                   ; 4
        jnc     sd_c                ; 12  кандидат не меньше
        xchg                        ; 4   меньше — он и есть минимум
sd_c:
        lhld    cd_c                ; 20
        mov     a,l                 ; 8
        sub     e                   ; 4
        mov     a,h                 ; 8
        sbb     d                   ; 4
        jnc     sd_n                ; 12
        xchg                        ; 4
sd_n:
        lhld    cd_n                ; 20
        mov     a,l                 ; 8
        sub     e                   ; 4
        mov     a,h                 ; 8
        sbb     d                   ; 4
        jnc     sd_min              ; 12
        xchg                        ; 4
sd_min:
        mov     h,d                 ; 8
        mov     l,e                 ; 8
        shld    dmin                ; 20
        dad     h                   ; 12  x2
        dad     h                   ; 12  x4 = биты по 32 такта
        xchg                        ; 4   DE = 4*dmin
        lhld    spent               ; 20
        lxi     b, C_STEP           ; 12
        dad     b                   ; 12  HL = spent + цена шага
        mov     a,e                 ; 8
        sub     l                   ; 4
        mov     e,a                 ; 8
        mov     a,d                 ; 8
        sbb     h                   ; 4
        mov     d,a                 ; 8   DE = 4*dmin - spent - C_STEP
        jnc     sd_clear            ; 12
        ; Шаг короче своих же накладных расходов (два голоса почти совпали):
        ; ждать нечего — задержка 0, а недобранное остаётся долгом в spent и
        ; вычитается из следующих, длинных шагов. Без этого DE ушёл бы в
        ; минус и задержка (до 65535 бит = 0.7 с) растянула бы весь такт.
        mov     a,e                 ; 8
        cma                         ; 4
        mov     l,a                 ; 8
        mov     a,d                 ; 8
        cma                         ; 4
        mov     h,a                 ; 8
        inx     h                   ; 8   HL = -DE = долг
        shld    spent               ; 20
        lxi     d, 0                ; 12
        jmp     beat_delay          ; 12
sd_clear:
        lxi     h, 0                ; 12
        shld    spent               ; 20
        jmp     beat_delay          ; 12  ret вернёт прямо в pl_loop

; ---------------------------------------------------------------------------
; Импульсы голосов. Счётчик записи уменьшается здесь; сама запись
; подхватывается mus_refill на следующем шаге (там же, где читается
; «счётчик кончился»). Цена импульса (биты) = скважность + FIRE_BASE, её
; считает генератор и кладёт в MUS_FIRE_x; не меньше 32 тактов, чтобы
; выравнивание не «съело» задержку.
; ---------------------------------------------------------------------------
fire_a:
        lda     cnt_a               ; 16
        dcr     a                   ; 8
        sta     cnt_a               ; 16
        lhld    per_a               ; 20
        shld    cd_a                ; 20
        mvi     a, 1                ; 8
        out     (PIA_CW), a         ; 12  фронт: PC0 = 1
        lxi     d, MUS_DUTY_A       ; 12
        call    beat_delay          ; 24 + 32*скважность
        xra     a                   ; 4
        out     (PIA_CW), a         ; 12  спад: PC0 = 0
        lhld    spent               ; 20
        lxi     d, MUS_FIRE_A       ; 12
        dad     d                   ; 12
        shld    spent               ; 20
        jmp     chk_b               ; 12

fire_b:
        lda     cnt_b               ; 16
        dcr     a                   ; 8
        sta     cnt_b               ; 16
        lhld    per_b               ; 20
        shld    cd_b                ; 20
        mvi     a, 1                ; 8
        out     (PIA_CW), a         ; 12
        lxi     d, MUS_DUTY_B       ; 12
        call    beat_delay          ; 24 + 32*скважность
        xra     a                   ; 4
        out     (PIA_CW), a         ; 12
        lhld    spent               ; 20
        lxi     d, MUS_FIRE_B       ; 12
        dad     d                   ; 12
        shld    spent               ; 20
        jmp     chk_c               ; 12

fire_c:
        lda     cnt_c               ; 16
        dcr     a                   ; 8
        sta     cnt_c               ; 16
        lhld    per_c               ; 20
        shld    cd_c                ; 20
        mvi     a, 1                ; 8
        out     (PIA_CW), a         ; 12
        lxi     d, MUS_DUTY_C       ; 12
        call    beat_delay          ; 24 + 32*скважность
        xra     a                   ; 4
        out     (PIA_CW), a         ; 12
        lhld    spent               ; 20
        lxi     d, MUS_FIRE_C       ; 12
        dad     d                   ; 12
        shld    spent               ; 20
        jmp     chk_n               ; 12

; --- слот шума: он же и вспышка, если план так сказал --------------------
fire_n:
        lhld    mus_np              ; 20
        shld    cd_n                ; 20  следующий слот
        lda     n_cnt               ; 16
        dcr     a                   ; 8
        sta     n_cnt               ; 16
        lda     n_fire              ; 16
        ora     a                   ; 4
        jz      pl_loop             ; 12  тишина в этом слоте
        call    mus_burst           ; 24  вспышка шума
        lhld    spent               ; 20  её время тоже прошло для всех голосов
        lxi     d, MUS_BURST_B      ; 12
        dad     d                   ; 12
        shld    spent               ; 20
        jmp     pl_loop             ; 12

; ---------------------------------------------------------------------------
; mus_burst — рисунок шума: первый байт — число шагов, далее интервалы в
; тиках по 20 тактов. Уровень инвертируется CMA+ANI 1 (12 тактов):
; инструкции XRI у 8080 нет, а CMA в одиночку дал бы 0xFF/0xFE — в BSR это
; mode-set (D7=1), то есть сброс PC0 и регистра скролла.
; ---------------------------------------------------------------------------
mus_burst:
        lxi     h, mus_nz           ; 12
        mov     c,m                 ; 8   шагов
        inx     h                   ; 8
        xor     a                   ; 4   A = 0: первый CMA+ANI даст 1
bz_step:
        cma                         ; 4
        and     1                   ; 8
        out     (PIA_CW), a         ; 12
        mov     b,m                 ; 8
        inx     h                   ; 8
bz_wait:
        dcr     b                   ; 8
        jnz     bz_wait             ; 12
        dcr     c                   ; 8
        jnz     bz_step             ; 12
        cma                         ; 4   последний фронт вспышки
        and     1                   ; 8
        out     (PIA_CW), a         ; 12
        xor     a                   ; 4
        out     (PIA_CW), a         ; 12  в тишину (PC0 = 0)
        ret                         ; 12

; ---------------------------------------------------------------------------
; mus_refill — подхватить записи, у которых кончился счёт импульсов.
; Запись голоса: счётчик импульсов, период мл., период ст. (единицы по 128
; тактов); 0 вместо счётчика — конец скрипта. Запись плана шума: сколько
; слотов, признак вспышки; 0 — конец. Конец любой записи означает конец
; партитуры (last_flag): голоса расходятся по времени на десятки мс, и
; начинать новый круг с середины нельзя.
; ---------------------------------------------------------------------------
mus_refill:
        lda     cnt_a               ; 16
        ora     a                   ; 4
        jnz     rf_b                ; 12
        lhld    ptr_a               ; 20
rf_a_get:
        mov     a,m                 ; 8   сколько импульсов этим периодом
        ora     a                   ; 4
        jz      piece_end           ; 12
        sta     cnt_a               ; 16
        inx     h                   ; 8
        mov     e,m                 ; 8   период, мл.
        inx     h                   ; 8
        mov     d,m                 ; 8   период, ст.
        inx     h                   ; 8
        shld    ptr_a               ; 20
        xchg                        ; 4
        shld    per_a               ; 20
rf_b:
        lda     cnt_b               ; 16
        ora     a                   ; 4
        jnz     rf_c                ; 12
        lhld    ptr_b               ; 20
        mov     a,m                 ; 8
        ora     a                   ; 4
        jz      piece_end           ; 12
        sta     cnt_b               ; 16
        inx     h                   ; 8
        mov     e,m                 ; 8
        inx     h                   ; 8
        mov     d,m                 ; 8
        inx     h                   ; 8
        shld    ptr_b               ; 20
        xchg                        ; 4
        shld    per_b               ; 20
rf_c:
        lda     cnt_c               ; 16
        ora     a                   ; 4
        jnz     rf_n                ; 12
        lhld    ptr_c               ; 20
        mov     a,m                 ; 8
        ora     a                   ; 4
        jz      piece_end           ; 12
        sta     cnt_c               ; 16
        inx     h                   ; 8
        mov     e,m                 ; 8
        inx     h                   ; 8
        mov     d,m                 ; 8
        inx     h                   ; 8
        shld    ptr_c               ; 20
        xchg                        ; 4
        shld    per_c               ; 20
rf_n:
        lda     n_cnt               ; 16
        ora     a                   ; 4
        jnz     rf_done             ; 12
        lhld    ptr_n               ; 20
        mov     a,m                 ; 8   сколько слотов
        ora     a                   ; 4
        jz      piece_end           ; 12
        sta     n_cnt               ; 16
        inx     h                   ; 8
        mov     a,m                 ; 8   играть вспышку?
        sta     n_fire              ; 16
        inx     h                   ; 8
        shld    ptr_n               ; 20
rf_done:
        ret                         ; 12

piece_end:
        mvi     a, 1                ; 8
        sta     last_flag           ; 16
        ret                         ; 12

; ---------------------------------------------------------------------------
; mus_restart — все голоса в начало партитуры, счётчики — по первым записям.
; ---------------------------------------------------------------------------
mus_restart:
        lxi     h, mus_a            ; 12
        shld    ptr_a               ; 20
        lxi     h, mus_b            ; 12
        shld    ptr_b               ; 20
        lxi     h, mus_c            ; 12
        shld    ptr_c               ; 20
        lxi     h, mus_n            ; 12
        shld    ptr_n               ; 20
        xra     a                   ; 4
        sta     cnt_a               ; 16
        sta     cnt_b               ; 16
        sta     cnt_c               ; 16
        sta     n_cnt               ; 16
        sta     last_flag           ; 16
        lxi     h, 0                ; 12
        shld    spent               ; 20
        call    mus_refill          ; 24  первые записи всех скриптов
        lhld    per_a               ; 20
        shld    cd_a                ; 20
        lhld    per_b               ; 20
        shld    cd_b                ; 20
        lhld    per_c               ; 20
        shld    cd_c                ; 20
        lhld    mus_np              ; 20  первый слот шума
        shld    cd_n                ; 20
        ret                         ; 12

; --- конец партитуры: ожидание любой клавиши ---------------------------
pl_seam:
        call    seam_scan           ; A = OR строк матрицы, Z — ни одной
        jz      pl_seam             ; тишина: опрос раз в кадр, пока не нажмут
        xor     a
        out     (PIA_CW), a         ; нажали — тишина на всё время удержания
seam_hold:
        call    seam_scan           ; опрос раз в кадр, пока не отпустят
        jnz     seam_hold
        ei                          ; в main идём с разрешёнными прерываниями
        ret

; Опрос матрицы раз в кадр: EI;HLT внутри kbd_scan_rows ловит VBlank, а он
; возвращает порт 03h (скролл) — вне гашения тот не выполняется, картинка
; не дёргается. Выход: A = OR всех восьми байт матрицы (1 = нажата),
; Z — не нажата ни одна (СС/УС сидят на порту C и сюда не входят).
seam_scan:
        ei
        call    kbd_scan_rows
        di
        lxi     h, _kbd_rows
        mvi     b, 8
        xra     a
ss_or:
        ora     m
        inx     h
        dcr     b
        jnz     ss_or
        ora     a
        ret

; ---------------------------------------------------------------------------
; Задержка ровно на DE*32 такта.
; Вход: DE — число единиц (>= 1). Цикл: 8 (DCX D) + 8 (mov a,e) + 4 (ora d)
; + 12 (jnz) = 32 такта на единицу. Проверка DE = 0 — чтобы укороченная
; компенсацией задержка не растянулась на 65536 итераций. A не сохраняется.
; ---------------------------------------------------------------------------
beat_delay:
        mov     a,d                 ; 8
        ora     e                   ; 4
        rz                          ; 8
bd_loop:
        dcx     d                   ; 8
        mov     a,e                 ; 8
        ora     d                   ; 4
        jnz     bd_loop             ; 12
        ret                         ; 12

        SECTION bss_user

; Счётчики до импульса — вплотную друг к другу: шаг планировщика
; вычитает dmin из всех четырёх одним циклом по 2 байта.
cd_a:           defs    2
cd_b:           defs    2
cd_c:           defs    2
cd_n:           defs    2
per_a:          defs    2       ; текущий период голоса
per_b:          defs    2
per_c:          defs    2
cnt_a:          defs    1       ; остаток импульсов в текущей записи
cnt_b:          defs    1
cnt_c:          defs    1
ptr_a:          defs    2       ; указатель на текущую запись скрипта
ptr_b:          defs    2
