/* ------------------ МЕРЦАНИЕ ПАЛИТРЫ (кадровое прерывание) -----------
 * Вся палитра, кроме индекса 0 (чёрный), слегка «плавает» по интенсивности
 * по синусоиде — мерцают и огонь, и заставка (палитра одна на всё).
 *
 * flick_frames — покадровая линия времени: одна строка = один кадр
 * (16 байт палитры). Обработчик просто берёт очередную строку и пишет
 * её в железо. Чтобы изменить рисунок/темп мерцания — правь строки;
 * чтобы удлинить цикл — дописывай строки (FLICK_N считается сам).
 *
 * Таблица сгенерирована мультипликативной синусоидой f = 1 + 0.20·sin
 * (оттенок сохраняется: нулевые каналы остаются нулевыми, яркие цвета
 * упираются в потолок), 16 шагов; реальную скорость задаёт FLICK_DIV.
 *
 * Запись — через v06_set_palette_isr: БЕЗ ei/halt, т.к. мы уже в VBlank
 * внутри ISR (ei там вызвал бы повторный вход в прерывание).
 * --------------------------------------------------------------- */

extern void v06_set_palette_isr(const unsigned char *pal);

