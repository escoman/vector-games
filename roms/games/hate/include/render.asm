;
; render.asm — вывод рельефа меню H.A.T.E. в двойной буфер.
;
; ЧТО РИСУЕТСЯ. Данные — include/terrain.inc (tools/gen_terrain.py): лента
; ландшафта, 32 столбца по окну ktop..kbot клеток в 8 байт. Окно взято из
; лесенки $D5B2 оригинала (ENGINE.MD §3.5) — блиттер рисует не весь столбец,
; а только перечисленные клетки, поэтому в кадре одна лента, а не три полосы
; мусора. Окно берётся ровно как в оригинале: в кольце нет продолжения сцены
; ниже 192-й строки (байты перед окном — предыдущий столбец кольца), поэтому
; строки 192..255 экрана Вектора остаются чёрными — там зона панели меню.
;
; ЦВЕТ. Весь рельеф жёлтый = логический цвет 1 = бит 0 = плоскость веса 1
; (0xE000). В плоскости веса 2 (0xC000) рельеф не пишет ничего — она должна
; быть нулевой (main.c зачищает обе плоскости ДО вызова, заодно убирая
; остатки заставки). Так что здесь один проход, один поток указателей.
;
; КУДА ИМЕННО В VRAM. Байт плоскости адресуется как base + столбец*256 +
; (255 - строка), поэтому столбец — это 256-байтовая колонка, растущая вниз
; адресом = вверх по экрану. Нижняя клетка окна kbot начинается с байта
; 248 - 8*kbot — он и лежит в terrain_geom (par «старт, клеток»). Дальше
; клетки идут ПОДРЯД по возрастанию адреса (вверх по экрану) — ровно в том
; порядке, как их читает оригинал (ENGINE.MD §3.5: блиттер пишет вверх).
;
; ЦЕНА. ~485 клеток * (8 байт копии + ~70 тактов на указатель и счётчик)
; ≈ 130 тыс. тактов ≈ 0.05 с — один раз, до показа кадра.
;
; Только 8080: без LDIR/LDDR/JR/DJNZ/IX/IY и префиксов CB/DD/ED/FD.

        SECTION code_clib
        PUBLIC  _terrain_draw

; ---------------------------------------------------------------------------
; void terrain_draw(void)
;
; Рельеф целиком в буфер A. Рисовать до показа кадра (gfx_dblbuf_present или
; fade-in): на экране в этот момент ещё чёрная палитра.
; ---------------------------------------------------------------------------
_terrain_draw:
        lxi     b, 0E000h           ; приёмник: плоскость веса 1, столбец 0
        lxi     d, terrain_c1       ; поток указателей на 8-байтные блоки
        lxi     h, terrain_geom     ; пары (старт, клеток) по столбцам
        lda     terrain_cols        ; 32 — из terrain.inc
        sta     t_cols
t_col:
        mov     a, b                ; старший байт адреса — свой у столбца
        sta     t_base
        mov     a, m                ; старт: байт нижней клетки в столбце
        mov     c, a
        inx     h
        mov     a, m                ; клеток в окне этого столбца
        sta     t_cnt
        inx     h
        push    h                   ; HL нужен копированию — геометрию в стек
t_cell:
        ldax    d               ; 7   адрес блока: сначала младший байт
        mov     l, a            ; 5
        inx     d               ; 6
        ldax    d               ; 7   затем старший
        mov     h, a            ; 5
        inx     d               ; 6
        mov     a, m            ; 7   --- 8 байт блока: (HL) -> (BC) ---
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        mov     a, m            ; 7
        stax    b               ; 7
        inx     b               ; 6
        inx     h               ; 6
        lda     t_cnt           ; 13  конец окна: клетки кончились
        dcr     a               ; 5
        sta     t_cnt           ; 13
        jnz     t_cell          ; 10
        pop     h
        lda     t_base          ; 13  следующий байтовый столбец VRAM
        inr     a               ; 5   (C за время столбца мог перейти через 0)
        mov     b, a            ; 5
        lda     t_cols          ; 13
        dcr     a               ; 5
        sta     t_cols          ; 13
        jnz     t_col           ; 10
        ret

        SECTION bss_clib

t_cols: defs    1               ; осталось столбцов
t_base: defs    1               ; старший байт адреса текущего столбца
t_cnt:  defs    1               ; осталось клеток в окне столбца

; Данные — в конце файла: terrain.inc открывает SECTION rodata_user сам,
; и до его включения по коду уже ничего не должно идти.
        INCLUDE "terrain.inc"
