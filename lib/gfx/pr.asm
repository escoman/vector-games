;
; graphpr.asm — быстрый вывод текста шрифтом 8x8 (Вектор-06Ц).
;
; Заменяет C-функции gfx_put_char и gfx_print (graph.c).
;
;   void gfx_put_char(unsigned char x, unsigned char y, char ch,
;                       unsigned char color);
;   void gfx_print(unsigned char x, unsigned char y, const char *s,
;                    unsigned char color);
;
; Соглашение вызова z88dk classic — по выводу компилятора этих функций
; (zcc -S): аргументы лежат в стеке в 16-битных слотах, значение в
; младшем байте. gfx_put_char: color sp+2, ch sp+4, y sp+6, x sp+8;
; gfx_print: color sp+2, s sp+4 (слово), y sp+6, x sp+8. Стек чистит
; вызывающий, поэтому функции НЕ трогают SP (никаких push/pop) и
; просто делают ret.
;
; Ячейка 8x8: пиксели глифа — цвет color (0-15), фон ячейки
; затирается. x должно быть кратно 8, y — верхняя строка ячейки.
; Неизвестный символ шрифта с таблицей имён рисуется глифом 0.
;
; Шрифт подключается во время работы: gfx_select_font() меняет
; текущий дескриптор (см. gfx_font_t в v06.h), поэтому одним и тем
; же вызовом gfx_print можно напечатать разными шрифтами. До
; первого вызова работает шрифт, собранный в ROM (_gfx_font_8x8).
;
; Дескриптор с chars = 0 вместо таблицы имён задаёт прямой индекс по
; коду символа в диапазоне first_code..last_code; коды вне диапазона
; не рисуются совсем (клетка остаётся нетронутой).
;
; Видеопамять: блок символа = (x/8)*256 байт внутри каждой плоскости
; (0x8000 + n*0x2000); строка y блока — по адресу (256-y)&0xFF, строки
; вниз — уменьшение адреса.
;
; Только 8080-инструкции: без jr/djnz и без префиксов CB/DD/ED/FD.
;

        SECTION code_clib

        PUBLIC  _gfx_put_char
        PUBLIC  _gfx_print
        PUBLIC  _gfx_select_font
        PUBLIC  _gfx_font_8x8

        ; Маска активных плоскостей текущего видеорежима (mode.c).
        ; Биты совпадают с маской B ниже: bit0→E000, bit1→C000,
        ; bit2→A000, bit3→8000.
        EXTERN  _gfx_active_planes

; ---------------------------------------------------------------
; void gfx_put_char(unsigned char x, unsigned char y,
;                     char ch, unsigned char color)
;   __z88dk_callee
;
; Аргументы на входе:
;
;   fill? Нет.
;
; После CALL стек:
;
;   SP -> return address
;          color
;          ch
;          y
;          x
;
; Забираем всё через POP и возвращаем return address обратно.
;
; x:
;   0..31, номер столбца (каждый столбец = 8 пикселей).
;
; y:
;   0..248, верхняя строка символа.
;
; color:
;   bit 3 -> плоскость E000-FFFF
;   bit 2 -> плоскость C000-DFFF
;   bit 1 -> плоскость A000-BFFF
;   bit 0 -> плоскость 8000-9FFF
;
; Неизвестный символ = пробел.
; ---------------------------------------------------------------

_gfx_put_char:

        ; Снимаем return address.
        pop     de

        ; color
        pop     hl
        ld      a, l
        ld      (tmp_color), a

        ; ch
        pop     hl
        ld      a, l
        ld      (tmp_ch), a

        ; y
        pop     hl
        ld      a, l
        ld      (tmp_y), a

        ; x
        pop     hl
        ld      a, l
        ld      (tmp_x), a

        ; Возвращаем return address.
        push    de

        jp      draw_char


; ---------------------------------------------------------------
; draw_char
;
; Внутренняя отрисовка одного символа.
;
; Входные данные:
;
;   tmp_x
;   tmp_y
;   tmp_ch
;   tmp_color
;
; Стек не изменяется.
;
; Регистры:
;
;   HL = адрес текущего байта VRAM
;   DE = указатель текущего глифа
;   C  = color
;   B  = маска плоскости
; ---------------------------------------------------------------

draw_char:

        ; =======================================================
        ; Текущий шрифт.
        ;
        ; tmp_font — адрес дескриптора (gfx_font_t). Из него
        ; выбираем два слова: таблицу имён и данные глифов.
        ; Читаем один раз на символ, дальше идёт как раньше.
        ; =======================================================

        ld      hl, (tmp_font)
        ld      a, (hl)
        ld      (tmp_chars), a
        inc     hl
        ld      a, (hl)
        ld      (tmp_chars + 1), a
        inc     hl
        ld      a, (hl)
        ld      (tmp_glyphs), a
        inc     hl
        ld      a, (hl)
        ld      (tmp_glyphs + 1), a

        ; =======================================================
        ; Ищем индекс глифа E.
        ;
        ; chars = 0  -> прямой индекс: E = код - first_code.
        ;               Код вне [first_code..last_code] пропускаем,
        ;               клетку не затираем.
        ; chars != 0 -> линейный поиск в таблице имён, неизвестный
        ;               символ = глиф 0 (пробел).
        ; =======================================================

        ld      a, (tmp_ch)
        ld      c, a

        ld      hl, (tmp_chars)
        ld      a, h
        or      l
        jp      z, dc_direct

        ld      e, 0

dc_find:
        ld      a, (hl)
        or      a
        jp      z, dc_not_found

        cp      c
        jp      z, dc_found

        inc     hl
        inc     e
        jp      dc_find

dc_not_found:
        ld      e, 0
        jp      dc_found

        ; =======================================================
        ; Прямой индекс. Границы лежат в словах дескриптора +4
        ; (first_code) и +6 (last_code), значим младшие байты.
        ;
        ; Шаг глифа в дескрипторе не нужен: он известен из формата
        ; шрифта и равен 8 байтам.
        ; =======================================================

dc_direct:

        ; HL = tmp_font + 4 (16-битное сложение с переносом)
        ld      hl, (tmp_font)
        ld      a, l
        adi     4
        ld      l, a
        ld      a, h
        aci     0
        ld      h, a

        ld      b, (hl)               ; B = first_code
        inc     hl
        inc     hl                    ; HL = last_code
        ld      a, (hl)
        sub     b                     ; D = last_code - first_code,
        jp      c, dc_range_out       ; макс. индекс; first > last –
        ld      d, a                  ; неверный шрифт, ничего не рисует

        ld      a, (tmp_ch)
        sub     b                     ; индекс = код - first_code
        jp      c, dc_range_out       ; код меньше first_code
        cp      d
        jp      z, dc_direct_ok       ; код == last_code
        jp      nc, dc_range_out      ; код больше last_code
dc_direct_ok:
        ld      e, a                  ; E = индекс глифа

dc_found:

        ; =======================================================
        ; HL = font8x8 + index * 8
        ; =======================================================

        ld      h, 0
        ld      l, e

        add     hl, hl
        add     hl, hl
        add     hl, hl

        ld      de, (tmp_glyphs)
        add     hl, de

        ; Сохраняем адрес глифа.
        ld      (tmp_glyph), hl

        ; =======================================================
        ; Вычисляем начальный адрес VRAM.
        ;
        ; Плоскость 8000:
        ;
        ;   8000 + x*256 + (255-y)
        ;
        ; Например:
        ;
        ;   x=0,  y=0   -> 80FF
        ;   x=1,  y=0   -> 81FF
        ;   x=0,  y=8   -> 80F7
        ;   x=31, y=248 -> 9F07
        ;
        ; Внутри символа адрес уменьшается на 1.
        ; =======================================================

        ; x (столбец 0-31)
        ld      a, (tmp_x)
        and     31

        ; 80h + номер блока
        add     a, 80h
        ld      h, a

        ; 255 - y
        ld      a, (tmp_y)
        cpl
        ld      l, a

        ; =======================================================
        ; C = color
        ; B = маска текущей плоскости.
        ;
        ; Порядок:
        ;
        ;   B=08 -> E000
        ;   B=04 -> C000
        ;   B=02 -> A000
        ;   B=01 -> 8000
        ; =======================================================

        ld      a, (tmp_color)
        ld      c, a

        ld      b, 08h


; ===============================================================
; Следующая плоскость
; ===============================================================

dc_plane:

        ; -------------------------------------------------------
        ; Пропускаем плоскости, не входящие в текущий видеорежим:
        ; неактивную плоскость не пишем и не стираем.
        ; -------------------------------------------------------

        ld      a, (_gfx_active_planes)
        and     b
        jp      z, dc_skip

        ; -------------------------------------------------------
        ; DE = начало текущего глифа.
        ; -------------------------------------------------------

        ld      de, (tmp_glyph)

        ; -------------------------------------------------------
        ; Проверяем цветовой бит.
        ; -------------------------------------------------------

        ld      a, c
        and     b
        jp      z, dc_clear


        ; =======================================================
        ; Цветной глиф.
        ; Записываем 8 строк.
        ;
        ; После каждой строки:
        ;
        ;   DE++
        ;   HL--
        ; =======================================================

        ld      a, (de)
        ld      (hl), a
        inc     de
        dec     hl

        ld      a, (de)
        ld      (hl), a
        inc     de
        dec     hl

        ld      a, (de)
        ld      (hl), a
        inc     de
        dec     hl

        ld      a, (de)
        ld      (hl), a
        inc     de
        dec     hl

        ld      a, (de)
        ld      (hl), a
        inc     de
        dec     hl

        ld      a, (de)
        ld      (hl), a
        inc     de
        dec     hl

        ld      a, (de)
        ld      (hl), a
        inc     de
        dec     hl

        ld      a, (de)
        ld      (hl), a
        dec     hl

        jp      dc_plane_next


; ===============================================================
; Нулевая плоскость.
;
; Если соответствующий бит color = 0, фон символа должен
; быть очищен.
; ===============================================================

dc_clear:

        xor     a

        ld      (hl), a
        dec     hl

        ld      (hl), a
        dec     hl

        ld      (hl), a
        dec     hl

        ld      (hl), a
        dec     hl

        ld      (hl), a
        dec     hl

        ld      (hl), a
        dec     hl

        ld      (hl), a
        dec     hl

        ld      (hl), a
        dec     hl


; ===============================================================
; Переход к следующей плоскости.
;
; После 8 × DEC HL:
;
;   HL = исходный адрес - 8
;
; Нужно получить:
;
;   исходный адрес + 2000h
;
; поэтому добавляем 2008h.
;
; Используем полноценную 16-битную арифметику с переносом.
; ===============================================================

dc_plane_next:

        ; После записи/очистки HL уменьшен на 8 — компенсируем и
        ; переходим на следующую плоскость: +2008h.
        ld      a, l
        adi     08h
        ld      l, a

        ld      a, h
        aci     20h
        ld      h, a

        jp      dc_mask_next

        ; -------------------------------------------------------
        ; Плоскость неактивна: запись не производилась, HL не менялся.
        ; Переход на следующую плоскость: +2000h (H += 20h).
        ; -------------------------------------------------------

dc_skip:

        ld      a, h
        adi     20h
        ld      h, a

        ; -------------------------------------------------------
        ; Следующая маска:
        ;
        ; 08 -> 04
        ; 04 -> 02
        ; 02 -> 01
        ; 01 -> 80
        ;
        ; После обработки плоскости 01 завершаем.
        ; -------------------------------------------------------

dc_mask_next:

        ld      a, b
        rrca
        ld      b, a

        cp      80h
        jp      nz, dc_plane

        ret


; ---------------------------------------------------------------
; Код вне диапазона шрифта прямого индекса: в VRAM не пишем ничего.
; ---------------------------------------------------------------

dc_range_out:

        ret


; ---------------------------------------------------------------
; void gfx_print(unsigned char x, unsigned char y,
;                  const char *s, unsigned char color)
;   __z88dk_callee
;
; Выводит строку символов с шагом 8 пикселей.
;
; DE = указатель строки во время цикла.
; draw_char может портить DE, поэтому указатель сохраняется
; обычным PUSH/POP вокруг CALL.
; ---------------------------------------------------------------

_gfx_print:

        ; return address
        pop     de

        ; color
        pop     hl
        ld      a, l
        ld      (tmp_color), a

        ; s
        pop     hl
        ld      (tmp_s), hl

        ; y
        pop     hl
        ld      a, l
        ld      (tmp_y), a

        ; x
        pop     hl
        ld      a, l
        ld      (tmp_x), a

        ; return address обратно
        push    de

        ; DE = строка
        ld      de, (tmp_s)


; ===============================================================
; Цикл вывода строки
; ===============================================================

dp_loop:

        ld      a, (de)
        or      a
        jp      z, dp_done

        ; DE указывает на следующий символ после INC.
        inc     de

        ; Сохраняем указатель строки.
        push    de

        ; Текущий символ.
        ld      (tmp_ch), a

        ; Рисуем.
        call    draw_char

        ; Восстанавливаем указатель строки.
        pop     de

        ; x += 1 (следующий столбец)
        ld      a, (tmp_x)
        inc     a
        ld      (tmp_x), a

        jp      dp_loop


dp_done:
        ret


; ---------------------------------------------------------------
; void gfx_select_font(const gfx_font_t *font)
;   __z88dk_callee
;
; Меняет текущий шрифт. Аргумент — адрес дескриптора
; (gfx_font_t из v06.h); вызов действует на все последующие
; gfx_put_char / gfx_print.
;
; font = 0 возвращает шрифт, собранный в ROM (_gfx_font_8x8).
;
; После CALL стек:
;
;   SP -> return address
;          font
; ---------------------------------------------------------------

_gfx_select_font:

        ; return address
        pop     de

        ; font
        pop     hl

        ; NULL -> шрифт по умолчанию
        ld      a, h
        or      l
        jp      nz, sel_user

        ld      hl, _gfx_font_8x8

sel_user:
        ld      (tmp_font), hl

        ; return address обратно
        push    de

        ret


; ---------------------------------------------------------------
; Временные переменные.
; ---------------------------------------------------------------

tmp_x:
        defb    0

tmp_y:
        defb    0

tmp_ch:
        defb    0

tmp_color:
        defb    0

tmp_glyph:
        defw    0

tmp_s:
        defw    0

; ---------------------------------------------------------------
; Текущий шрифт.
;
; tmp_font   — адрес дескриптора; инициализируется при сборке
;              шрифтом из ROM, gfx_select_font меняет его на ходу.
; tmp_chars, tmp_glyphs — два слова дескриптора, разобранные
;              один раз на символ (см. draw_char).
; ---------------------------------------------------------------

tmp_font:
        defw    _gfx_font_8x8

tmp_chars:
        defw    0

tmp_glyphs:
        defw    0


; ---------------------------------------------------------------
; Шрифт 8x8.
;
; Данные по умолчанию — fonts/default_8x8.inc. Путь разрешается
; относительно каталога этого файла, передавать -I не нужно.
;
; Шрифт целиком можно заменить на собранный в игре: для этого в
; SRCS добавляется модуль вида
;
;         SECTION code_clib
;         PUBLIC  font_chars
;         PUBLIC  font8x8
;
;   font_chars:
;         defm    " ..."
;         defb    0
;   font8x8:
;         defb    ...
;
; и собирается с -Ca-DFONT_EXTERNAL: тогда вместо INCLUDE обе
; метки объявляются как EXTERN и линкуются из того модуля.
;
; Второй вариант — не заменять шрифт по умолчанию, а добавить
; в ROM ещё один дескриптор и переключать его gfx_select_font
; (так печатают несколькими шрифтами на одном экране).
; ---------------------------------------------------------------

        ifdef   FONT_EXTERNAL
        EXTERN  font_chars
        EXTERN  font8x8
        else
        INCLUDE "fonts/default_8x8.inc"
        endif


; ---------------------------------------------------------------
; Дескриптор шрифта по умолчанию. Структура gfx_font_t (v06.h):
;
;   word 0  адрес таблицы имён   (font_chars, 0 = конец таблицы)
;   word 1  адрес данных глифов  (font8x8)
;   word 2  первый код символа   (first_code, младший байт)
;   word 3  последний код        (last_code, младший байт)
;
; Слова 2 и 3 работают только при chars = 0 (прямой индекс), поэтому у
; шрифта по умолчанию они заполнены нулём.
;
; ---------------------------------------------------------------

_gfx_font_8x8:
        defw    font_chars
        defw    font8x8
        defw    0
        defw    0
