; fire.asm — огонь 64×20 в 4 оттенка + DOUBLE BUFFER для Вектора-06Ц.
;
; Три функции, все __z88dk_callee (аргументы на стеке, callee их снимает):
;   void rnd_init(void)                       — ГСЧ-таблица + обнуление буфера
;   void fire_generate(unsigned char power)   — один кадр симуляции (значения 0..3)
;   void fire_paint(unsigned char back)       — «тайлер»: fire_buf → 2 плоскости VRAM
;
; Double buffer (как в mario-dbl): экран — ДВЕ пары плоскостей,
;   буфер A = E000 (вес 1) + C000 (вес 2)   → биты 0..1 цветного индекса
;   буфер B = A000 (вес 4) + 8000 (вес 8)   → биты 2..3 цветного индекса
; На экране виден тот буфер, чья маска загружена в палитру (16 слотов).
; Рисуем всегда в НЕвидимый буфер, показываем его загрузкой палитры в гашении
; ⇒ нет гонок с лучом, нет стирания кадра, DI на время отрисовки не нужен.
;
; fire_buf — «байт на пиксель», значение 0..VALMAX, шаг строки 256 (страница).
; Пиксель x лежит по смещению GUARD+x; клетки +0 и +65 — копии крайних точек,
; поэтому сбор сдвигом ±1 не требует ветки на перенос строки.
;
; Только инструкции Intel 8080 (без jr/djnz, без префиксов CB/DD/ED/FD).

        PUBLIC  _rnd_init
        PUBLIC  _fire_generate
        PUBLIC  _fire_paint

FIRE_W  EQU 64                        ; ширина огня (точек)
FIRE_H  EQU 20                        ; высота огня (точек)
SCALE_Y EQU 4                         ; вертикальное увеличение (строк VRAM на точку)
GUARD   EQU 1                         ; пиксель x — по смещению GUARD+x
ROWEND  EQU GUARD + FIRE_W            ; 65 — «строка готова»
STRIDE  EQU 256                       ; шаг строки fire_buf (страница ⇒ без переносов)
;
; ГСЧ — ОДНО окно псевдослучайного потока, отсчитываемое курсором _rnd_off.
; Раньше был LCG (seed*251+73, выход — старший байт): его байты связаны
; соотношением h(n+1) ≈ -5*h(n) по модулю 256, из-за чего биты сдвига (r&3)
; ходили закономерной последовательностью и на огне проступала сетка.
; Теперь таблицу заполняет Галуа-LFSR16 (маска 0xB400, taps 16/14/13/11,
; период 65535), выходной байт = старший⊕младший: соседние байты не связаны
; арифметикой.
;
; НО честный независимый шум сам по себе даёт «кипящие» точки: соседние
; точки выбирают источник независимо, язык за 20 рядов блуждает в стороны
; и распадается. Поэтому биты 0..1 (направление сдвига) в таблице ДЕРЖАТСЯ:
; меняются только когда (r & RNG_HOLD) == 0, то есть в среднем раз из 4
; шагов. Получается цепочка случайной длины — пламя тянется вверх одним
; наклоном, как у настоящего огня, а длины и позиции цепочек случайны,
; так что прежней «сетки» не возникает. Биты 2..4 (затухание) при этом
; остаются честным шумом и с направлением не связаны.
;
; Держать же сами биты 0..1 «как выпали» НЕЛЬЗЯ: длина удержания
; коррелирует с тем самым значением k, и в готовой таблице распределение
; съезжает (замер по окну 1024: ← 34%, прямо 60%, → 5.7%). Средний снос
; пакета тепла от базы до верха при этом -5.3 клетки из 64 — пламя
; выглядит так, будто на него дует ветер слева направо. Направление
; поэтому не рисуется случайным, а ЧЕРЕДУЕТСЯ: бит RNG_STRAIGHT решает
; «прямо» или «вбок», а знак бокового хода переключает _lfsr_dir —
; соседние боковые цепочки всегда смотрят в разные стороны, средний снос
; строго ноль по построению (замер: -0.2 клетки, разброс 2.4).
RNG_N   EQU 1024                      ; ячеек окна
RNG_TAIL EQU 128                      ; копия начала в конец (строка читает ≤ 64+7)
RNG_HI  EQU RNG_N / 256               ; 4: заворот смещения по старшему байту
RNG_SEED EQU 0ACEh                    ; состояние LFSR на старте (обязательно ≠ 0)
RNG_HOLD  EQU 0C0h                    ; биты «менять ли направление»: 1 раз из 4
RNG_STRAIGHT EQU 20h                  ; бит «прямо» против бокового хода (1/2)
SEED_R  EQU 7                         ; сдвиг курсора ГСЧ на строку
RNG_EMBER EQU 40h                     ; бит байта ГСЧ, решающий «остыл уголёк»
ROW_ADV EQU FIRE_W + SEED_R           ; 71 — курсор, съедаемый одной строкой
FRAME_R EQU 5                         ; нечётная добавка кадра ⇒ фаза ходит по всему окну
VRAM_END EQU FIRE_H * SCALE_Y         ; 80 — верх огненной зоны в столбце
ROWBACK EQU SCALE_Y - 1               ; смещение последней строки прогона внутри точки
ROWTOP  EQU VRAM_END + ROWBACK        ; 83 — E после последней строки (прогон вниз)
VALMAX  EQU 3                         ; максимальное значение (4 оттенка)
;
; Затухание зависит от ВЫСОТЫ: язык пламени теряет единицу яркости, когда
; (rnd & маска) == 0; маски подобраны так, чтобы матожидание высоты
; укладывалось в FIRE_H и верхний край не обрезался (было 1/8 на всех
; строках ⇒ ~3·8 = 24 строки при буфере в 20).
;   y <  TAPER_1 — DM_LO  (1Ch, 1 раз из 8) — основной массив пламени;
;   y <  TAPER_2 — DM_MID (18h, 1 раз из 4) — верхушки начинают гаснуть;
;   y >= TAPER_2 — DM_HI  (04h, 1 раз из 2) — последние 3 строки догорают.
; Подбор 14/17 (VALMAX=3, считан по модели): средняя высота языка ~15.3
; строки из 20, на ВЕРХНЕЙ строке буфера ярких точек ~3 из 64 (было ~7 при
; 1/8 везде — это и заметалось о край), а соседний кадр меняет поле высот
; на ~3.3 строки вместо 3.4 у старого LCG.
TAPER_1 EQU FIRE_H - 6                ; 14
TAPER_2 EQU FIRE_H - 3                ; 17
DM_LO   EQU 1Ch
DM_MID  EQU 18h
DM_HI   EQU 04h
LFSR_TAPS EQU 0B4h                    ; Галуа-LFSR16, маска 0xB400 (taps 16/14/13/11):
                                      ; обратная связь бьёт только в старший байт
; В fire_buf значения лежат УМНОЖЕННЫМИ НА 2: 0,2,4,6. Тогда смещение пары
; точек в таблице упаковки = 4*left + right (left/right — хранёные значения),
; то есть 2*(4L+R) = idx*2 без отдельного удвоения индекса.
; Цена — вычитание при затухании стало `sui 2`.
VSCALE  EQU 2                         ; множитель значения в fire_buf
VMAX    EQU VALMAX * VSCALE           ; 6

; ================================================================
; BSS
; ================================================================
        SECTION bss_clib
        ALIGN 256
_rnd_table:     defs RNG_N + RNG_TAIL ; окно LFSR[0..1023] + копия [0..127]
_rnd_off:       defw 0                ; смещение курсора в окне, 0..RNG_N-1

        ALIGN 256                     ; ⇒ каждая строка = страница, L = смещение
_fire_buf:      defs FIRE_H * STRIDE  ; 5120 байт, значение 0..VALMAX на точку

; Рабочая таблица упаковки. Специально в bss, а не в code: «ALIGN 256» в начале
; вклада файла в code_clib не даёт ВЫРОВНЕННОГО абсолютного адреса (смещение
; внутри секции нулевое ⇒ подложки нет, а линкер ставит секцию на $0182), и
; приём «lxi h,_pt / mov l,a» читал бы мусор вместо таблицы. Копия в bss
; попадает на ту же страницу, что и _fire_buf (5120 кратно 256), и
; контролируется проверкой карты в Makefile.
_pt:            defs 32               ; 16 пар (p0,p1), страница

_fg_power:      defb 0                ; порог базовой строки
_fg_y:          defb 0                ; номер генерируемой строки
_lfsr_raw:      defb 0                ; служебные ячейки заполнения таблицы
_lfsr_k:        defb 0                ; удерживаемое направление сдвига (биты 0..1)
_lfsr_dir:      defb 0                ; чередователь знака бокового хода (0 / FF)

_fr_base0:      defb 0                ; старший байт плоскости веса 1 (E0h или A0h)
_fr_base1:      defb 0                ;    ... и плоскости веса 2 (на 0x20 ниже)

; ================================================================
; Код
; ================================================================
        SECTION code_clib

; ---------------------------------------------------------------
; Таблица упаковки пары точек в байты двух плоскостей.
; Индекс idx = (left << 2) | right, left/right ∈ 0..3; left — ЛЕВЫЙ пиксель
; байта плоскости (биты 4..7), right — правый (биты 0..3). Записи идут парами
; (p0, p1), поэтому смещение = idx*2. Одна и та же таблица и для буфера A
; (веса 1/2), и для буфера B (веса 4/8) — набор битов внутри пары одинаков.
; ALIGN не нужен: это источник для копирования, индексация идёт по _pt в bss.
; ---------------------------------------------------------------
_pt_src:
        defb 00h,00h                  ;  0: (0,0)
        defb 0Fh,00h                  ;  1: (0,1)
        defb 00h,0Fh                  ;  2: (0,2)
        defb 0Fh,0Fh                  ;  3: (0,3)
        defb 0F0h,00h                 ;  4: (1,0)
        defb 0FFh,00h                 ;  5: (1,1)
        defb 0F0h,0Fh                 ;  6: (1,2)
        defb 0FFh,0Fh                 ;  7: (1,3)
        defb 00h,0F0h                 ;  8: (2,0)
        defb 0Fh,0F0h                 ;  9: (2,1)
        defb 00h,0FFh                 ; 10: (2,2)
        defb 0Fh,0FFh                 ; 11: (2,3)
        defb 0F0h,0F0h                ; 12: (3,0)
        defb 0FFh,0F0h                ; 13: (3,1)
        defb 0F0h,0FFh                ; 14: (3,2)
        defb 0FFh,0FFh                ; 15: (3,3)

; ================================================================
; void rnd_init(void)  __z88dk_callee
;
;   state = 0ACEh; k = 0; dir = 0;
;   for (i = 0; i < 1024; i++) {                 // Галуа-LFSR16, маска 0xB400
;       fb = state & 1; state >>= 1;
;       if (fb) state ^= 0xB400;
;       r = hi(state) ^ lo(state);
;       if ((r & 0xC0) == 0) {                   // раз из 4 — новое направление
;           if (r & 0x20) k = 1 + (dir ^= 1);    //   вбок, знак ЧЕРЕДУЕТСЯ
;           else          k = 0;                 //   «прямо»
;       }
;       rnd_table[i] = (r & 0xFC) | k;           // держится, пока не событие
;   }
;   rnd_table[1024..1151] = rnd_table[0..127];   // хвост, чтобы строка не
;   rnd_off = 0; fire_buf[] = 0;                    переносилась в середине
; Стоимость — ~90 тактов на байт, но это ОДНОСВРЕМЕННО при старте: ~1.5
; кадра до первой картинки. Внутренний цикл генерации не дорожает ничего.
; ================================================================
_rnd_init:
        push    bc
        push    de
        push    hl

        lxi     h,0
        shld    _rnd_off
        mvi     a,0
        sta     _lfsr_k               ; BSS не обнуляется (--no-crt) — обнуляем сами
        sta     _lfsr_dir
        lxi     h,_rnd_table
        lxi     b,RNG_N
        lxi     d,RNG_SEED
ri_loop:
        ; 16-битный сдвиг вправо: два RAR подряд, CY обнулена (XRA A),
        ; после второго RAR CY = бит0 состояния = сигнал обратной связи
        xra     a
        mov     a,d
        rar
        mov     d,a
        mov     a,e
        rar
        mov     e,a
        jnc     ri_nofb
        mov     a,d
        xri     LFSR_TAPS
        mov     d,a
ri_nofb:
        mov     a,d
        xra     e                     ; выходной байт = старший ⊕ младший
        sta     _lfsr_raw
        ani     RNG_HOLD              ; смена направления — когда все биты
        jnz     ri_keep               ;   держания нули (в среднем раз из 4)
        lda     _lfsr_raw
        ani     RNG_STRAIGHT          ; половина событий — «прямо», остальные
        jz      ri_straight           ;   вбок, и знак бокового хода чередуется
        lda     _lfsr_dir
        cma
        sta     _lfsr_dir
        ani     1
        adi     1                     ; k = 1 (источник левее) или 2 (правее)
        jmp     ri_newk
ri_straight:
        xra     a                     ; k = 0 — источник ровно снизу
ri_newk:
        sta     _lfsr_k
ri_keep:
        lda     _lfsr_k
        mov     m,a                   ; предзапись: k лежит в (HL), им и ORим
        lda     _lfsr_raw
        ani     0FCh
        ora     m                     ; (r & 0FC) | k
        mov     m,a
        inx     h
        dcx     b
        mov     a,b
        ora     c
        jnz     ri_loop

        ; Хвост-копия: курсор строки стартует с off ≤ 1023 и читает 64 байта
        ; (нужно ≤ 1086), переноса внутри строки нет — mod считается раз в
        ; строку, а не на пиксель.
        lxi     h,_rnd_table
        lxi     d,_rnd_table + RNG_N
        lxi     b,RNG_TAIL
ri_ext:
        mov     a,m
        stax    d
        inx     h
        inx     d
        dcx     b
        mov     a,b
        ora     c
        jnz     ri_ext

        ; Копия таблицы упаковки в выровненную RAM-копию (см. _pt в bss).
        lxi     h,_pt_src
        lxi     d,_pt
        lxi     b,32
ri_pt:
        mov     a,m
        stax    d
        inx     h
        inx     d
        dcx     b
        mov     a,b
        ora     c
        jnz     ri_pt

        ; Обнуление fire_buf — заодно занулены страховые клетки всех строк.
        lxi     h,_fire_buf
        lxi     d,FIRE_H * STRIDE
ri_clr:
        mvi     m,0
        inx     h
        dcx     d
        mov     a,d
        ora     e
        jnz     ri_clr

        pop     hl
        pop     de
        pop     bc
        ret

; ================================================================
; Внутренняя служба: _rnd_off += BC (mod RNG_N). Портит A и HL; BC/DE/стек
; целые — вызывается из цикла строк, где DE держит приёмную строку.
; После сложения off < RNG_N + ROW_ADV < 2048, поэтому заворот — это ровно
; одно вычитание 1024 из СТАРШЕГО байта (мл. байт при вычитании целого
; числа страниц не меняется).
; ================================================================
_fg_adv:
        lhld    _rnd_off
        dad     b
        mov     a,h
        cpi     RNG_HI
        jc      fga_store
        sui     RNG_HI
        mov     h,a
fga_store:
        shld    _rnd_off
        ret

; ================================================================
; void fire_generate(unsigned char power)  __z88dk_callee
;
; Порядок прохода: сначала базовая строка (её прежнее значение нужно для
; «угольков»), затем строки 1..FIRE_H-1 снизу вверх — каждая точка берётся
; из ТОЛЬКО ЧТО посчитанной строки ниже. Это НЕ in-place вариант из
; fire.html (там клетка читает соседа снизу из прошлого кадра): при 4
; оттенках накопленное случайное блуждание по вертикали рассыпается в
; «соль с перцем», а пересчёт от базы даёт связные языки. Проверено
; офлайн (.scratch/fire_inplace.py): in-place связаннее по кадрам, но
; картинкой выглядит хуже.
;
; Регистры на весь цикл:
;   DE — точка ПРИЁМНОЙ строки (y), +1 на точку; строка готова ⇒ E == ROWEND.
;        Источник (строка y-1) — это DE−256, то есть та же страница на одну
;        ниже. Запись точки — `stax d` (8T) вместо перекладывания HL/DE
;        (mov c,a / mov h,d / mov l,e / inr h / mov m,c / inx d = 48T):
;        экономия 24 такта на точку, цена — один dcr h в сборе.
;   HL — временный: carrier курсора ГСЧ (pop/push), адрес сбора (DE−256±1).
;   B  — rnd правой точки пары, C — rnd левой.
; Курсор ГСЧ живёт на стеке (п. 1а fire2): чтение = pop h/mov c,m/inx h/
; mov b,m/inx h/push h = 64 такта на пару точек (32 на точку вместо 56 при
; одном байте на точку). Смещение в окне догоняется РАЗ в конце строки
; (_fg_adv), а не на каждый пиксель.
;
; Раскладка регистров внутри строки: C — ГСЧ левой точки пары, B — правой,
; A — временный под расчёт сдвига и затухания. Чтение источника сделано
; ПОСЛЕ проверки затухания и продублировано в двух ветках: регистр под
; `above` освобождается, и лишнего mov a,b на общем пути (75% точек) нет.
;
; Один байт ГСЧ на точку:
;   биты 0..1 — сдвиг источника: 0 или 3 → прямо, 1 → влево, 2 → вправо
;   (считается БЕЗ веток, см. внутренний комментарий цикла);
;   биты 2..4 — затухание по маске строки (см. TAPER_1/TAPER_2): до TAPER_1
;   единица яркости теряется в среднем раз из 8, выше — раз из 4 и раз из 2,
;   поэтому языки гасают ДО верха буфера, а не обрезаются им.
; ================================================================
_fire_generate:
        push    bc
        lxi     h,4
        dad     sp
        mov     a,m
        sta     _fg_power       ; power

        ; ---- базовая строка y=0 — с ПАМЯТЬЮ (как в исходном fire.html):
        ;      угольки копятся и остывают, а не переролливляются каждый кадр,
        ;      поэтому низ огня «дышит», а не мерцает:
        ;        r <= power            → VMAX   (вспышка);
        ;        иначе бит 6 r == 0    → prev - 1 оттенок (остыл);
        ;        иначе                 → prev   (без изменений).
        ; Бит 7 для теста не годится: r > power означает r >= 9Ah, то есть
        ; бит 7 там всегда единица и ветка остывания была бы недостижима.
        ; курсор ГСЧ идёт прямо по HL — в базовой строке HL свободен
        lhld    _rnd_off
        lxi     b,_rnd_table
        dad     b
        lxi     d,_fire_buf + GUARD
        mvi     b,0
fg_seed_loop:
        mov     a,m                     ; rnd
        inx     h
        mov     c,a
        lda     _fg_power
        cmp     c                       ; CY если power < rnd ⇒ вспышки нет
        jc      fg_seed_dim
        mvi     a,VMAX
        jmp     fg_seed_w
fg_seed_dim:
        mov     a,c
        ani     RNG_EMBER
        jnz     fg_seed_same
        ldax    d                       ; остыл на оттенок
        sui     VSCALE
        jnc     fg_seed_w
        xra     a                       ; был холодным — остаётся 0
        jmp     fg_seed_w
fg_seed_same:
        ldax    d                       ; оставить как было
fg_seed_w:
        stax    d                       ; *DE = значение
        inx     d
        inr     b
        mov     a,b
        cpi     FIRE_W
        jnz     fg_seed_loop

        ; базовая строка съедает FIRE_W курсора + нечётная добавка кадра
        lxi     b,ROW_ADV + FRAME_R
        call    _fg_adv

        ; страховые клетки базовой строки (HL = база строки)
        lxi     h,_fire_buf
        call    _fg_guards

        ; ---- строки y = 1 .. FIRE_H-1 ----
        mvi     a,1
        sta     _fg_y
        lxi     d,_fire_buf + STRIDE + GUARD   ; DE = приёмная строка 1 (источник 0)
fg_y_loop:
        ; ---- маска затухания ТЕКУЩЕЙ строки. Операнд ANI внутри цикла
        ;      патчится один раз на строку (ROM живёт в RAM ⇒ самоизменение
        ;      кода легально), цена ~60 тактов на строку и НОЛЬ на точку.
        ;      Порядок важен: оба CPI читают A = _fg_y, поэтому ни одно MVI
        ;      не может стоять МЕЖДУ сравнениями (MVI флаги не трогает, но
        ;      портит A — второй CPI сравнивал бы маску строки с порогом).
        lda     _fg_y
        cpi     TAPER_1
        jc      fg_dm_lo
        cpi     TAPER_2
        mvi     a,DM_MID
        jc      fg_dm_set
        mvi     a,DM_HI
        jmp     fg_dm_set
fg_dm_lo:
        mvi     a,DM_LO
fg_dm_set:
        sta     fg0_dmask + 1
        sta     fg1_dmask + 1

        ; ---- курсор ГСЧ строки = таблица + смещение, кладём в стек ----
        lhld    _rnd_off
        lxi     b,_rnd_table
        dad     b
        push    h                       ; курсор ГСЧ на весь проход строки

fg_x_loop:
        ; ---- ГСЧ: два байта за один съём указателя (C = левой точки, B = правой)
        pop     h
        mov     c,m                     ; rnd0
        inx     h
        mov     b,m                     ; rnd1
        inx     h
        push    h                       ; новый указатель возвращаем в стек

        ; ================= точка 0: источник = DE−256+s, запись в DE ========
        ; Сдвиг источника БЕЗ веток. Биты k = rnd&3 задают смещение
        ; s = (бит1) − (бит0) ∈ {0,−1,+1,0} (00→0, 01→−1, 10→+1, 11→0):
        ;   ANI 3 чистит CY ⇒ RAR даёт A = бит1, а CY = бит0;
        ;   SBI 0 вычитает заём ⇒ A = знаковое смещение в доп. коде;
        ;   ADD E складывает с мл. байтом приёмной точки — переходов нет:
        ;   E ∈ 1..64, s ∈ −1..+1 ⇒ L ∈ 0..65 всегда в своей странице.
        ; 56 тактов вместо «пересобрать HL из DE (24) + лестница ветков
        ; (в среднем 40)» = −24 такта на точку, −29k тактов на кадр.
        mov     a,c
        ani     3
        rar
        sbi     0
        add     e
        mov     l,a
        mov     h,d
        dcr     h                       ; та же точка строкой ниже
        mov     a,c                     ; затухание: (rnd & маска) == 0 → −1
fg0_dmask:
        ani     DM_LO
        jnz     fg0_nod
        mov     a,m                     ; above (MOV A,M = 8T)
        sui     VSCALE
        jc      fg0_zero                ; above был 0 → значение 0
        jmp     fg0_store
fg0_zero:
        xra     a
        jmp     fg0_store
fg0_nod:
        mov     a,m
fg0_store:
        stax    d                       ; *DE = значение
        inx     d

        ; ================= точка 1: rnd в B, DE уже сдвинута ================
        mov     a,b
        ani     3
        rar
        sbi     0
        add     e
        mov     l,a
        mov     h,d
        dcr     h
        mov     a,b
fg1_dmask:
        ani     DM_LO
        jnz     fg1_nod
        mov     a,m
        sui     VSCALE
        jc      fg1_zero
        jmp     fg1_store
fg1_zero:
        xra     a
        jmp     fg1_store
fg1_nod:
        mov     a,m
fg1_store:
        stax    d                       ; *DE = значение (rnd в B больше не нужен)
        inx     d                       ; следующая точка приёмной строки
        mov     a,e
        cpi     ROWEND
        jnz     fg_x_loop

        ; ---- конец строки: снять курсор ГСЧ и догнать смещение (+FIRE_W+SEED_R)
        inx     sp
        inx     sp
        lxi     b,ROW_ADV
        call    _fg_adv

        ; страховые клетки записанной строки: её база — страница DE
        mov     h,d
        mvi     l,0
        call    _fg_guards

        ; DE → следующая приёмная строка: сейчас DE = base+ROWEND,
        ; нужно base+256+GUARD ⇒ мл. байт ставим прямо, старший +1
        mvi     e,GUARD
        inr     d

        lda     _fg_y
        inr     a
        sta     _fg_y
        cpi     FIRE_H
        jnz     fg_y_loop

fg_gend:
        pop     bc
        pop     de              ; адрес возврата
        inx     sp
        inx     sp              ; съесть power
        push    de
        ret

; ---------------------------------------------------------------
; Внутренняя служба: страховые клетки строки, на которую указывает HL (база).
;   [GUARD-1] = значение x=FIRE_W-1, [GUARD+FIRE_W] = значение x=0.
; Портит A и L; H (страница строки) и BC/DE сохраняются, стек не трогает.
; ---------------------------------------------------------------
_fg_guards:
        mvi     l,GUARD + FIRE_W - 1
        mov     a,m                     ; значение x=63
        mvi     l,GUARD - 1             ; левый страховок
        mov     m,a
        mvi     l,GUARD
        mov     a,m                     ; значение x=0
        mvi     l,GUARD + FIRE_W        ; правый страховок
        mov     m,a
        ret

; ================================================================
; void fire_paint(unsigned char back)  __z88dk_callee
;
; «Тайлер»: обход fire_buf по парам точек, для каждой пары — два байта
; (плоскость веса 1 и плоскость веса 2), каждый записывается в SCALE_Y
; подряд идущих строк столбца (вертикальное увеличение).
;
; Регистры:
;   HL — курсор fire_buf (строка 256байт ⇒ признак конца строки L == ROWEND);
;   DE — адрес VRAM: D = base0 + col (+256 на пару = inr d), E = rowoff;
;   B/C — байты двух плоскостей пары;
;   на время чтения _pt курсор уходит в стек: push h / pop h (16+16 тактов)
;   дешевле, чем xthl (24) с постоянной carrier-ячейкой, — третья косвенная
;   пара в 8080 не помещается, а между итерациями курсор всё равно в HL.
;
; Прогон из SCALE_Y одинаковых байтов сделан ВСТРЕЧНЫМ: плоскость веса 1
; пишется сверху вниз (dcr e), плоскость веса 2 — снизу вверх (inr e). Оба
; прогона покрывают одни и те же SCALE_Y строк, а E возвращается на место
; самим вторым прогоном — три инструкции возврата E на каждую плоскость
; (mov a,e / sui / mov e,a) просто исчезают: −40 тактов на пару.
; Поэтому E при входе в пару = 4y+ROWBACK (последняя строка), а не 4y.
;
; Пара точек развёрнута ДВАЖДЫ (fr_pair / fr_pair1): 64 точки = 32 пары,
; чётно, и L идёт 1,3,…,65 ⇒ признака «конец строки» внутри двойки нет,
; тест `mov a/l / cpi ROWEND / jnz` остаётся раз на две пары (−32 такта на
; двойку, −10k тактов на кадр).
;
; Буфер A: базы E000/C000, буфер B: A000/8000 (base1 = base0 - 0x20).
; SP не перехватываем, прерывания не запрещаем.
; ================================================================
_fire_paint:
        push    bc
        push    de
        push    hl
        lxi     h,8                   ; аргумент на SP+8 после трёх push (см. call)
        dad     sp
        mov     a,m                   ; back
        ani     1
        ora     a
        mvi     a,0E0h                  ; буфер A
        jz      fps_base
        mvi     a,0A0h                  ; буфер B
fps_base:
        sta     _fr_base0
        sui     20h
        sta     _fr_base1

        lda     _fr_base0
        mov     d,a                     ; D = base0 + col (col=0)
        mvi     e,ROWBACK               ; E = верх строки точки y=0 (прогон вниз)
        lxi     h,_fire_buf + GUARD

fr_pair:
        mov     b,m                     ; левая точка пары (MOV r,M = 8T вместо 16T)
        inx     h
        mov     c,m                     ; правая точка пары
        inx     h
        ; смещение в _pt = idx*2 = 4*left + right, где left/right — ХРАНЁННЫЕ
        ; значения (уже умноженные на 2): 4*(2L) + 2R = 2*(4L+R) = idx*2.
        ; Экономия одного `add a` против сырых значений (см. VSCALE)
        mov     a,b                     ; left
        add     a                       ; 2*left
        add     a                       ; 4*left
        add     c                       ; 4*left + right = смещение пары
        push    h                       ; курсор fire_buf в стек, HL свободен
        lxi     h,_pt
        mov     l,a
        mov     b,m                     ; p0 — плоскость веса 1
        inx     h
        mov     c,m                     ; p1 — плоскость веса 2
        pop     h                       ; курсор обратно в HL

        ; плоскость веса 1: SCALE_Y одинаковых байта ВНИЗ от 4y+ROWBACK
        mov     a,b
        stax    d
        dcr     e
        stax    d
        dcr     e
        stax    d
        dcr     e
        stax    d                       ; E = 4y
        ; плоскость веса 2: база на 0x20 ниже (E0→C0, A0→80)
        mov     a,d
        sui     20h
        mov     d,a
        mov     a,c
        stax    d                       ; от 4y ВВЕРХ, и E сам возвращается
        inr     e                       ; на 4y+ROWBACK — возврата нет
        stax    d
        inr     e
        stax    d
        inr     e
        stax    d

        mov     a,d                     ; вернуть базу + следующий столбец
        adi     21h
        mov     d,a

fr_pair1:
        mov     b,m                     ; левая точка пары (MOV r,M = 8T вместо 16T)
        inx     h
        mov     c,m                     ; правая точка пары
        inx     h
        mov     a,b                     ; left
        add     a                       ; 2*left
        add     a                       ; 4*left
        add     c                       ; 4*left + right = смещение пары
        push    h                       ; курсор fire_buf в стек, HL свободен
        lxi     h,_pt
        mov     l,a
        mov     b,m                     ; p0 — плоскость веса 1
        inx     h
        mov     c,m                     ; p1 — плоскость веса 2
        pop     h                       ; курсор обратно в HL

        mov     a,b
        stax    d
        dcr     e
        stax    d
        dcr     e
        stax    d
        dcr     e
        stax    d                       ; E = 4y
        mov     a,d
        sui     20h
        mov     d,a
        mov     a,c
        stax    d
        inr     e
        stax    d
        inr     e
        stax    d
        inr     e
        stax    d

        mov     a,d                     ; вернуть базу + следующий столбец
        adi     21h
        mov     d,a
        mov     a,l
        cpi     ROWEND
        jnz     fr_pair

        ; ---- конец строки: курсор на следующую страницу, col=0, rowoff += SCALE_Y
        mvi     l,GUARD
        inr     h
        lda     _fr_base0
        mov     d,a
        mov     a,e
        adi     SCALE_Y
        mov     e,a
        cpi     ROWTOP
        jnz     fr_pair

        pop     hl                      ; разбор пролога: push hl/de/bc
        pop     de
        pop     bc
        pop     de              ; адрес возврата
        inx     sp
        inx     sp              ; съесть back
        push    de
        ret
