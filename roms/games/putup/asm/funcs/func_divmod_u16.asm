; Функция: func_divmod_u16
; Адрес: 0x0355
; Размер: 15 байт
; Описание: Извлечение десятичной цифры делением. DE = дополнительный код
;           делителя (отрицательное число), HL = делимое. MVI C,0FFh;
;           loc_0357: INR C; DAD D; JC loc_0357 — прибавляет делитель к HL пока
;           есть перенос, C = число итераций = цифра частного. Затем вычитает DE
;           (SUB E / SBB D) — восстанавливает остаток в DE. MOV A,C — цифра в A;
;           XCHG. Возвращает: A = цифра, DE = остаток.

func_divmod_u16:
    MVI C, 0FFh                 ; 0x0355
loc_0357:
    INR C                       ; 0x0357
    DAD D                       ; 0x0358
    JC loc_0357                 ; 0x0359
    MOV A, L                    ; 0x035C
    SUB E                       ; 0x035D
    MOV E, A                    ; 0x035E
    MOV A, H                    ; 0x035F
    SBB D                       ; 0x0360
    MOV D, A                    ; 0x0361
    MOV A, C                    ; 0x0362
    XCHG                        ; 0x0363
