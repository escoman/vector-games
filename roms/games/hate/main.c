/*
 * main.c — H.A.T.E. (Vortex Software, 1989) на Векторе-06Ц.
 *
 * Этап 1: заставка, мелодия и «PRESS ANY KEY WHEN READY».
 * Этап 2: рельеф меню в двойном буфере — жёлтый ландшафт за пунктами меню
 * (сами пункты — следующий шаг).
 *
 * Старт (заставка, без dblbuf — TZ §3.5):
 *   1) чёрная палитра — экран гаснет, мусор ОЗУ не виден;
 *   2) режим 256x256, 16 цветов — ОБЫЧНЫЙ режим Вектора;
 *   3) распаковка 32 КБ плоскостей в 0x8000 (ZX0, 3.9 КБ в ROM);
 *   4) надпись «PRESS ANY KEY WHEN READY» в чёрной зоне под картинкой;
 *   5) палитра заставки — восемь ярких цветов ZX (картинка проявляется);
 *   6) мелодия целиком, затем ожидание любой клавиши (include/beep.asm).
 *
 * Меню (этап 2): экран гаснет, инициализируется двойной буфер с 4-цветной
 * палитрой рельефа, рельеф рисуется в буфер A (include/render.asm) и
 * копируется в B — картинка в обоих буферах одна и та же, поэтому кадровый
 * цикл пока только свапает палитры-маски. Пункты меню лягут в back-буфер
 * следующим этапом: тогда свап и станет перерисовкой без мигания.
 *
 * Картинка ZX (256x192) прижата к ВЕРХНЕМУ краю экрана, как на Спектруме:
 * нижние 64 строки Вектора (в образе они нулевые) остаются чёрными — туда
 * ложится надпись, а в меню — панель.
 */

#include "v06.h"
#include "title.inc"
#include "sfx_hate.h"

/* Примитивы вывода из include/render.asm: рельеф меню в две плоскости
 * буфера A. Параметров нет — потоки указателей лежат в include/terrain.inc. */
extern void terrain_draw(void);

/* Палитра рельефа — из include/terrain.inc (в asm это terrain_pal4 и его
 * C-алиас _terrain_pal4): слот = логический цвет. Порядок слотов задан CMAP
 * в tools/gen_terrain.py, менять его там и здесь одновременно. */
extern const unsigned char terrain_pal4[4];

/* Кадровое прерывание: только палитра dblbuf (TZ §7 — первой, до звука).
 * Сама функция легковесна: при pal_dirty = 0 это чтение байта и ret. */
static void hate_frame(void)
{
    gfx_dblbuf_isr();
}

/* Слоты 0..7 — восемь ярких цветов ZX по номерам чернил, ровно те, что
 * раскладывает по плоскостям tools/gen_title.py (номер чернила = номер
 * цвета). Бит 3 цвета (плоскость 0x8000) в образе картинки нулевой,
 * поэтому слоты 8..15 картинкой не заняты: слот 8 отдан серому тексту
 * (R=4 G=4 B=2 — в эмуляторе 128,128,128, ровный серый). */
static const unsigned char title_palette[16] = {
    V06_RGB(0, 0, 0),       /* 0: чёрный    — фон, paper ZX            */
    V06_RGB(0, 0, 3),       /* 1: синий                                */
    V06_RGB(7, 0, 0),       /* 2: красный   — марка двигателя          */
    V06_RGB(7, 0, 3),       /* 3: пурпурный                            */
    V06_RGB(0, 7, 0),       /* 4: зелёный   — решётки, рельеф          */
    V06_RGB(0, 7, 3),       /* 5: голубой   — подводная лодка, плашка  */
    V06_RGB(7, 7, 0),       /* 6: жёлтый    — танк                     */
    V06_RGB(7, 7, 3),       /* 7: белый     — HATE, корабль, рамка     */
    V06_RGB(4, 4, 2),       /* 8: серый     — текст под картинкой      */
    V06_RGB(0, 0, 0), V06_RGB(0, 0, 0), V06_RGB(0, 0, 0),
    V06_RGB(0, 0, 0), V06_RGB(0, 0, 0), V06_RGB(0, 0, 0), V06_RGB(0, 0, 0),
};

#define TEXT_GRAY  8            /* номер цвета = бит 3 = плоскость 0x8000 */

/* Надпись в чёрной зоне: x — НОМЕР БАЙТОВОЙ КОЛОНКИ VRAM (0..31),
 * y — строка в пикселях. 24 знака * 8 = 192 пикселя: колонки 4..27,
 * поля по 32 пикселя с обеих сторон; по вертикали — середина полосы
 * 192..255. */
static const char title_hint[] = "PRESS ANY KEY WHEN READY";
#define HINT_X  4
#define HINT_Y  220

#define FADE_HOLD  2            /* кадров на шаг фейда появления (mario-dbl) */

int main(void)
{
    gfx_set_black_palette();        /* экран чёрный: распаковка не видна */
    gfx_set_mode(GFX_MODE_256_16);  /* 256x256, все четыре плоскости    */

    /* 32 КБ плоскостей одним потоком: [вес 8][вес 4][вес 2][вес 1] по
     * адресам 0x8000/0xA000/0xC000/0xE000 (см. include/title.inc). */
    zx0_decompress(title_zx0, V06_VRAM);

    /* Текст — до включения палитры: к кадру появления картинки он уже на
     * месте, «дописывания» на глазах нет. Шрифт HATE — include/font.asm
     * (pr.asm собирается с -Ca-DFONT_EXTERNAL). */
    gfx_print(HINT_X, HINT_Y, title_hint, TEXT_GRAY);

    gfx_set_palette(title_palette);

    /* Мелодия целиком + ожидание любой клавиши. Возвращается, когда
     * клавиша нажата и отпущена, — это вход в меню. */
    sfx_title_play();

    /* --- Меню: рельеф в двойном буфере -------------------------------- */
    /* Палитра гасится ДО рисования: рельеф собирается вживую (0.14 с), и
     * при старой палитре на экране был бы виден процесс сборки. */
    gfx_set_black_palette();
    gfx_dblbuf_init(terrain_pal4);  /* палитры-маски буферов A и B      */
    gfx_dblbuf_set_planes(0x03);    /* библиотечный вывод — только в A  */
    terrain_draw();                 /* рельеф: плоскости 0xE000 и 0xC000 */
    gfx_dblbuf_copy_ab();           /* тот же рельеф в буфер B          */

    /* Плавное появление: fade проявляет палитру переднего буфера (A).
     * Кадровый обработчик назначаем после — палитрой во время фейда
     * владеет gfx_set_palette внутри gfx_fade_in. */
    gfx_fade_in(gfx_dblbuf_front_pal(), FADE_HOLD);
    frame_handler = hate_frame;

    for (;;) {
        /* Кадр: запросить свап палитр-масок и спать до ближайшего VBlank,
         * где ISR его и применит. Обе пары плоскостей держат один и тот же
         * рельеф, так что картинка не меняется — цикл готов принять
         * пункты меню в back-буфер. */
        gfx_dblbuf_present();
        v06_wait_frame();
    }

    return 0;
}
