/*
 * heap.c — bump-аллокатор свободной ОЗУ для Вектора-06Ц.
 *
 * Образ ROM загружается в ОЗУ с 0x0100 и занимает [0x0100, __tail):
 * линкер ставит __tail за последней размещённой секцией, и в него
 * попадает и BSS — статический буфер в OЗУ стоит ровно столько же
 * байт в файле образа, сколько он весит по адресу. Поэтому крупные
 * буферы, нужные только во время исполнения, выгоднее брать из кучи:
 * она стартует от __tail и места в образе не занимает.
 *
 * Куча растёт вверх от __tail до heap_top; по умолчанию потолок —
 * 0x8000, то есть куча не трогает видеопамять и безопасна в любом
 * режиме. Поднять его может проект, который заведомо не пишет в верхние
 * плоскости: в GFX_MODE_256_2 отображается и заполняется одна плоскость
 * 0xE000 (маска 0x01), и 0x8000..0xDFFF в нём — обычная ОЗУ.
 * Потолок присваивают до первой выдачи: опускать его ниже вершины
 * кучи поздно — выделенное окажется под картинкой.
 *
 * Начальный загрузчик во время загрузки рисует свою таблицу в
 * плоскости 0xC000, поэтому ОБРАЗ ROM может расти только до 0xBFFF
 * (48 КБ вместо обычных 32 КБ), а 0xC000..0xDFFF становится доступно
 * уже после старта программы — то есть только куче.
 *
 * Освобождения нет: память выдаётся один раз и до перезапуска.
 * Менеджер нужен, чтобы снять буферы с BSS, а не чтобы жить в
 * фрагментированной куче.
 */

#include "v06.h"

/* Конец образа — символ линкера __tail (C-имя _tail: sccz80 добавляет
 * префикс '_'). Всё, что выше, образом не занято. */
extern unsigned char _tail;

unsigned int heap_top = HEAP_TOP_DEFAULT;   /* потолок кучи            */
static unsigned int heap_ptr;               /* вершина; 0 = не начата  */

/* Адрес следующей выдачи. До первого heap_alloc вершина не известна —
 * берём конец образа. Ленивая инициализация сознательная: забыть
 * вызвать heap_init означает получить кучу в нуле и убить программу,
 * а здесь промах невозможен. */
static unsigned int heap_head(void)
{
    return heap_ptr ? heap_ptr : (unsigned int)&_tail;
}

/* Выдать size байт, или 0 если куча кончилась.
 * Кончается она двояко: запрос больше остатка — либо образ дорос до
 * потолка и выше. Второй случай реален: потолок по умолчанию 0x8000, а
 * образ в одноплоскостном режиме может дорасти до 0xBFFF (ROM_MAX в
 * finally.mk). Поэтому проверяем вершину отдельно — иначе разница
 * heap_top - p переполнится и пропустит любой запрос в видеопамять. */
void *heap_alloc(unsigned int size)
{
    unsigned int p = heap_head();
    unsigned int rest = heap_top - p;

    if (p >= heap_top) return (void *)0;

    /* Сравнение с разницей, а не p + size с потолком: сумма двух
     * 16-битных значений переполнилась бы и пропустила запрос наружу. */
    if (size > rest) return (void *)0;

    heap_ptr = p + size;
    return (void *)p;
}

unsigned int heap_avail(void)
{
    unsigned int p = heap_head();

    /* Ноль, а не переполнившаяся разница — там был бы огромный
     * остаток при пустой (или уже видеопамятной) куче. */
    if (p >= heap_top) return 0;

    return heap_top - p;
}
